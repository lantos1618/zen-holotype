def kind(node):
    return type(node).__name__


def f(node, name, default=None):
    return getattr(node, name, default)


def _diag(span, message, notes=()):
    Diag = getattr(zast, "Diag", None)
    if Diag is None:  # pragma: no cover - ast.py always has it
        return (span, message, tuple(notes))
