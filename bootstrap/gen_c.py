def generate(program, sema=None, root=None, sources=None):
    """The module graph -> (C source text, diagnostics).

    Deterministic: called twice with equal inputs it returns equal strings, and
    it holds no state between calls.
    """
    emitter = Emitter(program, sema=sema, root=root, sources=sources)
    text = emitter.emit()
    return text, tuple(emitter.diags)


# `emit` reads better at a call site that already has a program in hand.
