def changed_files(rev: str) -> tuple[dict[str, str], bool] | None:
    """({path: status}, is_merge) for one commit, via plumbing interfaces."""
    out = subprocess.run(
        ["git", "-C", str(ROOT), "diff-tree", "-r", "--name-status",
         "--root", "--no-commit-id", rev],
        capture_output=True, text=True)
    if out.returncode != 0:
        print(f"scope: could not read {rev}: {out.stderr.strip()}",
              file=sys.stderr)
        return None
    changes: dict[str, str] = {}
    for ln in out.stdout.splitlines():
        if not ln.strip():
            continue
        status, path = ln.split("\t", 1)
        if "\t" in path:  # R100 old new -- the NEW name is what landed
            path = path.split("\t")[-1]
        changes[path] = status[0]
    heads = subprocess.run(
        ["git", "-C", str(ROOT), "rev-list", "--parents", "-n", "1", rev],
        capture_output=True, text=True)
    is_merge = heads.returncode == 0 and len(heads.stdout.split()) > 2
    return changes, is_merge


def commit_subject(rev: str) -> str | None:
    out = subprocess.run(
        ["git", "-C", str(ROOT), "log", "-1", "--format=%s", rev],
        capture_output=True, text=True)
    if out.returncode != 0:
        return None
    return out.stdout.strip()


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        return self_test()

    revs = [a for a in argv if not a.startswith("-")]
    if not revs:
        revs = ["HEAD"]

    audited = 0
    failures = 0
    for rev in revs:
        subject = commit_subject(rev)
        got = changed_files(rev)
        if subject is None or got is None:
            print(f"scope: could not read {rev}; checked nothing",
                  file=sys.stderr)
            return 2
        changes, is_merge = got
        if is_merge:
            print(f"{rev} MERGE {subject!r} skipped -- parents state the scopes")
            continue
        audited += 1

        found = violations_for(subject, changes)
        print(f"{rev} {'OK' if not found else 'VIOLATION'} {subject!r}")
        for f in found[:12]:
            print(f"    {f}")
        if len(found) > 12:
            print(f"    .. and {len(found) - 12} more")
        failures += bool(found)

    if failures:
        print(f"\nscope: {failures} of {audited} audited commit(s) break the"
              f" scope rules (issue #765).")
        print("  1. a commit touching src/ outside its stated scope is"
              " rejected at review:")
        print("       state the area in the subject -- `<area>, <area>:"
              " <fact>`.")
        print("  2. a mechanical sweep (`style:`/`fmt:`/`ufcs:`) lands alone:"
              " no new file")
        print("       under src/, no `.expected`/`.count` change -- that is a"
              " feature and")
        print("       gets its own commit and its own sentence.")
        return 1
    print(f"\nscope: {audited} commit(s) audited; every src/ touch is inside"
          f" its subject's stated scope")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
