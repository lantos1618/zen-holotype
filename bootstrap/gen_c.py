"""gen_c.py -- the deterministic C backend of the Zen bootstrapper.

`bootstrap/CONTRACT.md` is the frozen interface; this file consumes the AST
described there and emits C99.  It imports `ast.py`, `modules.py` and
`sema.py` and never `cst.py`.

-------------------------------------------------------------------- determinism

Binding, from CONTRACT.md and `tests/determinism/README.md`.  Every rule below
is a property of the code rather than a thing to look for later:

* every emitted list is sorted by its mangled C name, or produced by a walk
  over a source-ordered tuple.  A dict is a lookup structure here, never an
  emission order; `sorted()` is called at every emission site.
* no pointer, address, `id()`, timestamp, environment variable, locale or
  absolute path reaches the output.  Positions are literal strings taken from
  the AST, so `__FILE__` is never emitted either.
* temporaries are numbered per function by the deterministic traversal that
  emits them, and the counter is reset at every function.
* a monomorphised instance's name is a pure function of the type: it is the
  type's own encoding (`tcode` below), so two instantiations of the same type
  from different modules produce one name regardless of which was seen first,
  and no counter takes part.
* nothing is emitted from a `set`; sets are converted with `sorted()` at use.

-------------------------------------------------------------------- mangling

Two prefixes, and every identifier in the output is under one of them:

    zu_   derived from a user name
    zg_   generated by the compiler (temporaries, helpers, the runtime)

Neither starts with an underscore, so neither is reserved to the C
implementation by C11 7.1.3, and `zu_` cannot produce `zg_`, so the reserved
prefix is unreachable by any mangled user name.  Because *every* user
identifier is mangled, no C keyword, no standard-header macro and no reserved
identifier can ever be emitted from user source -- which is decision 4 of
PLAN.md 0.4 handled as an identifier *class* rather than as a keyword list.
The single exception is the C entry point `main`, which the C standard fixes.

Components are length-prefixed, so concatenation is unambiguous:

    comp  := <decimal byte length> <bytes>
    list  := <decimal count> "_" comp*        (a count always ends with "_",
                                               a component never does)

A length is read as the maximal digit run; a Zen identifier can never start
with a digit, so the parse is unique.  `alpha` + `beta_gamma` encodes as
`2_5alpha10beta_gamma` and `alpha_beta` + `gamma` as `2_10alpha_beta5gamma`:
the collision that naive `_` joining has, closed by construction.

Symbols, by site (the seven of PLAN.md 0.4 decision 3, plus module values):

    type / instance   zu_ t <path> [I <args>]
    function          zu_ f <path> [O <param types>] [I <type args>]
    enum constant     zu_ e <path-of-enum + variant>
    struct member     zu_ m <comp>
    local / parameter zu_ l <comp> ["_" <n>]
    module value      zu_ v <path>
    struct tag        the same string as the typedef (C tags are a separate
                      namespace, so `typedef struct X X;` is legal and keeps
                      the emitted C readable)
    label             zg_ ... (generated, never user-derived)

Type arguments render through `tcode`, a pure function of the type:

    b <comp>                  primitive            i32   -> b3i32
    t <path> [I <n> "_" ...]  nominal type         Box<i32> in gamma ->
                                                   t2_5gamma3BoxI1_b3i32
    p <tcode>                 Ptr<T>
    a <count> "_" <tcode>     [T, N]
    f <ret> <n> "_" <tcode>*  function type
    u <n> "_" <tcode>*        union, members sorted so `A|B` == `B|A`
    z                         ()
    q                         unresolved (a diagnostic is raised with it)

The tag letters are lowercase and `I` is uppercase, so no tag can be mistaken
for the start of a component; the encoding is injective, so distinct types
never share a name and a user-written `Pair_i32_i32` can never collide with
`Pair<i32, i32>`.

-------------------------------------------------------------------- the failure model

DESIGN.md: signed overflow is undefined behaviour in C, so this file never
emits `a + b` and inspects the result.  Every checked operation goes through a
`zg_` helper that tests *before* the operation, using `__builtin_*_overflow`
where the compiler has it and an explicit range test where it does not.  A
trap prints `file:line:col: trap: <what>` to stderr and exits 134; the
position is the operator token, resolved by `OperatorSpans` below.

-------------------------------------------------------------------- what sema owns

gen_c asks `sema` for what it cannot know, and degrades to its own resolution
when a query is absent, so that this file compiles against a partial sema:

    sema.type_of(expr)            -> a Type node, or None
    sema.resolve(expr)            -> the declaration a Path/Member names
    sema.defs_of(name, module)    -> declarations bound to a name

All three are optional.  Anything gen_c cannot resolve becomes a `Diag`
(collected, never raised) rather than a guess.
"""

