def prim(name):
    return ("prim", name)


def tcode(t) -> str:
    """The name of a type.  A pure function of the type, and injective."""
    if t is None:
        return "q"
    k = t[0]
    if k == "prim":
        return "b" + comp(t[1])
    if k == "named":
        return tcode_named(t[1], t[2])
    if k == "ptr":
        return "p" + tcode(t[1])
    if k == "array":
        return "a%d_%s" % (t[1], tcode(t[2]))
    if k == "fn":
        return "f" + tcode(t[1]) + clist([tcode(p) for p in t[2]])
    if k == "union":
        return "u" + clist(sorted(tcode(m) for m in t[1]))
    if k == "unit":
        return "z"
    return "q"


def is_int(t):
    return t is not None and t[0] == "prim" and t[1] in INT_VALUES


def int_info(t):
    return INT_VALUES[t[1]]


def ty_label(t):
    """A type as a diagnostic names it: the source spelling, not the C one.
    "no method `get` on `Vec<Found>`" is only useful if the reader can find
    `Vec<Found>` in what they wrote."""
    if t is None or t == UNKNOWN:
        return "this value"
    if t[0] == "prim":
        return t[1]
    if t[0] == "unit":
        return "()"
    if t[0] == "ptr":
        return "Ptr<%s>" % ty_label(t[1])
    if t[0] == "array":
        return "[%s, %s]" % (ty_label(t[2]), t[1])
    if t[0] == "union":
        return " | ".join(ty_label(m) for m in t[1])
    if t[0] == "named":
        head = t[1][-1] if t[1] else "?"
        return "%s<%s>" % (head, ", ".join(ty_label(a) for a in t[2])) if t[2] else head
    return t[0]


def union_of(members):
    """Flatten and normalise a union; the member order is not observable."""
    flat = []
    for m in members:
        if m[0] == "union":
            flat.extend(m[1])
        else:
            flat.append(m)
    uniq = []
    for m in flat:
        if m not in uniq:
            uniq.append(m)
    if len(uniq) == 1:
        return uniq[0]
    return ("union", tuple(sorted(uniq, key=tcode)))


# ---------------------------------------------------------------------------
# source text, for the one thing the AST cannot answer
#
# A trap's position is the OPERATOR token (DESIGN.md, and every .stderr file in
# tests/corpus/traps/).  `Binary` and `Index` carry no operator span, so the
# operator is located by scanning the gap between the two operand spans,
# skipping whitespace and comments.  That is a function of the program text and
# therefore deterministic; when the text is unavailable the node's own span is
# used, which is the same file and line and at worst the wrong column.
# ---------------------------------------------------------------------------


class SourceMap:
    def __init__(self, root=None, sources=None):
        self.root = root
        self.given = dict(sources or {})
        self.cache = {}

    def _lines(self, relpath):
        if relpath in self.cache:
            return self.cache[relpath]
        text = self.given.get(relpath)
        if text is None and self.root is not None:
            try:
                with open(os.path.join(self.root, relpath), "rb") as fh:
                    text = fh.read().decode("utf-8", "replace")
            except OSError:
                text = None
        lines = text.splitlines(True) if text is not None else None
        self.cache[relpath] = lines
        return lines

    def gap(self, relpath, start, end):
        """The text between two (line, col) points, plus its start position."""
        lines = self._lines(relpath)
        if not lines:
            return None
        sl, sc = start
        el, ec = end
        if sl < 1 or el > len(lines) or (sl == el and ec < sc):
            return None
        out = []
        pos = []
        for ln in range(sl, min(el, len(lines)) + 1):
            raw = lines[ln - 1].encode("utf-8")
            lo = sc - 1 if ln == sl else 0
            hi = ec - 1 if ln == el else len(raw)
            lo = max(0, min(lo, len(raw)))
            hi = max(lo, min(hi, len(raw)))
            for i in range(lo, hi):
                out.append(raw[i : i + 1])
                pos.append((ln, i + 1))
        return b"".join(out), pos


def _skip_trivia(text, pos):
    """Index of the first byte of the first real token in `text`."""
    i = 0
    n = len(text)
    while i < n:
        c = text[i : i + 1]
        if c in b" \t\r\n":
            i += 1
            continue
        if text[i : i + 2] == b"//":
            j = text.find(b"\n", i)
            i = n if j < 0 else j + 1
            continue
        if text[i : i + 2] == b"/*":
            j = text.find(b"*/", i + 2)
            i = n if j < 0 else j + 2
            continue
        return i
    return None


class Positions:
    """`file:line:col` for a trap, with the operator token located."""

    def __init__(self, sources: SourceMap, root=None):
        self.sources = sources
        self.root = root

    def relfile(self, span):
        path = f(span, "file", "") or ""
        path = str(path).replace("\\", "/")
        if os.path.isabs(path) and self.root:
            try:
                path = os.path.relpath(path, self.root).replace("\\", "/")
            except ValueError:  # pragma: no cover - different drives
                path = os.path.basename(path)
        return path

    def of(self, node):
        span = f(node, "span")
        if span is None:
            return ("", 0, 0)
        start = f(span, "start", (0, 0)) or (0, 0)
        return (self.relfile(span), start[0], start[1])

    def operator(self, node, left, right):
        """The operator token between two operands, for a trap position."""
        explicit = f(node, "op_span")
        if explicit is not None:
            start = f(explicit, "start", (0, 0))
            return (self.relfile(explicit), start[0], start[1])
        lspan = f(left, "span")
        rspan = f(right, "span")
        span = f(node, "span")
        if lspan is not None and rspan is not None and span is not None:
            got = self.sources.gap(
                self.relfile(span),
                f(lspan, "end", (0, 0)),
                f(rspan, "start", (0, 0)),
            )
            if got:
                text, pos = got
                at = _skip_trivia(text, pos)
                if at is not None and at < len(pos):
                    line, col = pos[at]
                    return (self.relfile(span), line, col)
        return self.of(node)


