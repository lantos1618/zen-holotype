def modules_of(program):
    """Whatever modules.py hands back -> ((path components, ast.Module), ..).

    Sorted by the module's identity, never by discovery order: `modules.py`
    sorts its enumeration and this sorts again, because check 3 of
    `tests/determinism/check.sh` shuffles the input order on purpose.
    """
    mods = program
    got = getattr(program, "modules", None)
    if got is not None:
        mods = got
    if isinstance(mods, dict):
        mods = list(mods.values())
    try:
        mods = list(mods)
    except TypeError:
        mods = [mods]

    out = []
    for m in mods:
        dotted = f(m, "dotted", None)  # modules.ModuleInfo
        if dotted is not None:
            node = f(m, "node")
            if node is None:
                continue  # the file did not parse; modules.py already said so
            out.append((tuple(str(dotted).split(".")), node))
            continue
        if kind(m) == "Module" or f(m, "decls") is not None:
            out.append((module_parts(m), m))
    return tuple(sorted(out, key=lambda pair: pair[0]))


def module_parts(mod):
    """A module's mangling path: its dotted name, or its file path's stem."""
    path = str(f(mod, "path", "") or "")
    if path:
        stem = path[:-4] if path.endswith(".zen") else path
        stem = stem.replace(os.sep, ".").replace("/", ".")
        if stem:
            return tuple(stem.split("."))
    name = f(mod, "name", None)
    if name:
        return tuple(str(name).split("."))
    return ("module",)


class Decl:
    """One declaration, with everything gen_c needs to name and emit it."""

    __slots__ = ("parts", "node", "dkind", "name", "tparams", "module", "owner",
                 "otparams")

    def __init__(self, parts, node, dkind, name, tparams=(), owner=None, module="",
                 otparams=()):
        # A method of `Vec<T>` is generic in T whether or not it declares any
        # type parameters of its own, so the owner's come FIRST and an
        # instantiation is (receiver args + call args).
        self.otparams = tuple(otparams)
        tparams = self.otparams + tuple(tparams)
        self.parts = tuple(parts)
        self.node = node
        self.dkind = dkind  # "type" | "fn" | "value"
        self.name = name
        self.tparams = tuple(tparams)
        self.owner = owner
        self.module = module

    @property
    def key(self):
        return (self.module, self.owner or "", self.name)

    @property
    def scope_parts(self):
        """Where this declaration's body is written, for name lookup and for
        `@Self`.  For an impl entry that is the TARGET type, not the trait:
        `Arena.impl(Alloc, { raw = (self: @Self, ..) })` has `@Self` = Arena,
        and reading `self.state` off the trait would find nothing."""
        base = tuple(self.module.split(".")) if self.module else ()
        return base + ((self.owner,) if self.owner else ())


def _tparam_names(node):
    return tuple(str(f(tp, "name", "T")) for tp in (f(node, "tparams", ()) or ()))


def _is_variadic(param):
    """`args: ...` — the zero-or-more tail (ast.py spells it `Named("...")`)."""
    ty = f(param, "ty")
    return ty is not None and f(ty, "name", None) == "..."


def _bare_name(name):
    """A type's name without its arguments: `Range<T>` is an impl of `Range`."""
    return str(name or "").split("<", 1)[0].strip()


def _type_args(name):
    """The arguments of a type written as text: `Range<T>` -> ("T",)."""
    text = str(name or "")
    if "<" not in text or not text.rstrip().endswith(">"):
        return ()
    inner = text[text.index("<") + 1:text.rstrip().rindex(">")]
    return tuple(part.strip() for part in inner.split(",") if part.strip())


def _block_value(body):
    """What a block evaluates to, for a peek.  A `Block` lowered with no
    expected type is a statement and answers `()`, so asking it what a body
    RETURNS has to reach the value expression itself."""
    if body is None or kind(body) != "Block":
        return body
    value = f(body, "value")
    if value is not None:
        return value
    stmts = list(f(body, "stmts", ()) or ())
    if stmts and kind(stmts[-1]) == "ExprStmt":
        return f(stmts[-1], "expr")
    return body


def _bound_apps(tp):
    """A type parameter's bounds, as (name, argument names) -- `<S: Shape<T>>`
    is where a `T` that appears nowhere else is named."""
    out = []

    def walk(t):
        if t is None:
            return
        if kind(t) == "Union":
            for m in f(t, "members", ()) or ():
                walk(m)
            return
        nm = f(t, "name", None)
        if isinstance(nm, str):
            out.append((nm, tuple(f(a, "name", None)
                                  for a in (f(t, "args", ()) or ()))))

    walk(f(tp, "bound"))
    return tuple(out)


def _bound_names(node):
    """The names a declaration's type parameters are bounded by.

    `<K: Eq + Hash>` arrives as a Union (ast.py's stopgap for an
    intersection), so a union bound is every bound and not a choice.
    """
    out = []

    def walk(t):
        if t is None:
            return
        if kind(t) == "Union":
            for m in f(t, "members", ()) or ():
                walk(m)
            return
        nm = f(t, "name", None)
        if isinstance(nm, str):
            out.append(nm)

    for tp in f(node, "tparams", ()) or ():
        walk(f(tp, "bound"))
    return tuple(out)


def _is_pure_default(node):
    """Can this expression be written twice without anyone being able to tell?

    A default is emitted at EVERY construction that omitted the field, so it
    must name no function and read no frame.  A literal can; so can an
    operator over things that can, and so can a construction of them -- a
    compound literal names no function and reads nothing.  A call to anything
    else cannot, and neither can a bare name, because a name is a local whose
    frame the use site is not in.

    `src/gen/gen_c/gen_c_const.zen:is_pure_value` is the same predicate on the
    other side, and it is the same gate a constant read is held to.
    """
    k = kind(node)
    if k in ("Literal", "Unit"):
        return True
    if k == "Unary":
        return _is_pure_default(f(node, "operand"))
    if k == "Binary":
        return _is_pure_default(f(node, "lhs")) and _is_pure_default(f(node, "rhs"))
    if k == "Member":
        return True  # `Shape.Unit`, `i32.MAX`: a value of a DECLARATION
    if k == "Call":
        return all(
            _is_pure_default(f(a, "value") if kind(a) == "Arg" else a)
            for a in f(node, "args", ()) or ()
        )
    return False


def _field_defaults(node):
    """`name :: T = value` -- the value a field takes when nobody supplies one.

    DESIGN.md: "`= default` makes a field optional at construction."  A field
    the call omitted is therefore not absent, it is the value its declaration
    wrote -- and this walk is the only thing that knows that, because the
    initialiser list is otherwise built out of the ARGUMENTS alone.  Nothing
    in the tree could notice it was missing: every default in std is already
    a zero, which is exactly what C's `{0}` was giving instead.

    A default that is not a pure value is left to that zeroing.  `Vec`'s
    `data :: Ptr<T> = null_ptr<T>()` is the only shape in the tree that
    reaches it, and a null pointer is what zeroing gives.
    """
    out = {}
    for member in f(node, "fields", ()) or ():
        if _is_fn_field(member):
            continue
        value = f(member, "default")
        if value is None:
            value = f(member, "value")
        if value is not None and _is_pure_default(value):
            out[str(f(member, "name", ""))] = value
    return out


def _is_fn_field(node):
    """A struct member whose value is a function: DESIGN.md's method form.

    There is one declaration form, so a method arrives three ways: as a

    There is one declaration form, so a method arrives three ways: as a
    `Function` in the struct's `fields`, as a `Field` whose type is a
    `FnType` (the bodyless `= sig` / `::= sig` forms), or as a `Field` whose
    default is a `Lambda`.  All three are the same thing.
    """
    if kind(node) in ("Function", "Lambda"):
        return True
    ty = f(node, "ty")
    if ty is not None and kind(ty) == "FnType":
        return True
    for attr in ("default", "value"):
        v = f(node, attr)
        if v is not None and kind(v) in ("Lambda", "Function"):
            return True
    return False


def _is_assoc_fn(e, decl):
    """A struct-body member that takes no receiver: an ASSOCIATED function.

    "A struct body may bind a name to a value, read as `Type.NAME`", and a
    function is a value -- so `Duration.seconds(2)` is a member read through
    its type, not a method with `Duration` shoved into the receiver slot.

    A constructor is why this has to exist: it takes a number and returns the
    type, so travelling with its first parameter would put `.seconds()` on
    every `u64` in every program, `u64` being a prelude name. The first
    parameter is the whole test -- `@Self`, or the owner spelled out, means a
    method; anything else, including no parameter at all, means this.
    """
    fnode = e.fn_node(decl.node)
    if fnode is None:
        return False
    params = e.params_of(fnode)
    if not params:
        return True
    ty = f(params[0], "ty")
    if ty is None or kind(ty) != "Named":
        return True
    return str(f(ty, "name", "")) not in ("@Self", decl.owner)


