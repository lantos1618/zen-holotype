def self_test() -> int:
    bad = 0
    for subject, changes, expect_bad, why in CASES:
        got = violations_for(subject, changes)
        ok = bool(got) == expect_bad
        mark = "ok:   " if ok else "FAIL: "
        print(f"self-test {mark}{subject!r}")
        if not ok:
            print(f"    {why}")
            verdict = f"{len(got)} finding(s): {got}" if got else "PASS"
            print(f"    expected {'VIOLATION' if expect_bad else 'PASS'},"
                  f" got {verdict}")
            bad += 1
    n = len(CASES)
    if bad:
        print(f"\nscope: self-test {bad}/{n} case(s) disagree")
        return 1
    print(f"\nscope: self-test {n}/{n} cases agree")
    return 0


