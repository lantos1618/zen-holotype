#!/usr/bin/env python3
"""A commit's subject names its scope, and `src/` obeys it.

Issue #765: af2f9af7 landed three features -- a new LSP code-action provider,
the @meta M0/M1 interception, and a module-resolution change -- inside 113
files under a subject that reads `style:`. Nothing in the message says any of
them happened. A reviewer reading `style:` does not go looking for a new
type-checker interception or a change to module resolution, and git bisect on
any of the three lands on a commit labelled as a formatting sweep.

The rules this gate enforces are the ones the issue asks for and the owner
adopted in the thread:

  1. a commit touching src/ outside its stated scope is rejected at review;
  2. a mechanical sweep lands ALONE -- no feature, no diagnostic change,
     no new file under src/.

THE STATED SCOPE IS THE SUBJECT PREFIX. This repo has written subjects as
`<area>: <fact>` for its whole history (`lex:`, `gen_c:`, `lsp:`, `sema:`),
and multi-area work as a comma list (`gen, lsp:`, `std.text, lsp:`). So the
mechanical form of "outside its stated scope" is decidable:

    every file under src/ that a commit touches must resolve to an area
    named in the subject's prefix.

An area resolves to a path three ways, each taken from the log rather than
invented: a dotted name joins segments (`std.text` is exactly src/std/text/),
a bare name matches any ONE path segment (`lex:` covered src/std/lex/ in
d6882f11; `gen_c:` covers src/gen/gen_c/ without dragging in src/gen/gen.zen),
and a bare name matches the file's own stem (`zen_build.zen` under `zen:`,
because a module's subject file IS the module).

SWEEPS ARE DIFFERENT, and pretending otherwise would have flagged half the
log. `style:`, `fmt:` and `ufcs:` commits reach across every area on purpose
-- that is what a sweep is -- and rule 2 says that is legal IF the sweep lands
alone. Alone is decidable too: a sweep may MODIFY src/, but it may not ADD a
file under src/ (a new file is a feature landing, rule 3's own sentence) and
it may not add or change any `.expected` / `.count` file (the corpus speaks
in those; a diff in them is a behaviour or diagnostic change). Applied to the
history: 3a976841 and 35efd2ee and 90921493 were sweeps and landed alone --
they pass. af2f9af7 declared `style:` and added src/lsp/lsp_action.zen and
changed nine `.expected` files -- it fails both ways at once, which is the
issue's point made mechanical.

A subject with NO `<areas>:` prefix (`fix-c06`, `wip: ...`, a bare sentence)
states no scope, so any src/ touch is outside it. That refusal IS rule 1: a
commit that cannot say where it reaches must not reach. Merge commits are
skipped -- their parents state the scopes, and a diff against both parents
double-counts everything the branches shared.

WHY THE SUBJECT AND NOT A TRAILER. A trailer (`Scope:`) duplicates a fact the
subject already carries, and two copies of a fact is one stale fact waiting
to happen -- the same argument STYLE.md makes about restating rules. It also
lets the message and the trailer disagree, which is worse than either alone.

WHAT IS DELIBERATELY NOT CHECKED, because gating it would be guessing:
  - whether the subject's FACT is true of the files (judgement, review);
  - tests/, docs/, Makefile, ISSUES.md riding along. Every lane here commits
    its proof beside its change -- 1aab00ca adds four corpus files under
    `gen_c:`, d6882f11 adds must-fails and a gate under `lex:` -- so a rule
    that made tests need their own sentence would be violated by every good
    commit in the log. The owner's rule targets src/; only inside a SWEEP do
    expectation files count, because there they are the evidence of a hidden
    second landing.
  - seed/zen.c. It is a build artifact regenerated by `make seed`, which the
    Makefile runs `git add` on; five recent commits are nothing else. It
    carries no information about scope, so it is exempt everywhere.

EXIT CODES follow the house convention (STYLE.md): 0 pass, 1 violation found,
2 the harness could not run -- checked nothing, never counted as a pass.

SELF-TEST. `--self-test` runs the fixture table below and exits nonzero on
any disagreement. `make scope` runs it before the real audit, so the gate
cannot quietly rot: a parser change that starts misreading subjects fails
the target even when the tree itself is clean.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# THE BUILD ARTIFACT EXEMPTION. `make seed` regenerates seed/zen.c from the
# tree and `git add`s it; it is emitted bytes, not authored scope.
EXEMPT_PREFIXES = ("seed/",)

# THE MECHANICAL-SWEEP TAGS, as used in this repo's log. A commit under one
# of these prefixes DECLARES itself a sweep and gets rule 2 instead of rule
# 1: src/ may be rewritten anywhere, but the landing must be alone.
SWEEP_TAGS = {"style", "fmt", "format", "ufcs"}

# What a sweep may not bring with it: new code (rule 3 gives a new src/ file
# its own sentence) and expectation diffs (a diagnostic or behaviour change).
SWEEP_FORBIDDEN_SUFFIXES = (".expected", ".count")

SUBJECT_RE = re.compile(r"^(?P<areas>[A-Za-z0-9_., +\-]+?): (?P<fact>.+)$")


def parse_areas(subject: str) -> list[str] | None:
    """The areas a subject declares, or None when it declares none.

    None covers: no `<areas>:` shape at all, an empty area list, duplicate
    areas (`gen, gen:` scopes nothing coherent). Callers treat None as
    "nothing is scoped".
    """
    m = SUBJECT_RE.match(subject)
    if m is None:
        return None
    areas = [a.strip().lower() for a in m.group("areas").split(",")]
    if not all(areas) or len(areas) != len(set(areas)):
        return None
    return areas


def is_sweep(subject: str) -> bool:
    areas = parse_areas(subject)
    return areas is not None and len(areas) == 1 and areas[0] in SWEEP_TAGS


def area_matches(area: str, rel: str) -> bool:
    """Does one declared area cover one src/-relative path? See module doc."""
    parts = rel.split("/")
    dotted = area.split(".")
    if parts[: len(dotted)] == dotted and len(parts) > len(dotted):
        return True
    if area in parts[:-1]:  # any single directory segment
        return True
    return parts[-1][: -len(".zen")] == area  # the module's own stem


def scoped_out(subject: str, changes: dict[str, str]) -> list[str]:
    """src/ files this commit touches outside whatever its subject scopes."""
    areas = parse_areas(subject)
    out = []
    for p, _status in sorted(changes.items()):
        if not p.startswith("src/") or p.startswith(EXEMPT_PREFIXES):
            continue
        if areas is None or not any(area_matches(a, p[len("src/"):])
                                    for a in areas):
            out.append(p)
    return out


def sweep_contraband(changes: dict[str, str]) -> list[str]:
    """What rule 2 forbids a sweep to carry: new src/ files, expect diffs."""
    bad = []
    for p, status in sorted(changes.items()):
        if p.startswith(EXEMPT_PREFIXES):
            continue
        if p.startswith("src/") and status == "A":
            bad.append(f"{p} (added inside a sweep)")
        elif p.endswith(SWEEP_FORBIDDEN_SUFFIXES) and status in "AM":
            bad.append(f"{p} (expectation changed inside a sweep)")
    return bad


def violations_for(subject: str, changes: dict[str, str]) -> list[str]:
    if is_sweep(subject):
        return sweep_contraband(changes)
    return scoped_out(subject, changes)


