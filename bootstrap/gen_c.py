class Emitter:
    def __init__(self, program, sema=None, root=None, sources=None):
        self.program = program
        self.sema = sema
        self.root = root
        self.pos = Positions(SourceMap(root, sources), root)
        self.diags = []

        self.mods = modules_of(program)
        self.types = {}  # name -> ("struct"|"enum"|"array"|"union", payload)
        self.consts = {}  # enum constant -> value; one C enum for the program
        self.type_order = {}  # name -> deps (by-value)
        self.protos = {}  # cname -> prototype line
        self.bodies = {}  # cname -> body text
        self.helpers = set()  # generated arithmetic helpers actually used
        self.needs = set()  # generated runtime pieces actually used
        self.argv_vec_fields = ()

        self.decls = {}  # (module parts, name) -> [Decl]
        self.by_key = {}  # (module, owner, name) -> [Decl]
        self.by_name = {}  # name -> [Decl]  (module-agnostic fallback)
        self.impls = []    # (target, trait, trait args as written, target tparams)
        self.worklist = []
        self.done = set()
        self.instances = 0
        self.expanding = []  # constants being inlined, to catch a self-reference
        self._drops = {}   # type parts -> the Drop impl's `drop`, or None
        self._unions = {}  # enum parts -> is it a union of existing types?
        self._consumed = None  # names moved with `consume`, program-wide
        self._rets = {}    # id(fn node) -> its return type with `_` filled in
        self._scope_ty = None  # the `Scope` type, resolved once
        self.defer_envs = {}   # site number -> its capture struct's definition
        self.defer_sites = 0   # deferred closures lifted so far, for naming
        self._defer_cache = {}  # (body text, capture layout) -> (thunk, env)
        self.graph = program if getattr(program, "modules", None) and hasattr(
            program, "lookup"
        ) else None
        self._collect()

    # -- collection --------------------------------------------------------

    def _add_decl(self, decl):
        self.decls.setdefault((decl.scope_parts, decl.name), []).append(decl)
        self.by_key.setdefault(decl.key, []).append(decl)
        self.by_name.setdefault(decl.name, []).append(decl)

    def _collect(self):
        # Impls last: an impl entry is generic in the TARGET's parameters
        # (`Vec.impl(Range<T>, ..)` writes `Res<T>` for Vec's own T), so the
        # target has to be on the table before the entry is named.
        impls = []
        for base, mod in self.mods:
            for node in f(mod, "decls", ()) or ():
                if kind(node) == "Impl":
                    impls.append((base, node))
                else:
                    self._collect_decl(base, node)
        for base, node in impls:
            self._collect_decl(base, node)

    def _collect_decl(self, base, node):
        k = kind(node)
        dotted = ".".join(base)
        name = f(node, "name", None)
        if k in ("Struct", "Enum", "Alias") and name:
            self._add_decl(Decl(base + (str(name),), node, "type", str(name),
                                _tparam_names(node), module=dotted))
            if k == "Enum":
                # A variant is an exported name of its own: `Res*, Ok*, None*
                # = std.core.result` imports three names, and `Ok(0)` is
                # written without qualification everywhere in the stdlib.
                for v in f(node, "variants", ()) or ():
                    vname = str(f(v, "name", ""))
                    self._add_decl(
                        Decl(base + (str(name), vname), v, "variant", vname,
                             owner=str(name), module=dotted)
                    )
            if k == "Struct":
                for member in f(node, "fields", ()) or ():
                    mname = str(f(member, "name", ""))
                    if _is_fn_field(member):
                        self._add_decl(
                            Decl(base + (str(name), mname), member, "fn", mname,
                                 _tparam_names(member), owner=str(name), module=dotted,
                                 otparams=_tparam_names(node))
                        )
                    elif f(member, "default") is not None and not f(member, "ty"):
                        self._add_decl(
                            Decl(base + (str(name), mname), member, "value", mname,
                                 owner=str(name), module=dotted)
                        )
                for c in f(node, "consts", ()) or ():
                    cname = str(f(c, "name", ""))
                    self._add_decl(
                        Decl(base + (str(name), cname), c, "value", cname,
                             owner=str(name), module=dotted)
                    )
        elif k == "Function" and name:
            self._add_decl(Decl(base + (str(name),), node, "fn", str(name),
                                _tparam_names(node), module=dotted))
        elif k == "Impl":
            # `A.impl(B, {..})` supplies a value for every field B declares:
            # a function-typed field takes a function, an f64 field takes an
            # f64 expression, which is read back as a computed field.
            # `Vec.impl(Range<T>, ..)` names the trait with its arguments
            # applied, and the arguments are not part of its NAME: the impl is
            # of Range, at T.  (cst.py hands both sides over as source text.)
            target = _bare_name(f(node, "target", ""))
            trait = _bare_name(f(node, "trait", ""))
            tdecl = self.type_decl(target, base)
            owner_tps = tdecl.tparams if tdecl is not None else ()
            # `Vec.impl(Range<T>, ..)` says WHICH of Vec's own arguments the
            # bound's argument is, and nothing else in the tree does.
            self.impls.append((target, trait, _type_args(f(node, "trait", "")),
                               owner_tps))
            for entry in f(node, "entries", ()) or ():
                ename = str(f(entry, "name", "") or "")
                if not ename:
                    continue
                dk = "fn" if kind(entry) in ("Function", "Lambda") else "value"
                self._add_decl(
                    Decl(base + (target, trait, ename), entry, dk, ename,
                         _tparam_names(entry), owner=target, module=dotted,
                         otparams=owner_tps)
                )
        elif k in ("Let", "Const") and isinstance(name, str):
            self._add_decl(Decl(base + (str(name),), node, "value", str(name),
                                module=dotted))

    # -- lookup ------------------------------------------------------------

    def lookup(self, name, parts=(), dkind=None):
        """Declarations for a name, as seen from `parts`.

        modules.py owns visibility: its `scope` already carries imports,
        re-exports, the prelude and the `*` gate, so the graph is asked first
        and the local table is only the fallback for a caller that handed
        gen_c bare `ast.Module`s.
        """
        def keep(found):
            return [d for d in found if not dkind or d.dkind == dkind]

        # The kind asked for is part of the question, not a filter applied
        # afterwards: `Alloc` declares a member named `Vec` and std declares a
        # TYPE named `Vec`, and the member shadowing the type in expression
        # position must not hide it in type position.
        if self.graph is not None and parts:
            for n in range(len(parts), 0, -1):
                dotted = ".".join(parts[:n])
                if dotted in getattr(self.graph, "modules", {}):
                    got = keep(self.from_bindings(self.graph.lookup(dotted, name)))
                    if got:
                        return got
        if parts:
            for n in range(len(parts), -1, -1):
                got = keep(self.decls.get((tuple(parts[:n]), name), []))
                if got:
                    return got
        return keep(self.by_name.get(name, []))

    def from_bindings(self, bindings):
        out = []
        for b in bindings or ():
            entity = f(b, "entity")
            if entity is None:
                continue
            key = (
                str(f(entity, "module", "")),
                str(f(entity, "owner", "") or ""),
                str(f(entity, "name", "")),
            )
            for d in self.by_key.get(key, []):
                if d not in out:
                    out.append(d)
        return out

    def type_decl(self, name, parts=(), arity=None):
        """A type declaration, selected by the NUMBER OF TYPE ARGUMENTS.

        `Res<T>` and `Res<T, E>` are both declared in the prelude, so one
        name legitimately has two declarations differing only in
        type-parameter count -- and the use site picks between them by how
        many arguments it wrote, exactly as a call picks an overload by how
        many it passed.  sema keys on `(name, arity)`; so does this.
        """
        got = self.lookup(name, parts, "type")
        if not got:
            return None
        if arity is not None:
            exact = [d for d in got if len(d.tparams) == arity]
            if exact:
                return exact[0]
            alias = [d for d in got if kind(d.node) == "Alias"]
            if alias:
                return alias[0]
        return got[0]

    # -- @scope ------------------------------------------------------------
    #
    # "A closure registered on a scope keeps its captures in that scope's own
    # storage" (DESIGN.md).  So a `Scope` value is a POINTER to the enclosing
    # block's record, and the record holds both the registered closures and
    # their captures.  The block outlives every frame that registers on it --
    # that is what non-escaping buys -- so the record is the one storage that
    # is always still alive when the closure runs, and no allocator and no
    # heap record take part.  This is not escaping-closure support and must
    # not grow into it: nothing here works for a closure whose scope is not
    # the storage.

    def scope_type(self):
        """`Scope`, as the tuple model sees it."""
        if self._scope_ty is None:
            decl = self.type_decl("Scope", ())
            self._scope_ty = ("named", decl.parts, ()) if decl is not None else UNKNOWN
        return self._scope_ty

    def is_scope_ty(self, t):
        return t is not None and t[0] == "named" and t == self.scope_type()

    # -- types -------------------------------------------------------------

    def resolve_type(self, node, subst=None, parts=(), self_ty=None):
        """An AST Type -> the tuple model."""
        subst = subst or {}
        if node is None:
            return UNKNOWN
        k = kind(node)
        if k == "Named":
            name = str(f(node, "name", ""))
            args = tuple(
                self.resolve_type(a, subst, parts, self_ty)
                for a in (f(node, "args", ()) or ())
            )
            if name in subst and not args:
                return subst[name]
            if name in ("Ptr", "RawPtr"):
                return ("ptr", args[0] if args else prim("u8"))
            if name == "...":
                return ("variadic",)
            if name in NUMERIC:
                # `std/core/num.zen` declares `i32`, `usize` and the rest as
                # struct bodies so they can carry MIN/MAX/BITS -- "a constant
                # declares one value per type, which is the only kind i32
                # could have".  The declaration is where the constants live;
                # the TYPE is still the machine one.
                return prim(name)
            decl = self.type_decl(name, parts, len(args))
            if decl is None:
                if name in PRIMS:
                    return prim(name)
                if name == "@Self":
                    if self_ty is not None:
                        return self_ty
                    if parts:
                        return ("named", tuple(parts), ())
                if name not in subst:
                    self.error(node, "unknown type `%s`" % name)
                return UNKNOWN
            if kind(decl.node) == "Alias":
                return self.resolve_type(f(decl.node, "target"), subst,
                                         decl.scope_parts, self_ty)
            return ("named", decl.parts, args)
        if k == "Union":
            return union_of(
                [self.resolve_type(m, subst, parts, self_ty)
                 for m in (f(node, "members", ()) or ())]
            )
        if k == "FnType":
            ret = self.resolve_type(f(node, "ret"), subst, parts, self_ty)
            ps = tuple(
                self.resolve_type(f(p, "ty"), subst, parts, self_ty)
                for p in (f(node, "params", ()) or ())
            )
            return ("fn", ret, ps)
        if k == "ArrayType":
            count = self.const_int(f(node, "count"), parts)
            elem = self.resolve_type(f(node, "elem"), subst, parts, self_ty)
            return ("array", count if count is not None else 0, elem)
        if k == "Unit":
            return UNIT
        if k == "Infer":
            return UNKNOWN
        return UNKNOWN

    def const_int(self, expr, parts=()):
        """Comptime integer, for an array length.  Literals and Type.NAME."""
        if expr is None:
            return None
        k = kind(expr)
        if k == "Literal" and f(expr, "kind") == "int":
            return parse_int(f(expr, "text", "0"))
        if k == "Unary" and f(expr, "op") == "-":
            inner = self.const_int(f(expr, "operand"), parts)
            return None if inner is None else -inner
        if k == "Member":
            base = f(expr, "base")
            if kind(base) == "Path":
                got = self.builtin_type_const(str(f(base, "name", "")), str(f(expr, "name", "")))
                if got is not None:
                    return got[0]
        if k == "Path":
            got = self.lookup(str(f(expr, "name", "")), parts, "value")
            if got:
                if got[0].key in self.expanding:
                    return None
                self.expanding.append(got[0].key)
                try:
                    return self.const_int(f(got[0].node, "value"), got[0].scope_parts)
                finally:
                    self.expanding.pop()
        return None

    def builtin_type_const(self, tyname, member):
        """i32.MAX / u8.MIN / i64.BITS, when std has not declared them."""
        if tyname not in INT_VALUES:
            return None
        lo, hi, bits = INT_VALUES[tyname]
        if member == "MIN":
            return (lo, prim(tyname))
        if member == "MAX":
            return (hi, prim(tyname))
        if member == "BITS":
            return (bits, prim("usize"))
        return None

    # -- C spelling of a type ---------------------------------------------

    def ctype(self, t):
        if t is None or t == UNKNOWN:
            return "int"  # a diagnostic has already been raised
        k = t[0]
        if k == "prim":
            name = t[1]
            if name == "str" and self.type_decl("str"):
                return self.request_type(("named", self.type_decl("str").parts, ()))
            return PRIMS.get(name, "int")
        if k == "unit":
            return "void"
        if k == "ptr":
            inner = self.ctype(t[1])
            return inner + " *"
        if k in ("named", "array", "union"):
            if k == "named" and self.is_scope_ty(t):
                # a Scope is the block's record, reached by pointer: passing
                # it INWARD has to reach the caller's stack, not a copy of it
                self.needs.add("scope")
                return GEN + "scope *"
            return self.request_type(t)
        if k == "fn":
            return GEN + "closure"
        return "int"

    def fnptr(self, ret, params, name):
        """`ret (*name)(void *, params..)` -- the receiver is erased to a
        pointer, so one slot serves every impl."""
        args = ["void *"] + [self.ctype(p).strip() for p in params]
        spelling = self.ctype(ret)
        join = "" if spelling.endswith("*") else " "
        return "%s%s(*%s)(%s)" % (spelling, join, name, ", ".join(args))

    def declarator(self, t, name):
        """A C declarator; pointers bind to the name, everything else does not."""
        spelling = self.ctype(t)
        if spelling.endswith("*"):
            return spelling + name
        return spelling + " " + name

    # -- type emission -----------------------------------------------------

    def request_type(self, t):
        """Register a type for emission and return its C name."""
        if t[0] == "named":
            cname = USR + tcode(t)
        else:
            cname = GEN + tcode(t)
        if cname in self.types:
            return cname
        self.types[cname] = None  # reserve, so recursion terminates
        if t[0] == "array":
            self.types[cname] = ("array", t)
            self.type_order[cname] = self._deps([t[2]])
        elif t[0] == "union":
            self.types[cname] = ("union", t)
            self.type_order[cname] = self._deps(list(t[1]))
        else:
            self._request_named(cname, t)
        return cname

    def _request_named(self, cname, t):
        parts, args = t[1], t[2]
        decl = None
        cands = [
            d for d in self.by_name.get(parts[-1], [])
            if d.dkind == "type" and d.parts == parts
        ]
        for d in cands:  # arity first: Res<T> and Res<T, E> share a name
            if len(d.tparams) == len(args):
                decl = d
                break
        if decl is None and cands:
            decl = cands[0]
        if decl is None:
            self.types[cname] = ("opaque", t)
            self.type_order[cname] = ()
            return
        node = decl.node
        subst = dict(zip(decl.tparams, args))
        base = decl.scope_parts
        if len(args) != len(decl.tparams):
            self.error(node, "wrong number of type arguments for %s" % parts[-1])
        self.instances += 1
        if self.instances > MAX_INSTANCES:
            self.error(node, "generic instantiation did not terminate")
            self.types[cname] = ("opaque", t)
            self.type_order[cname] = ()
            return
        if kind(node) == "Struct" and self.trait_decl(t) is not None:
            self.types[cname] = ("trait", t, self.trait_slots(t), decl)
            # A trait's slots are FUNCTION POINTERS, so none of them is by-value
            # containment and none of them constrains definition order -- every
            # tag is forward-declared above. Feeding the slot signatures to
            # _deps made a trait depend on every type its methods mention,
            # including itself: `Eq.eq = (self: @Self, other: @Self) bool`
            # recorded Eq -> Eq and reported a by-value cycle in std.core.eq
            # that stopped the whole of src/ compiling. The receiver is `void *`
            # in the emitted record; it was never containment at all.
            self.type_order[cname] = ()
        elif kind(node) == "Struct":
            fields = []
            for member in f(node, "fields", ()) or ():
                if _is_fn_field(member):
                    continue  # a method is a function, not storage
                mname = str(f(member, "name", ""))
                mty = self.resolve_type(f(member, "ty"), subst, base)
                fields.append((mname, mty))
            self.types[cname] = ("struct", t, tuple(fields), decl)
            self.type_order[cname] = self._deps([ft for _, ft in fields])
            for _, ft in fields:
                self.ctype(ft)
        elif kind(node) == "Enum":
            variants = []
            union = self.enum_is_union(decl)
            for v in f(node, "variants", ()) or ():
                vname = str(f(v, "name", ""))
                payload = f(v, "payload")
                pty = self.resolve_type(payload, subst, base) if payload is not None else None
                if union:
                    # "`A | B` is an anonymous enum of two variants -- a
                    # STRUCTURAL enum."  A variant that names a type carries a
                    # value of that type, so `WriteError.IoError` records WHICH
                    # IoError; tag-only, it would record only that there was one.
                    pty = self.union_member_ty(vname, base)
                if pty == UNIT:
                    pty = None  # `Ok(())` carries nothing; a void member is illegal C
                variants.append((vname, pty))
            for i, (vname, _p) in enumerate(variants):
                # The tag name is a function of the DECLARATION, not of the
                # instantiation: Res<i32, E> and Res<i32, F> share `Ok`, and
                # emitting the constant per instance is a C redefinition.
                self.consts[sym_variant(tuple(parts) + (vname,))] = i
            self.types[cname] = ("enum", t, tuple(variants), decl)
            self.type_order[cname] = self._deps([p for _, p in variants if p])
            for _, p in variants:
                if p:
                    self.ctype(p)
        else:  # Alias to a non-union type
            self.types[cname] = ("opaque", t)
            self.type_order[cname] = ()

    def _deps(self, tys):
        """By-value dependencies only; a pointer needs no complete type."""
        out = []
        for t in tys:
            if t is None:
                continue
            if t[0] in ("named", "array", "union"):
                out.append(self.request_type(t))
            elif t[0] == "prim" and t[1] == "str" and self.type_decl("str"):
                out.append(self.ctype(t))
        return tuple(sorted(set(out)))

    # -- traits ------------------------------------------------------------
    #
    # "There are no traits, only structs.  A struct whose fields happen to be
    # functions, used as a bound, is what other languages call a trait --
    # nothing marks it special, because nothing needs to."  So a trait is
    # recognised by its shape: it declares behaviour and no storage.  A struct
    # with storage is a concrete type, even when an impl supplies fields for
    # it, and it is never a fat value.

    def struct_decl(self, ty):
        """The struct a named type refers to, whatever its shape.

        Any struct may be used as a bound -- DESIGN.md's own example impls
        `Rect`, which is nothing but storage.  So "can this name a bound" and
        "is this a fat value" are two questions, and only the second one is
        about shape.
        """
        if ty is None or ty[0] != "named":
            return None
        for d in self.by_name.get(ty[1][-1], []):
            if d.dkind == "type" and d.parts == ty[1]:
                return d if kind(d.node) == "Struct" else None
        return None

    def trait_decl(self, ty):
        d = self.struct_decl(ty)
        if d is None:
            return None
        node = d.node
        members = [m for m in (f(node, "fields", ()) or ()) if _is_fn_field(m)]
        storage = [m for m in (f(node, "fields", ()) or ()) if not _is_fn_field(m)]
        # only a struct that declares behaviour and no storage can BE a value:
        # a fat value is a receiver plus one function pointer per method, and
        # a storage field has no function pointer to carry.
        return d if members and not storage else None

    def is_trait(self, ty):
        return self.trait_decl(ty) is not None

    def has_impl(self, ty):
        """Does anything in the program impl this trait?

        A trait with no impl anywhere is not a dispatch problem, it is a
        CAPABILITY: `Console` and `Mem` are the authority itself, and
        DESIGN.md's law is that all authority flows from Env.  Their members
        have no Zen implementation to find because the runtime is the
        implementation -- exactly like `Ptr`'s members.
        """
        name = ty[1][-1]
        for ds in self.by_name.values():
            for d in ds:
                if len(d.parts) >= 3 and d.parts[-2] == name and d.owner \
                        and d.owner != name:
                    return True  # `C.impl(Trait, ..)`, not the trait's own member
        return False

    def trait_slots(self, ty):
        """One slot per declared member, IN DECLARATION ORDER.

        The layout is a pure function of the trait declaration and of nothing
        else -- not of which impls exist, not of the order they were found in.
        Determinism is the reason, and so is the ability to compile two
        programs' records to the same shape.
        """
        decl = self.trait_decl(ty)
        if decl is None:
            return ()
        subst = dict(zip(decl.tparams, ty[2]))
        seen = {}
        out = []
        mark = len(self.diags)
        for m in f(decl.node, "fields", ()) or ():
            if not _is_fn_field(m):
                continue
            name = str(f(m, "name", ""))
            seen[name] = seen.get(name, 0) + 1
            slot = sym_member(name) + ("" if seen[name] == 1 else "_%d" % seen[name])
            fnode = self.fn_node(m)
            base = decl.scope_parts
            self_ty = ("named", ty[1], ty[2])
            # A member's OWN type parameters are what erasure erases, so they
            # are resolved to the erased element type here rather than left
            # unresolved -- `Ptr<T>` in the declaration IS `Ptr<u8>` in the slot.
            local = dict(subst)
            for tp in _tparam_names(m):
                local[tp] = prim("u8")
            params = [
                erase(self.resolve_type(f(p, "ty"), local, base, self_ty))
                for p in self.params_of(fnode)[1:]
            ]
            # One `size_t` per erased type parameter: the element size the
            # erasure dropped.  "raw is bytes and nothing more -- size and
            # alignment in, an address out.  Naming what the bytes are is
            # `Ptr.to`, one level down."  The erased interface is the byte
            # one, so the size travels beside the pointer, exactly as it does
            # in Zig's std.mem.Allocator.
            elems = len(_tparam_names(m))
            params += [prim("usize")] * elems
            ret = erase(self.resolve_type(self.ret_of(fnode), local, base, self_ty))
            out.append((slot, name, m, tuple(params), ret))
        del self.diags[mark:]
        return tuple(out)

    def variant_parts(self, t, vname):
        return tuple(t[1]) + (vname,)

    def enum_info(self, t):
        cname = self.request_type(t)
        entry = self.types.get(cname)
        if entry and entry[0] == "enum":
            return entry
        return None

    def struct_info(self, t):
        cname = self.request_type(t)
        entry = self.types.get(cname)
        if entry and entry[0] == "struct":
            return entry
        return None

    # -- RAII ---------------------------------------------------------------

    def drop_impl(self, ty):
        """The `drop` a `T.impl(Drop, ..)` supplies for this type, or None.

        Only a DIRECT impl counts.  Drop is not recursive here: `DESIGN.md`
        gives `Vec.take` as the way a `Vec<T>` of Drop values is emptied --
        "without this a Vec<T> of Drop values can be filled and never
        emptied" -- which is only a sentence worth writing if the container
        does not drop its elements for you.
        """
        if ty is None or ty[0] != "named":
            return None
        key = tuple(ty[1])
        if key in self._drops:
            return self._drops[key]
        found = None
        for d in self.decls.get((key, "drop"), []):
            # `parts` is base + (target, trait, member): the trait component is
            # what tells an impl of Drop from a type's own method named `drop`.
            if d.dkind == "fn" and len(d.parts) >= 2 and d.parts[-2] == "Drop":
                found = d
                break
        self._drops[key] = found
        return found

    def consumed_names(self):
        """Every name written as `consume <name>` anywhere in the program.

        Program-wide and not per-function on purpose: a body reaches gen_c
        inlined into its caller's frame, so "was this binding moved" cannot be
        asked of one function's source.  Over-approximating costs an unread
        `int` on a frame; under-approximating costs a double free.
        """
        if self._consumed is None:
            names = set()
            for _base, mod in self.mods:
                for node in zast.walk(mod) if zast is not None else ():
                    if kind(node) == "Consume":
                        operand = f(node, "operand")
                        if operand is not None and kind(operand) == "Path":
                            names.add(str(f(operand, "name", "")))
            self._consumed = frozenset(names)
        return self._consumed

    def union_member_ty(self, vname, base):
        """The type a union member's NAME denotes, or None if it denotes none."""
        decl = self.type_decl(vname, base, 0)
        if decl is None or decl.tparams:
            return None
        if kind(decl.node) == "Alias":
            return self.resolve_type(f(decl.node, "target"), {}, decl.scope_parts)
        return ("named", decl.parts, ())

    def enum_is_union(self, decl):
        """Is this enum declaration `A | B`, a union of EXISTING types?

        DESIGN.md draws the line there: that is what makes the declaration a
        set rather than an ordinary enum, and it is the only thing that makes
        propagating one set into another safe.  `CfgError = Missing | Bad`
        names no types and is not one.  Two or more variants, none carrying a
        payload of its own, every name a type -- the same three questions
        sema's `enum_is_union` asks, because a disagreement between the two
        halves is exactly what a structural enum cannot survive.
        """
        if decl is None or kind(decl.node) != "Enum":
            return False
        key = decl.parts
        if key in self._unions:
            return self._unions[key]
        self._unions[key] = False   # a variant naming its own enum is nominal
        vs = list(f(decl.node, "variants", ()) or ())
        ok = len(vs) >= 2
        mark = len(self.diags)
        for v in vs if ok else ():
            if f(v, "payload") is not None:
                ok = False
                break
            if self.union_member_ty(str(f(v, "name", "")), decl.scope_parts) is None:
                ok = False
                break
        del self.diags[mark:]   # asking the question reports nothing
        self._unions[key] = ok
        return ok

    def error_set_members(self, ty):
        """The members of `Error = AllocError | IoError`, or None."""
        info = self.enum_info(ty)
        if info is None or not self.enum_is_union(info[3]):
            return None
        return [v for v, _p in info[2]]

    def drop_takes_address(self, decl):
        """`drop = (self :: @Self)` is passed by address, as every `::`
        receiver is; an impl that wrote `:` is passed by value."""
        params = self.params_of(self.fn_node(decl.node))
        return bool(params) and bool(f(params[0], "mutable", False))

    # -- building a fat value ----------------------------------------------

    def impl_entry(self, concrete, trait, name):
        """The impl's answer for one of a trait's members, if it supplies one."""
        target = concrete[1][-1]
        traitname = trait[1][-1]
        out = []
        for d in self.by_name.get(name, []):
            if d.dkind != "fn" or d.owner != target:
                continue
            if len(d.parts) >= 3 and d.parts[-2] == traitname:
                out.append(d)
        return out

    def convert(self, code, src, dst):
        """Rebuild a value at another type -- never reinterpret one.

        Erasure is what lets one slot serve every instantiation of a generic
        member, and this is the way back: a pointer is cast, and a tagged
        union is rebuilt variant by variant.  Nothing here assumes two
        pointer types share a representation.
        """
        if src is None or dst is None or src == dst:
            return code
        if dst[0] == "ptr":
            return "((%s)%s)" % (self.ctype(dst).strip(), paren(code))
        if src[0] == "named" and dst[0] == "named" and src[1] == dst[1]:
            sinfo, dinfo = self.enum_info(src), self.enum_info(dst)
            if sinfo is None or dinfo is None:
                return code
            spay, dpay = dict(sinfo[2]), dict(dinfo[2])
            out = None
            for vname, _p in reversed(dinfo[2]):
                inner = None
                if dpay.get(vname) is not None:
                    inner = self.convert(
                        "%s.%sdata.%s" % (paren(code), GEN, sym_member(vname)),
                        spay.get(vname), dpay.get(vname))
                built = self.variant_literal(dst, vname, inner)
                if out is None:
                    out = built
                else:
                    out = "(%s.%stag == %s ? %s : %s)" % (
                        paren(code), GEN, sym_variant(self.variant_parts(dst, vname)),
                        built, out)
            return out if out is not None else code
        return code

    def variant_literal(self, ty, vname, payload):
        cname = self.ctype(ty)
        tag = sym_variant(self.variant_parts(ty, vname))
        if payload is None:
            return "((%s){ .%stag = %s })" % (cname, GEN, tag)
        return "((%s){ .%stag = %s, .%sdata = { .%s = %s } })" % (
            cname, GEN, tag, GEN, sym_member(vname), payload)

    def thunk(self, concrete, trait, slot, params, ret, decl, targs):
        """One `void *`-receiving shim per (impl member, trait slot).

        The record's slots are erased, the impl's function is not, so
        something has to sit between them.  A cast of the function pointer
        would be undefined; a shim is a call.
        """
        target = self.request_fn(decl, targs)
        cname = GEN + "v" + target[len(USR):]
        if cname in self.bodies or cname in self.protos:
            return cname
        fnode = self.fn_node(decl.node)
        subst = dict(zip(decl.tparams, targs))
        base = decl.scope_parts
        real = [self.resolve_type(f(p, "ty"), subst, base, concrete)
                for p in self.params_of(fnode)]
        rret = self.resolve_type(self.ret_of(fnode), subst, base, concrete)
        names = ["%sa%d" % (GEN, i) for i in range(len(params))]
        # `self :: @Self` takes the receiver BY REFERENCE, so the shim hands
        # the pointer straight through; `self: @Self` takes it by value and
        # the shim dereferences.  A String's `write` mutates the buffer the
        # record points at, which only works if the pointer survives the shim
        own = self.params_of(fnode)
        args = ["(%s *)%sself" % (self.ctype(concrete), GEN)
                if own and f(own[0], "mutable", False)
                else "(*(%s *)%sself)" % (self.ctype(concrete), GEN)]
        nreal = max(0, len(real) - 1)
        for i, (pname, pty) in enumerate(zip(names, params)):
            if i >= nreal:
                continue  # a trailing element size, consumed below
            want = real[i + 1] if i + 1 < len(real) else pty
            # A count beside an erased pointer is an ELEMENT count, and the
            # instance being called was compiled for bytes.  The size the
            # erasure dropped is the argument that puts it back.
            if want == prim("usize") and i > 0 and params[i - 1][0] == "ptr" \
                    and len(names) > nreal:
                args.append("(%s * %s)" % (pname, names[nreal]))
                continue
            args.append(self.convert(pname, pty, want))
        head = "static %s%s%s(void *%sself%s)" % (
            self.ctype(ret), "" if self.ctype(ret).endswith("*") else " ", cname, GEN,
            "".join(", " + self.declarator(p, n) for n, p in zip(names, params)))
        call = "%s(%s)" % (target, ", ".join(args))
        body = "    return %s;\n" % self.convert(call, rret, ret)
        if ret in (None, UNIT):
            head = "static void %s(void *%sself%s)" % (
                cname, GEN,
                "".join(", " + self.declarator(p, n) for n, p in zip(names, params)))
            body = "    %s;\n" % call
        self.protos[cname] = head + ";"
        self.bodies[cname] = head + " {\n" + body + "}\n"
        return cname

    def console_thunk(self, name, slot, params, ret):
        """One slot of the console's Sink record.

        The console has no Zen implementation to call -- the runtime IS the
        implementation, exactly as it is for `Ptr`'s members -- so these are
        written here rather than found.  Each one writes and reports success:
        a console cannot fail to grow, and `print_bytes` has no failure to
        report, so the honest answer on this path is Ok.
        """
        writes = {
            "write": "    %sprint_bytes((const char *)%sa0.%s, (size_t)%sa0.%s);"
                     % (GEN, GEN, sym_member("data"), GEN, sym_member("len")),
            "write_byte": "    { char %sc = (char)%sa0; %sprint_bytes(&%sc, 1); }"
                          % (GEN, GEN, GEN, GEN),
        }
        if name not in writes or not params:
            return None
        cname = "%sconsole_%s" % (GEN, name)
        if cname in self.bodies:
            return cname
        head = "static %s %s(void *%sself, %s)" % (
            self.ctype(ret), cname, GEN, self.declarator(params[0], GEN + "a0"))
        body = writes[name] + "\n"
        # a `()` payload is no storage, so Ok is a tag and nothing else
        ok = "((%s){ .%stag = %s })" % (
            self.ctype(ret), GEN, sym_variant(self.variant_parts(ret, "Ok")))
        body += "    (void)%sself;\n    return %s;\n" % (GEN, ok)
        self.protos[cname] = head + ";"
        self.bodies[cname] = head + " {\n" + body + "}\n"
        return cname

    def fat_value(self, code, concrete, trait, ctx=None):
        """`shape.as(Display)`, or any concrete value reaching a trait slot.

        Two words plus a function pointer per method, built on the stack and
        copied by value.  The receiver must outlive the record, which is the
        ordinary rule for any pointer stored in anything.
        """
        slots = []
        for slot, name, member, params, ret in self.trait_slots(trait):
            entries = self.impl_entry(concrete, trait, name)
            if not entries:
                entries = [d for d in self.by_name.get(name, [])
                           if d.dkind == "fn" and d.owner == concrete[1][-1]]
            fn = None
            for d in entries:
                if self.fn_node(d.node) is not None:
                    fn = d
                    break
            if fn is None and f(self.fn_node(member), "body") is not None:
                # the trait's own default, specialised on this receiver
                tdecl = self.trait_decl(trait)
                for d in self.by_name.get(name, []):
                    if d.dkind == "fn" and d.owner == trait[1][-1] and d.parts[:-1] == tdecl.parts:
                        fn = d
                        break
            if fn is None:
                slots.append((slot, "NULL"))
                continue
            # compiled at the erased element type: one byte, so a scaled
            # count is already the byte count it needs
            targs = tuple(prim("u8") for _ in fn.tparams)
            if fn.otparams:
                targs = tuple(concrete[2]) + tuple(
                    prim("u8") for _ in fn.tparams[len(fn.otparams):])
            slots.append((slot, self.thunk(concrete, trait, slot, params, ret, fn, targs)))
        inits = [".%sself = (void *)%s" % (GEN, code)]
        inits += [".%s = %s" % (slot, fn) for slot, fn in slots]
        return "((%s){ %s })" % (self.ctype(trait), ", ".join(inits))

    # -- diagnostics -------------------------------------------------------

    def error(self, node, message, notes=()):
        self.diags.append(_diag(f(node, "span"), message, notes))

    # ------------------------------------------------------------------ API

    def emit(self):
        """The whole program, as one C99 translation unit."""
        # Whole-program compilation emits what the program reaches.  Seeding
        # from `main` rather than from every declaration is what keeps an
        # unused std member -- one supplied by an impl gen_c cannot dispatch
        # yet -- from failing a program that never calls it.
        roots = [d for d in self.by_name.get("main", []) if d.dkind == "fn"]
        if not roots:
            roots = [d for ds in self.by_name.values() for d in ds if d.dkind == "fn"]
        for decl in sorted(roots, key=lambda d: d.parts):
            if decl.tparams:
                continue  # a generic is emitted per instantiation
            self.request_fn(decl, ())
        self.drain()
        return self.assemble()

    def drain(self):
        guard = 0
        while self.worklist:
            guard += 1
            if guard > MAX_INSTANCES:
                # `f<T> = (x: T) { f<Vec<T>>(..) }` must terminate with an
                # error rather than consume all memory (TESTING.md, Sema).
                cname, decl = self.worklist[0][0], self.worklist[0][1]
                self.error(decl.node,
                           "generic instantiation did not terminate at `%s`" % decl.name)
                break
            self.worklist.sort(key=lambda item: item[0])
            cname, decl, targs, self_ty = self.worklist.pop(0)
            self.emit_fn(cname, decl, targs, self_ty)

    def request_fn(self, decl, targs=(), self_ty=None):
        node = decl.node
        fnode = self.fn_node(node)
        subst = dict(zip(decl.tparams, targs))
        sig = self.overload_sig(decl, subst)
        if self_ty is not None and self_ty == self.self_type(decl, subst):
            self_ty = None  # the declaration's own Self: not a specialisation
        cname = sym_fn(decl.parts, sig, targs, self_ty)
        if cname in self.done:
            return cname
        self.done.add(cname)
        if fnode is None or f(fnode, "body") is None:
            # required / hook forms have no body: no C function to emit
            return cname
        self.worklist.append((cname, decl, tuple(targs), self_ty))
        return cname

    def fn_node(self, node):
        """The Function/Lambda carrying params and a body for a declaration.

        A method is a struct member whose value is a function (DESIGN.md has
        one declaration form), so the member, its `default`/`value` and its
        `FnType` are all places the signature can be.
        """
        if kind(node) in ("Function", "Lambda"):
            return node
        for attr in ("default", "value"):
            v = f(node, attr)
            if v is not None and kind(v) in ("Function", "Lambda"):
                return v
        ty = f(node, "ty")
        if ty is not None and kind(ty) == "FnType":
            return node
        return None

    def params_of(self, fnode):
        if fnode is None:
            return ()
        got = f(fnode, "params")
        if got is None:
            ty = f(fnode, "ty")
            got = f(ty, "params") if ty is not None else None
        return tuple(got or ())

    def ret_of(self, fnode):
        if fnode is None:
            return None
        if f(fnode, "ret") is not None:
            return self.filled_ret(fnode, f(fnode, "ret"))
        ty = f(fnode, "ty")
        return self.filled_ret(fnode, f(ty, "ret") if ty is not None else None)

    def filled_ret(self, fnode, node):
        """`Res<T, _>` with the set sema inferred written in.

        "Inference inside a module, explicit at the boundary" (law 6): the
        boundary spelling is already a type, and this is the other half.  It
        happens HERE, at the one funnel every caller reads a return type
        through, so a caller and a callee can never disagree about what `_`
        turned out to be.
        """
        if node is None or kind(node) != "Named" or str(f(node, "name", "")) != "Res":
            return node
        args = tuple(f(node, "args", ()) or ())
        if len(args) != 2 or kind(args[1]) != "Infer":
            return node
        key = id(fnode)
        if key in self._rets:
            return self._rets[key]
        filled = node
        query = getattr(self.sema, "error_set_ast", None) if self.sema else None
        if query is not None:
            try:
                got = query(fnode)
            except Exception:  # pragma: no cover - a partial sema
                got = None
            if got is not None and zast is not None:
                filled = zast.Named(str(f(node, "name", "")), (args[0], got),
                                    span=getattr(node, "span", None))
        self._rets[key] = filled
        return filled

    def overload_sig(self, decl, subst):
        """Parameter types, but only for a name declared more than once.

        A pure function of the program: the count comes from the declaration
        table, never from the order calls were seen in.
        """
        siblings = [d for d in self.decls.get((decl.scope_parts, decl.name), [])]
        if len(siblings) < 2:
            return ()
        fnode = self.fn_node(decl.node)
        if fnode is None:
            return ()
        return tuple(
            self.resolve_type(f(p, "ty"), subst, decl.scope_parts,
                              self.self_type(decl, subst))
            for p in self.params_of(fnode)
        )

    # ------------------------------------------------------- function bodies

    def emit_fn(self, cname, decl, targs, self_ty=None):
        fnode = self.fn_node(decl.node)
        subst = dict(zip(decl.tparams, targs))
        base = decl.scope_parts
        params = list(self.params_of(fnode))
        self_ty = self_ty or self.self_type(decl, subst)
        ret = self.resolve_type(self.ret_of(fnode), subst, base, self_ty)
        ctx = FnCtx(self, decl, subst, ret, self_ty)
        ctx.consumed = self.consumed_names()

        decls = []
        for p in params:
            pname = str(f(p, "name", "_"))
            pty = self.resolve_type(f(p, "ty"), subst, base, self_ty)
            if pty == UNKNOWN and self.sema is not None:
                pty = self.sema_type(p, base, subst) or pty
            if pty == ("variadic",):
                # `args: ...` — a variadic is resolved at the call site, and
                # the only caller in the seed subset is `println`, which gen_c
                # lowers to typed writes rather than to a C varargs call.
                continue
            if f(p, "mutable", False):
                # "`::` means the method writes the receiver's OWN BYTES" --
                # so the receiver is passed by address.  By value, `self.grow()`
                # would grow a copy: the Vec that called it would still hold a
                # null data pointer, which is a segfault one line later.
                cn = ctx.declare(pname, pty, byref=True)
                decls.append(self.declarator(("ptr", pty), cn))
            else:
                cn = ctx.declare(pname, pty)
                decls.append(self.declarator(pty, cn))
        if not decls:
            decls = ["void"]
        head = "static %s(%s)" % (self.declarator(ret, cname), ", ".join(decls))
        self.protos[cname] = head + ";"

        body = f(fnode, "body")
        ctx.push()
        value = ctx.block_value(body, ret)
        if ret != UNIT and value is not None:
            ctx.line("return %s;" % value)
        elif ret != UNIT:
            ctx.line("return (%s){0};" % self.ctype(ret) if ret[0] != "prim" else "return 0;")
        ctx.pop()
        self.bodies[cname] = head + " {\n" + ctx.text() + "}\n"

    def defer_thunk(self, ctx, lam, caps, node):
        """A deferred closure, lifted to a C function over the record's env.

        The ONE closure that becomes a real function rather than being
        inlined, and it is not the escaping closure the design forbids: its
        environment is the block's storage, handed to it as `void *`, so
        nothing is boxed and nothing is allocated.  Returns the function's
        name and its capture struct's, or `None` when it captures nothing.

        Two lowerings of one closure are one function.  Overload resolution
        and the trailing-expression rule both lower speculatively and throw
        the text away, and a thunk registered by a discarded lowering would
        otherwise sit in the output as an unreferenced static.
        """
        self.needs.add("scope")
        fields = "".join(
            "    %s;\n" % self.declarator(ty, "%sc%d" % (GEN, i))
            for i, (_name, _code, ty) in enumerate(caps)
        )
        inner = FnCtx(self, ctx.decl, ctx.subst, UNIT, ctx.self_ty)
        inner.consumed = ctx.consumed
        inner.push()
        if caps:
            inner.line("%s *%senv = (%s *)%sp;" % (ENVMARK, GEN, ENVMARK, GEN))
            for i, (name, _code, ty) in enumerate(caps):
                inner.scopes[-1][name] = ("(*%senv).%sc%d" % (GEN, GEN, i), ty)
        else:
            inner.line("(void)%sp;" % GEN)
        if f(lam, "params", ()):
            self.error(node, "a deferred closure takes no parameters")
        inner.block_value(f(lam, "body"), UNIT)
        inner.pop()
        key = (inner.text(), fields)
        if key in self._defer_cache:
            return self._defer_cache[key]
        self.defer_sites += 1
        n = self.defer_sites
        thunk = "%sd%d" % (GEN, n)
        env = None
        if caps:
            env = "%senv%d" % (GEN, n)
            self.defer_envs[n] = "typedef struct %s {\n%s} %s;\n\n" % (env, fields, env)
        head = "static void %s(void *%sp)" % (thunk, GEN)
        self.protos[thunk] = head + ";"
        self.bodies[thunk] = (head + " {\n" + inner.text() + "}\n").replace(
            ENVMARK, env or "void")
        self._defer_cache[key] = (thunk, env)
        return thunk, env

    def self_type(self, decl, subst):
        """`@Self` for this declaration: the owning type, at the arguments
        this instantiation was made with."""
        if not decl.owner:
            return None
        base = tuple(decl.module.split(".")) if decl.module else ()
        return ("named", base + (decl.owner,),
                tuple(subst.get(tp, UNKNOWN) for tp in decl.otparams))

    def sema_type(self, node, parts=(), subst=None):
        if self.sema is None:
            return None
        query = getattr(self.sema, "type_of", None)
        if query is None:
            return None
        try:
            got = query(node)
        except Exception:  # pragma: no cover - sema is another agent's file
            return None
        if got is None:
            return None
        return self.resolve_type(got, subst or {}, parts)

    # ------------------------------------------------------------- assembly

    def assemble(self):
        # `main` first: it can register one last type, and the type section
        # has to know about every type before it is written.
        entry = self.entry_point()
        types = self.emit_types()
        out = []
        out.append(BANNER)
        out.append(INCLUDES)
        out.append(self.prelude())
        out.append(types)
        out.append(self.defer_section())
        out.append("/* ---- prototypes ---- */\n")
        for cname in sorted(self.protos):
            out.append(self.protos[cname] + "\n")
        out.append("\n/* ---- definitions ---- */\n\n")
        for cname in sorted(self.bodies):
            out.append(self.bodies[cname] + "\n")
        out.append(entry)
        return "".join(out)

    def argv_prelude(self):
        """`env.argv`, built once at startup from the C runtime's own argv.

        Generated rather than a PRELUDE_ constant because it names the mangled
        `Vec<str>` and `str` types, which are not known until they are
        requested. The rows are never freed: they last exactly as long as the
        process, and `argv` itself is storage the C runtime already owns, so a
        row borrows rather than copies.
        """
        if len(self.argv_vec_fields) != 3:
            return ""
        vdata, vlen, vcap = self.argv_vec_fields
        return (
            "static %s %sargv_vec(int argc, char **argv) {\n"
            "    %s v;\n"
            "    memset(&v, 0, sizeof v);\n"
            "    if (argc <= 0) return v;\n"
            "    %s *rows = (%s *)malloc((size_t)argc * sizeof *rows);\n"
            "    if (!rows) return v;\n"
            "    for (int i = 0; i < argc; i++) {\n"
            "        rows[i].%s = (unsigned char *)argv[i];\n"
            "        rows[i].%s = strlen(argv[i]);\n"
            "    }\n"
            "    v.%s = rows;\n"
            "    v.%s = (size_t)argc;\n"
            "    v.%s = (size_t)argc;\n"
            "    return v;\n"
            "}\n\n"
            % (self.argv_vec_ctype, GEN, self.argv_vec_ctype,
               self.argv_str_ctype, self.argv_str_ctype,
               self.argv_str_data, self.argv_str_len,
               vdata, vlen, vcap)
        )

    def prelude(self):
        parts = [PRELUDE_TYPES, PRELUDE_TRAP]
        if "scope" in self.needs:
            parts.append(PRELUDE_SCOPE)
        if "print" in self.needs:
            parts.append(PRELUDE_PRINT)
        if "fs" in self.needs:
            parts.append(PRELUDE_FS)
        if "stdin" in self.needs:
            parts.append(PRELUDE_STDIN)
        for name in sorted(self.helpers):
            parts.append(HELPERS[name])
        return "".join(parts)

    def defer_section(self):
        """The block record, after the types a capture can name.

        A slot's env is a union over every capture record in the program, so
        it is exactly as large and as aligned as the largest one -- no
        guessed byte count, and nothing to overflow.  How MANY closures one
        block may carry is the one thing whole-program analysis cannot answer
        (a `defer` in a loop is unbounded), so that bound is a constant and
        exceeding it traps rather than corrupting the frame.
        """
        if "scope" not in self.needs:
            return ""
        out = ["/* ---- @scope: the block's own defer stack ---- */\n\n"]
        for n in sorted(self.defer_envs):
            out.append(self.defer_envs[n])
        out.append("typedef union %sdefer_env {\n    char %snone;\n" % (GEN, GEN))
        for n in sorted(self.defer_envs):
            out.append("    %senv%d %su%d;\n" % (GEN, n, GEN, n))
        out.append("} %sdefer_env;\n\n" % GEN)
        out.append(DEFER_RUNTIME)
        return "".join(out)

    def emit_types(self):
        # Every tag is forward-declared before any definition: a by-value
        # field needs a complete type (so definitions are sorted by
        # dependency) and a cycle through Ptr cannot be sorted at all, so
        # both mechanisms are used rather than one.
        bodies = {}
        for _ in range(8):  # emitting a definition can register a new type
            todo = [n for n in sorted(self.types) if n not in bodies]
            if not todo:
                break
            for cname in self.topo(todo):
                bodies[cname] = self.emit_type(cname)
        out = ["/* ---- types ---- */\n"]
        for cname in sorted(self.types):
            out.append("typedef struct %s %s;\n" % (cname, cname))
        out.append("\n")
        if self.consts:
            out.append("enum {\n")
            for name in sorted(self.consts):
                out.append("    %s = %d,\n" % (name, self.consts[name]))
            out.append("};\n\n")
        for cname in self.topo(sorted(bodies)):
            out.append(bodies[cname])
        return "".join(out)

    def topo(self, names):
        """Definition order: dependencies first, ties broken by name.

        Every tag is forward-declared above, so only by-value containment
        constrains this; a genuine by-value cycle is a sema error and is
        broken here by name so that emission still terminates.
        """
        pending = {n: set(self.type_order.get(n, ())) & set(names) for n in names}
        emitted = []
        done = set()
        while pending:
            ready = sorted(n for n, deps in pending.items() if not (deps - done))
            if not ready:
                ready = [sorted(pending)[0]]
                entry = self.types.get(ready[0])
                if entry:
                    self.diags.append(
                        _diag(None, "type %s is part of a by-value cycle" % ready[0])
                    )
            for n in ready:
                emitted.append(n)
                done.add(n)
                pending.pop(n, None)
        return emitted

    def emit_type(self, cname):
        entry = self.types.get(cname)
        if entry is None or entry[0] == "opaque":
            return "struct %s { char %spad; };\n\n" % (cname, GEN)
        if entry[0] == "struct":
            _, t, fields, _decl = entry
            lines = ["struct %s {\n" % cname]
            if not fields:
                # C11 6.7.2.1p1 requires a member; one byte, in exactly one
                # place, so a bare Empty and an Empty field agree.
                lines.append("    char %spad;\n" % GEN)
            for fname, fty in fields:
                lines.append("    %s;\n" % self.declarator(fty, sym_member(fname)))
            lines.append("};\n\n")
            return "".join(lines)
        if entry[0] == "trait":
            _, t, slots, _decl = entry
            # "a trait value is an ordinary record: a receiver pointer plus one
            # function pointer per method, copied by value.  No dyn, no vtable
            # concept, no boxing, NO ALLOCATION."
            lines = ["struct %s {\n    void *%sself;\n" % (cname, GEN)]
            for slot, _name, _m, params, ret in slots:
                lines.append("    %s;\n" % self.fnptr(ret, params, slot))
            lines.append("};\n\n")
            return "".join(lines)
        if entry[0] == "enum":
            _, t, variants, _decl = entry
            lines = []
            lines.append("struct %s {\n    int32_t %stag;\n" % (cname, GEN))
            payloads = [(v, p) for v, p in variants if p is not None]
            if payloads:
                lines.append("    union {\n")
                for vname, pty in payloads:
                    lines.append("        %s;\n" % self.declarator(pty, sym_member(vname)))
                lines.append("    } %sdata;\n" % GEN)
            lines.append("};\n\n")
            return "".join(lines)
        if entry[0] == "array":
            _, t = entry
            return "struct %s {\n    %s;\n};\n\n" % (
                cname,
                self.declarator(t[2], "%selems[%d]" % (GEN, max(t[1], 1))),
            )
        if entry[0] == "union":
            _, t = entry
            members = tuple(sorted(t[1], key=tcode))
            lines = ["enum {\n"]
            for i, m in enumerate(members):
                lines.append("    %stag%s = %d,\n" % (GEN, tcode(m), i))
            lines.append("};\n")
            lines.append("struct %s {\n    int32_t %stag;\n    union {\n" % (cname, GEN))
            for m in members:
                lines.append("        %s;\n" % self.declarator(m, GEN + "m" + tcode(m)))
            lines.append("    } %sdata;\n};\n\n" % GEN)
            return "".join(lines)
        return ""

    def env_value(self, ety):
        """The `Env` main receives, with `argv` actually filled in.

        It was `(Env){0}` — a zeroed struct — so `env.argv.len` was 0 in every
        program ever compiled, and `zg_argc`/`zg_argv` were assigned in `main`
        and read by nothing. A compiler cannot be told what to compile that
        way, which is what made this the last thing between the tree and a
        fixpoint attempt.

        The rows are one `malloc` at startup and are never freed: they live
        exactly as long as the process, and `argv` itself is already static
        storage the C runtime owns. The Vec's `alloc` stays zeroed, so growing
        `env.argv` would fault — nobody grows argv, and the alternative is
        handing main's arena to a value built before any arena exists.
        """
        vec_decl = self.type_decl("Vec")
        str_decl = self.type_decl("str")
        if vec_decl is None or str_decl is None:
            return "(%s){0}" % self.ctype(ety)
        str_ty = ("named", str_decl.parts, ())
        vty = ("named", vec_decl.parts, (str_ty,))
        einfo = self.types.get(self.request_type(ety))
        if einfo is None or einfo[0] != "struct":
            return "(%s){0}" % self.ctype(ety)
        if not any(n == "argv" for n, _ in einfo[2]):
            return "(%s){0}" % self.ctype(ety)
        self.needs.add("argv")
        self.argv_vec_ctype = self.ctype(vty)
        self.argv_str_ctype = self.ctype(str_ty)
        self.argv_str_data = sym_member("data")
        self.argv_str_len = sym_member("len")
        vinfo = self.types.get(self.request_type(vty))
        names = [n for n, _ in vinfo[2]] if vinfo and vinfo[0] == "struct" else []
        self.argv_vec_fields = tuple(sym_member(n) for n in ("data", "len", "capacity")
                                     if n in names)
        return "((%s){ .%s = %sargv_vec(argc, argv) })" % (
            self.ctype(ety), sym_member("argv"), GEN)

    def entry_point(self):
        """`main`, the one name the C standard fixes for us."""
        cands = [d for d in self.by_name.get("main", []) if d.dkind == "fn"]
        if not cands:
            return ""
        decl = sorted(cands, key=lambda d: d.parts)[0]
        fnode = self.fn_node(decl.node)
        if fnode is None:
            return ""
        cname = sym_fn(decl.parts, self.overload_sig(decl, {}), ())
        ret = self.resolve_type(self.ret_of(fnode), {}, decl.scope_parts)
        nparams = len(self.params_of(fnode))
        args = []
        for p in self.params_of(fnode):
            pty = self.resolve_type(f(p, "ty"), {}, decl.scope_parts)
            if pty[0] == "named" and pty[1] and pty[1][-1] == "Env":
                args.append(self.env_value(pty))
            else:
                args.append("(%s){0}" % self.ctype(pty) if pty[0] != "prim" else "0")
        # argv_vec names the mangled Vec<str> and str types, so it cannot go
        # in the prelude: that is emitted BEFORE the type definitions. Here it
        # sits directly above `main`, after every type is complete.
        body = [self.argv_prelude() if "argv" in self.needs else ""]
        body.append("int main(int argc, char **argv) {\n")
        body.append("    %sargc = argc;\n    %sargv = argv;\n" % (GEN, GEN))
        call = "%s(%s)" % (cname, ", ".join(args) if nparams else "")
        info = self.enum_info(ret) if ret[0] == "named" else None
        if info:
            names = [v for v, _ in info[2]]
            ok = "Ok" if "Ok" in names else names[0]
            body.append("    %s r = %s;\n" % (self.ctype(ret), call))
            payload = dict(info[2]).get(ok)
            if payload is not None and is_int(payload):
                body.append(
                    "    if (r.%stag == %s) return (int)r.%sdata.%s;\n"
                    % (GEN, sym_variant(self.variant_parts(ret, ok)), GEN, sym_member(ok))
                )
            else:
                body.append(
                    "    if (r.%stag == %s) return 0;\n"
                    % (GEN, sym_variant(self.variant_parts(ret, ok)))
                )
            body.append("    return 1;\n")
        elif is_int(ret):
            body.append("    return (int)%s;\n" % call)
        else:
            body.append("    %s;\n    return 0;\n" % call)
        body.append("}\n")
        return "".join(body)


# ---------------------------------------------------------------------------
# per-function lowering
#
# Everything is lowered to statements plus a result temporary.  TESTING.md's
# nesting corpus is the reason: gen_c may not assume its output nesting is
# bounded by its input nesting, so a match, a block-as-value and any operation
# that traps all spill, and an expression deeper than MAX_EXPR_DEPTH spills too.
# ---------------------------------------------------------------------------


class FnCtx:
    def __init__(self, emitter, decl, subst, ret, self_ty=None):
        self.e = emitter
        self.decl = decl
        self.parts = decl.scope_parts
        self.subst = subst
        self.self_ty = self_ty
        self.ret = ret
        self.lines = []
        self.indent = 1
        self.scopes = [{}]
        self.counts = {}
        self.tmp = 0
        self.depth = 0
        self.loops = []      # (break, continue, result, type, acc, drop depth)
        self.inlining = 0    # inline depth, so a recursive body cannot spin
        self._bounds = None  # the bounds in scope, computed once on demand
        # RAII.  One list per emitted C block, in DECLARATION order; scope exit
        # walks it backwards.  This stack follows the emitted BRACES and not
        # `self.scopes`, which `inline_lambda` rewinds to the frame a closure
        # was written in -- a `.try()` inside an inlined body still has to
        # unwind the block it is physically standing in.
        self.dscopes = []
        # One entry per `dscopes` entry, in step with it: the block's defer
        # record, or None when nothing can register on that block.
        self.sscopes = []
        self.consumed = frozenset()  # names `consume`d anywhere in this body
        self.blk_ty = UNIT  # the type of the last block `_block_body` closed

    # -- output ------------------------------------------------------------

    def line(self, text):
        self.lines.append("    " * self.indent + text + "\n")

    def open(self, text="{"):
        self.line(text)
        self.indent += 1

    def close(self, text="}"):
        self.indent -= 1
        self.line(text)

    def text(self):
        return "".join(self.lines)

    def new_tmp(self, ty):
        self.tmp += 1
        name = "%st%d" % (GEN, self.tmp)
        if ty is not None and ty != UNIT:
            self.line(self.e.declarator(ty, name) + ";")
        return name

    # -- scopes ------------------------------------------------------------

    def push(self):
        self.scopes.append({})

    def pop(self):
        self.scopes.pop()

    def declare(self, name, ty, byref=False):
        n = self.counts.get(name, 0) + 1
        self.counts[name] = n
        cname = sym_local(name, n)
        # A by-reference binding reads as the pointee everywhere else, so
        # nothing downstream has to know how it was passed.
        self.scopes[-1][name] = ("(*%s)" % cname if byref else cname, ty)
        return cname

    def find(self, name):
        for scope in reversed(self.scopes):
            if name in scope:
                return scope[name]
        return None

    # -- RAII --------------------------------------------------------------
    #
    # "the compiler calls drop when a BINDING leaves scope, reverse
    # declaration order, exactly once."  So: only `let` bindings are tracked,
    # never temporaries, never parameters (passing a Drop value to a parameter
    # is a borrow), and never a match arm's payload binder, which names part
    # of a value somebody else still owns.
    #
    # `consume` is the exactly-once half, and it is not a straight-line fact:
    # a value may be moved on one path and not another.  A binding that is
    # consumed ANYWHERE in the body therefore carries a live flag, cleared at
    # the move and tested at every exit -- the same drop flag Rust uses, for
    # the same reason.  A flag costs one `int` on the frame; getting this
    # wrong statically costs a double free.

    def track_drop(self, name, cname, ty):
        """Register a binding for scope exit, if its type impls Drop."""
        if not self.dscopes or self.e.drop_impl(ty) is None:
            return
        flag = None
        if name in self.consumed:
            flag = self.label("live")
            self.line("int %s = 1;" % flag)
        self.dscopes[-1].append((cname, ty, flag))

    def kill_drop(self, node):
        """`consume x` -- x is somebody else's now, so this frame must not
        drop it."""
        if kind(node) != "Path":
            return
        got = self.find(str(f(node, "name", "")))
        if got is None:
            return
        for scope in self.dscopes:
            for cname, _ty, flag in scope:
                if cname == got[0] and flag is not None:
                    self.line("%s = 0;" % flag)
                    return

    def emit_drop(self, cname, ty, flag):
        decl = self.e.drop_impl(ty)
        if decl is None:
            return
        fn = self.e.request_fn(decl, tuple(ty[2]))
        arg = ("&" + cname) if self.e.drop_takes_address(decl) else cname
        call = "%s(%s);" % (fn, arg)
        self.line(("if (%s) { %s }" % (flag, call)) if flag else call)

    def unwind(self, entries, keep=None):
        """Drop one block's bindings, reverse declaration order.

        `keep` is the block's value expression: a binding named in it is
        being handed out of the block, so dropping it here would free what
        the caller is about to read.  Leaving it undropped leaks; dropping it
        is a use-after-free, and only one of those two is recoverable.
        """
        for cname, ty, flag in reversed(entries):
            if keep and re.search(r"\b%s\b" % re.escape(cname), keep):
                continue
            self.emit_drop(cname, ty, flag)

    def exit_scope(self, i, keep=None):
        """One block leaving: its defers run LIFO, and ALL of them run before
        ANY of its drops (DESIGN.md).  Every exit goes through here, so a
        defer that runs at three exits out of four is not expressible."""
        rec = self.sscopes[i]
        if rec is not None:
            self.line("%sscope_run(&%s);" % (GEN, rec))
        self.unwind(self.dscopes[i], keep)

    def unwind_to(self, depth, keep=None):
        """Every block from the innermost out to `depth`: what a non-local
        exit -- `.try()`, `h.break()`, `h.next()` -- leaves behind."""
        for i in reversed(range(depth, len(self.dscopes))):
            self.exit_scope(i, keep)

    # -- statements --------------------------------------------------------

    def block_value(self, block, want=None):
        """Emit a Block's statements; return its value expression, if any."""
        if block is None:
            return None
        if kind(block) != "Block":
            return self.expr(block)[0]
        self.dscopes.append([])
        self.sscopes.append(None)
        try:
            self.sscopes[-1] = self.scope_record(block)
            return self._block_body(block, want)
        finally:
            self.dscopes.pop()
            self.sscopes.pop()

    def scope_record(self, block):
        """This block's defer record, declared before its first statement.

        Only a block that writes `@scope` gets one: a nested block and a
        lambda body each get their own, which is what "it nests, and each
        block gets its own" means.  Its storage is automatic, so re-entering
        the block -- the next iteration of a loop -- starts an empty stack.
        """
        if not _writes_scope(block):
            return None
        self.e.needs.add("scope")
        rec = self.label("blk")
        self.line("%sscope %s;" % (GEN, rec))
        self.line("%s.%sn = 0;" % (rec, GEN))
        return rec

    def _block_body(self, block, want=None):
        stmts = list(f(block, "stmts", ()) or ())
        value = f(block, "value")
        if value is None and want not in (None, UNIT, UNKNOWN) and want is not INFER \
                and stmts:
            # "`0;` closes a `Res<i32, E>` function exactly as `Ok(0);` does"
            # -- a trailing expression statement IS the block's value when one
            # is wanted, and is left alone when it evaluates to nothing.
            #
            # Under INFER nothing is wanted yet: the question is what this
            # block HAS, and a semicolon-terminated statement is not it.
            # Promoting one would let `{ stored = false; h.break(); }` claim
            # a `Res<()>` it never produces, which types the whole match on
            # it and leaves its `()` sibling assigning 0 to a Res.
            last = stmts[-1]
            if kind(last) == "ExprStmt":
                _code, ty = self.peek(f(last, "expr"))
                if ty not in (UNIT, None):
                    value = f(last, "expr")
                    stmts = stmts[:-1]
        for stmt in stmts:
            self.stmt(stmt)
        here = len(self.dscopes) - 1
        entries = self.dscopes[here]
        if value is None:
            self.blk_ty = UNIT
            self.exit_scope(here)
            return None
        code, ty = self.expr(value, None if want is INFER else want)
        if want is not INFER:
            code = self.coerce(code, ty, want)
        rty = ty if want in (None, UNKNOWN) or want is INFER else want
        # the tail's type, for `ex_Block`: a block cannot report it any other
        # way, because finding it means running the block
        self.blk_ty = rty
        if rty == UNIT and code not in ("", "0"):
            # a tail expression of type `()` is the block's value in name
            # only: nothing can read it, so it has to RUN here.  Handing it
            # back instead loses a call whose whole purpose was its effect --
            # `() { cleanup(x) }` emitting nothing at all.
            self.line("(void)(%s);" % code)
            self.exit_scope(here)
            return "0"
        if not entries and self.sscopes[here] is None:
            return code
        if rty in (None, UNIT, UNKNOWN):
            self.exit_scope(here, code)
            return code
        # the block's value is read BEFORE its defers and its bindings die, so
        # it is spilled to a temporary and the cleanup runs against that
        tmp = self.new_tmp(rty)
        self.line("%s = %s;" % (tmp, code))
        self.exit_scope(here, code)
        return tmp

    def coerce(self, code, ty, want):
        """Hoisting, and only in the direction DESIGN.md allows.

        A bare `T` lifts into `Res<T>` wherever a `Res` is expected -- `0;`
        closes a `Res<i32, E>` function exactly as `Ok(0);` does -- and it
        fires only when exactly ONE variant carries the type.  Only success
        lifts: `Err` and `None` are always written.
        """
        if want in (None, UNKNOWN) or ty == want:
            return code
        if want[0] != "named":
            return code
        if self.e.is_trait(want) and ty not in (None, UNKNOWN) and ty[0] == "named" \
                and not self.e.is_trait(ty):
            return self.e.fat_value(self.addr_of(code, ty), ty, want)
        info = self.e.enum_info(want)
        if info is None:
            return code
        got = self.widen_res(code, ty, want)
        if got is not None:
            return got
        carriers = [v for v, p in info[2] if p is not None and p == ty]
        if len(carriers) != 1:
            return code
        return self.make_variant(want, carriers[0], code)

    def widen_res(self, code, ty, want):
        """A `Res` landing where a `Res` with a WIDER error set is expected.

        "The error type of a `Res` is a union, and propagation merges sets"
        (DESIGN.md, Errors) -- and `.try()` is not the only place a set
        merges.  Two match arms raising different sets meet at the match's
        own type, and that value has to be BUILT, not just named.

        Widening only, exactly as `emit_propagate` does it: every member
        keeps its own name, nothing converts, and a member with no home in
        the wider set gives None here so the caller reports it rather than
        the compiler inventing a reason.
        """
        if ty in (None, UNKNOWN) or ty[0] != "named" or ty[1] != want[1]:
            return None
        if len(ty[2]) != 2 or len(want[2]) != 2 or ty[2][0] != want[2][0]:
            return None
        if self.e.enum_info(ty) is None:
            return None
        # the value is read three times -- its tag and each payload -- so it
        # lands in a temporary first
        tmp = self.new_tmp(ty)
        self.line("%s = %s;" % (tmp, code))
        err = self.widen_error("%s.%sdata.%s" % (tmp, GEN, sym_member("Err")),
                               ty[2][1], want[2][1])
        if err is None:
            return None
        return "(%s.%stag == %s ? %s : %s)" % (
            tmp, GEN, sym_variant(self.e.variant_parts(ty, "Ok")),
            self.make_variant(want, "Ok",
                              "%s.%sdata.%s" % (tmp, GEN, sym_member("Ok"))),
            self.make_variant(want, "Err", err))

    def by_ref(self, code, ty):
        if _LVALUE.match(code):
            return "&" + code
        if code.startswith("(*") and code.endswith(")"):
            return code[2:-1]
        tmp = self.new_tmp(ty)
        self.line("%s = %s;" % (tmp, code))
        return "&" + tmp

    def by_ref_as(self, code, ty, want, fallback=None):
        """The address of an argument for a `::` parameter, at the type the
        parameter declares.

        A `::` parameter is a reference, so the ordinary answer is the
        argument's own address.  When the parameter names a TRAIT and the
        argument is concrete -- a String reaching `out :: Sink` -- the
        reference has to be to a fat value, not to the String: the record is
        what carries the function pointers.  It holds the String's address,
        so writes through it still land in the caller's buffer, which is the
        whole point of passing the sink by reference.
        """
        if want is not None and want[0] == "named" and self.e.is_trait(want) \
                and ty not in (None, UNKNOWN) and ty[0] == "named" \
                and not self.e.is_trait(ty):
            fat = self.e.fat_value(self.addr_of(code, ty), ty, want)
            tmp = self.new_tmp(want)
            self.line("%s = %s;" % (tmp, fat))
            return "&" + tmp
        return self.by_ref(code, fallback if fallback is not None else ty)

    def value(self, node, want=None):
        """Lower an expression at the type its destination expects.

        This is where a concrete value becomes a fat value: passing an Arena
        where an Alloc is wanted builds the record, at the argument, at the
        field, and at the return -- one rule, three sites.
        """
        if isinstance(node, tuple):
            return self.coerce(node[0], node[1], want)
        code, ty = self.expr(node, want)
        return self.coerce(code, ty, want)

    def addr_of(self, code, ty):
        """The receiver's address, without copying it where that would move
        the storage the record points at."""
        if _LVALUE.match(code):
            return "&" + code
        tmp = self.new_tmp(ty)
        self.line("%s = %s;" % (tmp, code))
        return "&" + tmp

    def stmt(self, node):
        k = kind(node)
        if k == "Let":
            self.let(node)
        elif k == "ExprStmt":
            self.expr_stmt(f(node, "expr"))
        elif k == "Block":
            self.push()
            self.open()
            self.block_value(node)
            self.close()
            self.pop()
        elif k in ("Struct", "Enum", "Alias", "Function", "Impl"):
            pass  # a nested declaration; collected, not emitted here
        else:
            self.expr_stmt(node)

    def let(self, node):
        name = f(node, "name")
        value = f(node, "value")
        declared = f(node, "ty")
        if not isinstance(name, str):
            # `self.len = ..` / `buf[i] = ..`: the target is an lvalue node
            target, _ty = self.expr(name)
            code, _vt = self.expr(value)
            self.line("%s = %s;" % (target, code))
            return
        existing = self.find(name)
        want = (
            self.e.resolve_type(declared, self.subst, self.parts, self.self_ty)
            if declared is not None
            else (existing[1] if existing else None)
        )
        code, ty = self.expr(value, want)
        if want not in (None, UNKNOWN):
            code = self.coerce(code, ty, want)
        if existing is not None and declared is None and not f(node, "mutable", False):
            # a second binding of a name already in scope is an assignment:
            # Zen writes a declaration and a store the same way
            self.line("%s = %s;" % (existing[0], code))
            return
        ty = want or ty or UNKNOWN
        if ty == UNKNOWN:
            self.e.error(node, "cannot infer a type for `%s`" % name)
        cname = self.declare(name, ty)
        self.line("%s = %s;" % (self.e.declarator(ty, cname), code))
        self.track_drop(name, cname, ty)

    def expr_stmt(self, node):
        if node is None:
            return
        k = kind(node)
        if k == "Binary" and f(node, "op") == "=":
            target, _ = self.expr(f(node, "lhs"))
            code, _ = self.expr(f(node, "rhs"))
            self.line("%s = %s;" % (target, code))
            return
        code, ty = self.expr(node)
        if code and code not in ("", "0"):
            self.line("(void)(%s);" % code)

    # -- expressions -------------------------------------------------------

    def expr(self, node, want=None):
        """-> (C expression text, resolved type).  May emit statements."""
        if node is None:
            return ("0", UNKNOWN)
        self.depth += 1
        try:
            if self.depth > MAX_EXPR_DEPTH:
                code, ty = self._expr(node, want)
                if ty not in (UNIT, UNKNOWN) and not code.isidentifier():
                    tmp = self.new_tmp(ty)
                    self.line("%s = %s;" % (tmp, code))
                    return (tmp, ty)
                return (code, ty)
            return self._expr(node, want)
        finally:
            self.depth -= 1

    def _expr(self, node, want=None):
        k = kind(node)
        method = getattr(self, "ex_" + k, None)
        if method is None:
            self.e.error(node, "gen_c cannot lower a %s expression" % k)
            return ("0", UNKNOWN)
        return method(node, want)

    # literals ------------------------------------------------------------

    def ex_Literal(self, node, want=None):
        lk = f(node, "kind")
        text = str(f(node, "text", ""))
        if lk == "int":
            value = parse_int(text)
            ty = want if is_int(want) else prim("i32")
            return (int_literal(value, ty), ty)
        if lk == "float":
            ty = want if want and want[0] == "prim" and want[1] in ("f32", "f64") else prim("f64")
            return (float_literal(text), ty)
        if lk == "bool":
            return ("true" if text.strip() in ("true", "1") else "false", prim("bool"))
        if lk == "char":
            return (str(decode_char(text)), prim("u8"))
        if lk == "str":
            return (self.str_literal(decode_str(text)), self.str_type())
        if lk == "unit":
            return ("0", UNIT)
        self.e.error(node, "unknown literal kind %r" % lk)
        return ("0", UNKNOWN)

    def str_type(self):
        decl = self.e.type_decl("str")
        return ("named", decl.parts, ()) if decl else prim("str")

    def str_names(self):
        decl = self.e.type_decl("str")
        if decl is None:
            return ("data", "len", False)
        return ("data", "len", True)

    def str_literal(self, raw: bytes):
        ty = self.str_type()
        cname = self.e.ctype(ty)
        data, length, user = self.str_names()
        dname = sym_member(data) if user else "data"
        lname = sym_member(length) if user else "len"
        return "((%s){ .%s = (unsigned char *)%s, .%s = %d })" % (
            cname,
            dname,
            c_string(raw),
            lname,
            len(raw),
        )

    def ex_Path(self, node, want=None):
        name = str(f(node, "name", ""))
        local = self.find(name)
        if local:
            return local
        variants = self.e.lookup(name, self.parts, "variant")
        if variants:
            return self.build_variant(variants, None, want, node)
        vals = self.e.lookup(name, self.parts, "value")
        if vals:
            d = vals[0]
            # A constant is inlined at its use, so a constant whose value
            # names itself would inline forever.  `seed_even = seed_odd + 1`
            # beside `seed_odd = seed_even + 1` has no order that computes
            # both -- modules.py says so across modules, and this says so
            # within one.  A crash is not a diagnostic.
            if d.key in self.e.expanding:
                ring = self.e.expanding[self.e.expanding.index(d.key):] + [d.key]
                self.e.error(node, "constant cycle: %s"
                                   % " -> ".join(k[2] for k in ring))
                return ("0", UNKNOWN)
            declared = f(d.node, "ty")
            if declared is not None:
                want = self.e.resolve_type(declared, self.subst, d.scope_parts) or want
            self.e.expanding.append(d.key)
            try:
                code, ty = self.expr(f(d.node, "value"), want)
            finally:
                self.e.expanding.pop()
            return (code, ty)
        fns = self.e.lookup(name, self.parts, "fn")
        if fns:
            d = fns[0]
            cn = self.e.request_fn(d, ())
            fnode = self.e.fn_node(d.node)
            ret = self.e.resolve_type(self.e.ret_of(fnode), {}, d.scope_parts)
            return (cn, ("fn", ret, ()))
        tys = self.e.lookup(name, self.parts, "type")
        if tys:
            return (name, ("named", tys[0].parts, ()))
        self.e.error(node, "unresolved name `%s`" % name)
        return ("0", UNKNOWN)

    def ex_Member(self, node, want=None):
        base = f(node, "base")
        name = str(f(node, "name", ""))
        # Type.NAME -- an enum variant, a type constant, or a module member
        if kind(base) == "Path":
            bname = str(f(base, "name", ""))
            if self.find(bname) is None:
                tdecl = self.e.type_decl(bname, self.parts)
                if bname in NUMERIC:
                    if tdecl is not None:
                        lit = self.type_member(tdecl, name, node)
                        if lit is not None:
                            return lit
                    got = self.e.builtin_type_const(bname, name)
                    if got is not None:
                        value, ty = got
                        return (int_literal(value, ty), ty)
                if tdecl is not None:
                    lit = self.type_member(tdecl, name, node)
                    if lit is not None:
                        return lit
                mod = self.module_named(bname)
                if mod is not None:
                    return self.module_member(mod, name, node)
        code, ty = self.expr(base)
        if ty is not None and ty[0] == "named":
            info = self.e.struct_info(ty)
            if info:
                for fname, fty in info[2]:
                    if fname == name:
                        return ("%s.%s" % (paren(code), sym_member(name)), fty)
                computed = self.computed_of(ty, name)
                if computed is not None:
                    return self.read_computed(ty, code, computed)
                method = self.method_of(ty, name)
                if method is not None:
                    return (method, UNKNOWN)
        if ty is not None and ty[0] == "prim" and ty[1] == "str" and name == "len":
            return ("%s.len" % paren(code), prim("usize"))
        self.e.error(node, "no member `%s` on this value" % name)
        return ("0", UNKNOWN)

    def type_member(self, tdecl, name, node, depth=0):
        node_t = tdecl.node
        if kind(node_t) == "Alias" and depth < 8:
            # "Alias.Circle exists, because Alias IS Shape": an alias is the
            # type it names, and reading a variant through it is not a
            # different question.
            target = f(node_t, "target")
            tname = f(target, "name", None) if target is not None else None
            if isinstance(tname, str):
                inner = self.e.type_decl(tname, tdecl.scope_parts)
                if inner is not None and inner is not tdecl:
                    return self.type_member(inner, name, node, depth + 1)
            return None
        if kind(node_t) == "Enum":
            # `Error = AllocError | IoError` writes no payload down, but each
            # variant carries its member, so `Error.IoError` alone is as
            # incomplete as `Shape.Circle` alone -- and answering it with a
            # tag beside uninitialised bytes would be the compiler inventing
            # the very value the union exists to carry.
            union = self.e.enum_is_union(tdecl)
            for v in f(node_t, "variants", ()) or ():
                if str(f(v, "name", "")) != name:
                    continue
                if union:
                    self.e.error(node, "`%s.%s` carries a value of type `%s` -- "
                                       "write `%s.%s(e)`"
                                 % (tdecl.name, name, name, tdecl.name, name))
                    ty = ("named", tdecl.parts, ())
                    return (self.make_variant(ty, name, None), ty)
                if f(v, "payload") is None:
                    ty = ("named", tdecl.parts, ())
                    return (self.make_variant(ty, name, None), ty)
                return None  # a payload variant: handled at the Call
        for c in list(f(node_t, "consts", ()) or ()) + list(f(node_t, "fields", ()) or ()):
            if str(f(c, "name", "")) != name:
                continue
            value = f(c, "value")
            if value is None:
                value = f(c, "default")
            if value is None:
                continue
            # `MAX*: i64 = 9223372036854775807` is read AT ITS DECLARED TYPE.
            # Lowering it at the literal's default width truncates the value
            # and, worse, makes the arithmetic that follows unable to overflow
            # -- the trap silently stops existing.
            declared = f(c, "ty")
            want = (self.e.resolve_type(declared, self.subst, tdecl.scope_parts)
                    if declared is not None else None)
            return self.expr(value, want)
        return None

    def module_named(self, name):
        """The module a bare name refers to: `a = alpha` then `a.total()`.

        A module alias is not a name imported *from* a module, so it does not
        appear in `scope`; matching the last component of a module's path is
        how `a` finds `alpha`, and the search is over a sorted tuple.
        """
        for base, _mod in self.e.mods:
            if base[-1] == name or ".".join(base) == name:
                return base
        # `a = alpha` is an alias whose target NAMES a module: one hop, and
        # only when nothing else answered, so a type never loses to a module
        for d in self.e.lookup(name, self.parts, "type"):
            target = f(d.node, "target")
            tname = f(target, "name", None) if target is not None else None
            if not isinstance(tname, str) or tname == name:
                continue
            for base, _mod in self.e.mods:
                if base[-1] == tname or ".".join(base) == tname:
                    return base
        for base, _mod in self.e.mods:
            if name in base:
                return base
        return None

    def module_member(self, base, name, node):
        for dkind in ("fn", "value", "type"):
            got = self.e.decls.get((base, name), [])
            got = [d for d in got if d.dkind == dkind]
            if got:
                if dkind == "fn":
                    cn = self.e.request_fn(got[0], ())
                    return (cn, UNKNOWN)
                if dkind == "value":
                    return self.expr(f(got[0].node, "value"))
                return (name, ("named", got[0].parts, ()))
        self.e.error(node, "module has no member `%s`" % name)
        return ("0", UNKNOWN)

    def owned_decls(self, ty, name, dkind):
        """Declarations owned by a type: its own members, and its impls'."""
        owner = ty[1][-1]
        module = ".".join(ty[1][:-1])
        out = [d for d in self.e.by_key.get((module, owner, name), []) if d.dkind == dkind]
        if not out:
            out = [
                d
                for d in self.e.by_name.get(name, [])
                if d.dkind == dkind and d.owner == owner
            ]
        return out

    def method_of(self, ty, name):
        got = self.owned_decls(ty, name, "fn")
        return self.e.request_fn(got[0], ()) if got else None

    def bounds_in_view(self):
        """The bounds this body was written under.

        "When two impls declare the same name, the bound in scope selects
        which is in view; with no bound to disambiguate it is an error --
        never file order."  Monomorphisation has already replaced `T` with the
        concrete type by the time gen_c runs, so the bound has to do the
        selecting from here rather than through the type.
        """
        if self._bounds is None:
            names = set(_bound_names(self.decl.node))
            if self.decl.owner:
                # a member's own body reads its own struct's fields: `Framed`
                # is the bound in scope inside `Framed.border`.
                names.add(self.decl.owner)
            self._bounds = names
        return self._bounds

    def computed_of(self, ty, name):
        """An impl-supplied field: computed, read-only, non-addressable."""
        got = self.owned_decls(ty, name, "value")
        if len(got) > 1:
            view = self.bounds_in_view()
            # an impl entry's parts end `target/trait/name`
            picked = [d for d in got if len(d.parts) >= 3 and d.parts[-2] in view]
            if len(picked) == 1:
                return picked[0]
        return got[0] if got else None

    def read_computed(self, ty, code, decl):
        """Re-evaluated on read, so it can never go stale (DESIGN.md)."""
        value = f(decl.node, "value")
        if value is None:
            value = f(decl.node, "default")
        if value is None:
            self.e.error(decl.node, "impl supplies no value for `%s`" % decl.name)
            return ("0", UNKNOWN)
        tmp = self.new_tmp(ty)
        self.line("%s = %s;" % (tmp, code))
        self.push()
        self.scopes[-1]["self"] = (tmp, ty)
        try:
            return self.expr(value)
        finally:
            self.pop()

    def ex_Index(self, node, want=None):
        base = f(node, "base")
        index = f(node, "index")
        bcode, bty = self.expr(base)
        icode, ity = self.expr(index, prim("usize"))
        if bty is not None and bty[0] == "array":
            file, line, col = self.e.pos.operator(node, base, index)
            helper = "idx_u" if not (is_int(ity) and int_info(ity)[0] < 0) else "idx_s"
            self.e.helpers.add(helper)
            checked = "%s%s(%s, %d, %s, %d, %d)" % (
                GEN,
                helper,
                icode,
                bty[1],
                c_string(file.encode("utf-8")),
                line,
                col,
            )
            return ("%s.%selems[%s]" % (paren(bcode), GEN, checked), bty[2])
        if bty is not None and bty[0] == "ptr":
            # a raw pointer carries no length: DESIGN.md bounds-checks fixed
            # arrays, and Vec.get returns a Res instead
            return ("%s[%s]" % (paren(bcode), icode), bty[1])
        if bty is not None and bty[0] == "named":
            # `s[i]` is `s.index(i)`: a type says what indexing means, and
            # `str.index` is where str's bounds check lives
            got = self.owned_decls(bty, "index", "fn")
            if got:
                return self.emit_call(got[0], node, [(icode, ity)], (), want,
                                      receiver=(bcode, bty))
        self.e.error(node, "value is not indexable")
        return ("0", UNKNOWN)

    def ex_Unary(self, node, want=None):
        op = f(node, "op")
        operand = f(node, "operand")
        code, ty = self.expr(operand, want)
        if op == "-":
            if kind(operand) == "Literal" and f(operand, "kind") == "int":
                value = -parse_int(str(f(operand, "text", "0")))
                t = want if is_int(want) else prim("i32")
                return (int_literal(value, t), t)
            if is_int(ty):
                file, line, col = self.e.pos.of(node)
                helper = "sub_" + ty[1]
                self.e.helpers.add(helper)
                return (
                    "%s%s(0, %s, %s, %d, %d)"
                    % (GEN, helper, code, c_string(file.encode("utf-8")), line, col),
                    ty,
                )
            return ("(-%s)" % paren(code), ty)
        if op == "!":
            return ("(!%s)" % paren(code), prim("bool"))
        if op == "&":
            return ("(&%s)" % paren(code), ("ptr", ty or UNKNOWN))
        self.e.error(node, "unknown unary operator %r" % op)
        return ("0", UNKNOWN)

    def ex_Consume(self, node, want=None):
        # `consume` is a move: the bytes are unchanged, so the value IS the
        # operand -- what changes is who drops it.  This frame no longer does.
        operand = f(node, "operand")
        got = self.expr(operand, want)
        self.kill_drop(operand)
        return got

    def ex_Binary(self, node, want=None):
        op = str(f(node, "op", ""))
        lhs, rhs = f(node, "lhs"), f(node, "rhs")
        if op == "=":
            target, tty = self.expr(lhs)
            code, _ = self.expr(rhs, tty)
            self.line("%s = %s;" % (target, code))
            return (target, tty)
        if op in ("&&", "||"):
            # short circuit, with the right-hand side's statements guarded
            lcode, _ = self.expr(lhs, prim("bool"))
            tmp = self.new_tmp(prim("bool"))
            self.line("%s = %s;" % (tmp, lcode))
            self.open("if (%s%s) {" % ("" if op == "&&" else "!", paren(tmp)))
            rcode, _ = self.expr(rhs, prim("bool"))
            self.line("%s = %s;" % (tmp, rcode))
            self.close()
            return (tmp, prim("bool"))
        # `a + b + c + ..` is LEFT-nested, so one python frame per term turns a
        # long line into a RecursionError -- and "a crash is not a diagnostic"
        # (TESTING.md).  Raising the interpreter's limit only moves the number,
        # so the spine is walked with a loop and folded outward.  The hint
        # travels DOWN the spine exactly as it did through the recursion, and
        # the operands are still evaluated left to right, so the emitted C is
        # the same C.
        spine = []
        cur, hint = node, want
        while True:
            cop = str(f(cur, "op", ""))
            hint = hint if cop in ARITH or cop in WRAPPING else None
            spine.append((cur, cop, hint))
            down = f(cur, "lhs")
            if kind(down) != "Binary" or str(f(down, "op", "")) in ("=", "&&", "||"):
                break
            cur = down
        base, _bop, hint = spine[-1]
        lhs, rhs = f(base, "lhs"), f(base, "rhs")
        if not is_int(hint) and kind(lhs) == "Literal" and f(lhs, "kind") == "int":
            # "an unannotated literal has no width yet" -- so the other side
            # decides, and `0 - (v % 10)` on an i64 stays an i64 instead of
            # being narrowed to the literal's default and trapping.
            other = self.peek(rhs)[1]
            if is_int(other):
                hint = other
        acc = self.expr(lhs, hint)
        deep = self.depth + len(spine) - 1
        for step, (cur, cop, _h) in enumerate(reversed(spine)):
            lhs, rhs = f(cur, "lhs"), f(cur, "rhs")
            lcode, lty = acc
            rcode, rty = self.expr(rhs, lty if is_int(lty) else None)
            acc = self.fold_binary(cur, cop, lhs, rhs, lcode, lty, rcode, rty)
            acc = self.spill(acc, deep - step)
        return acc

    def spill(self, got, depth):
        """`expr`'s rule, applied along a folded spine: past MAX_EXPR_DEPTH a
        value lands in a temporary rather than in one more layer of C."""
        code, ty = got
        if depth > MAX_EXPR_DEPTH and ty not in (UNIT, UNKNOWN) \
                and not code.isidentifier():
            tmp = self.new_tmp(ty)
            self.line("%s = %s;" % (tmp, code))
            return (tmp, ty)
        return got

    def fold_binary(self, node, op, lhs, rhs, lcode, lty, rcode, rty):
        ty = lty if lty not in (None, UNKNOWN) else rty
        if op in COMPARE:
            if op in ("==", "!=") and ty is not None and ty[0] == "named":
                # `Eq` is an ordinary struct and `str.impl(Eq, ..)` is where
                # str's equality is written, so `==` on a type that has one is
                # that call -- a C `==` on a struct is not even legal C.
                got = self.eq_call((lcode, ty), (rcode, rty or ty), node)
                if got is not None:
                    return ("(!%s)" % paren(got), prim("bool")) if op == "!=" \
                        else (got, prim("bool"))
            return ("(%s %s %s)" % (paren(lcode), op, paren(rcode)), prim("bool"))
        if op in WRAPPING:
            base = {"+%": "wadd", "-%": "wsub", "*%": "wmul"}[op]
            if is_int(ty):
                name = "%s_%s" % (base, ty[1])
                self.e.helpers.add(name)
                return ("%s%s(%s, %s)" % (GEN, name, lcode, rcode), ty)
            return ("(%s %s %s)" % (paren(lcode), op[0], paren(rcode)), ty)
        if op in ARITH:
            if is_int(ty):
                base = {"+": "add", "-": "sub", "*": "mul", "/": "div", "%": "mod"}[op]
                name = "%s_%s" % (base, ty[1])
                self.e.helpers.add(name)
                file, line, col = self.e.pos.operator(node, lhs, rhs)
                out = "%s%s(%s, %s, %s, %d, %d)" % (
                    GEN,
                    name,
                    lcode,
                    rcode,
                    c_string(file.encode("utf-8")),
                    line,
                    col,
                )
                tmp = self.new_tmp(ty)
                self.line("%s = %s;" % (tmp, out))
                return (tmp, ty)
            return ("(%s %s %s)" % (paren(lcode), op, paren(rcode)), ty)
        self.e.error(node, "unknown binary operator %r" % op)
        return ("0", UNKNOWN)

    # calls ---------------------------------------------------------------

    def ex_Call(self, node, want=None):
        callee = f(node, "callee")
        args = list(f(node, "args", ()) or ())
        targs = list(f(node, "targs", ()) or ())
        ck = kind(callee)

        if ck == "Path":
            name = str(f(callee, "name", ""))
            bound = self.find(name)
            if bound is not None and bound[1] is not None and bound[1][0] == "lambda":
                return self.inline_lambda(bound, self.arg_nodes(args), want, node)
            if name in ("println", "print") and not any(
                f(self.e.fn_node(d.node), "body") is not None
                for d in self.e.lookup(name, self.parts, "fn")
            ):
                return self.lower_print(node, args, newline=(name == "println"))
            named = any(kind(a) == "Arg" and f(a, "name") for a in args)
            fns = [d for d in self.e.lookup(name, self.parts, "fn")
                   if self.e.fn_node(d.node) is not None]
            # `Vec(alloc: a)` builds the struct; `Vec<Entry<K,V>>(a)` calls the
            # ufcs constructor beside it.  Named arguments are the
            # construction form -- "the same `name: value` form used at
            # construction" -- and a call never sees parameter names, so
            # positional arguments mean the function.
            if named or not fns:
                built = self.try_construct(name, node, args, targs, want)
                if built is not None:
                    return built
            variants = self.e.lookup(name, self.parts, "variant")
            if variants:
                payload = self.arg_nodes(args)
                return self.build_variant(variants, payload[0] if payload else None,
                                          want, node)
            got = self.call_named(name, node, args, targs, want)
            if got is not None:
                return got
        if ck == "Member":
            got = self.call_member(callee, node, args, targs, want)
            if got is not None:
                return got
        # a computed callee: a function value
        code, ty = self.expr(callee)
        argv = [self.expr(f(a, "value") if kind(a) == "Arg" else a)[0] for a in args]
        ret = ty[1] if ty and ty[0] == "fn" else UNKNOWN
        return ("%s(%s)" % (code, ", ".join(argv)), ret)

    def arg_nodes(self, args):
        return [f(a, "value") if kind(a) == "Arg" else a for a in args]

    def try_construct(self, name, node, args, targs, want):
        """`Point(x: 1, y: 2)`, `Shape.Circle(c)`, `[i32, 4](..)`."""
        tdecl = self.e.type_decl(name, self.parts)
        if tdecl is None:
            return None
        return self.construct_type(tdecl, node, args, targs, want)

    def construct_type(self, tdecl, node, args, targs, want):
        if kind(tdecl.node) == "Enum":
            return None  # a bare enum name is not a constructor
        targ_tys = tuple(self.e.resolve_type(t, self.subst, self.parts, self.self_ty) for t in targs)
        if not targ_tys and tdecl.tparams and want is not None and want[0] == "named" \
                and want[1] == tdecl.parts and len(want[2]) == len(tdecl.tparams):
            targ_tys = want[2]
        if not targ_tys and tdecl.tparams:
            targ_tys = self.infer_targs(tdecl, args)
        ty = ("named", tdecl.parts, targ_tys)
        info = self.e.struct_info(ty)
        if info is None:
            return None
        fields = dict(info[2])
        order = [fname for fname, _ in info[2]]
        values = {}
        positional = []
        for a in args:
            aname = f(a, "name") if kind(a) == "Arg" else None
            value = f(a, "value") if kind(a) == "Arg" else a
            if aname:
                values[str(aname)] = value
            else:
                positional.append(value)
        for i, value in enumerate(positional):
            if i < len(order):
                values.setdefault(order[i], value)
        defaults = _field_defaults(tdecl.node)
        inits = []
        for fname in order:
            if fname in values:
                code = self.value(values[fname], fields.get(fname))
                inits.append(".%s = %s" % (sym_member(fname), code))
            elif fname in defaults:
                code = self.value(defaults[fname], fields.get(fname))
                inits.append(".%s = %s" % (sym_member(fname), code))
        cname = self.e.ctype(ty)
        if not inits:
            return ("((%s){0})" % cname, ty)
        return ("((%s){ %s })" % (cname, ", ".join(inits)), ty)

    def infer_targs(self, tdecl, args):
        """Type arguments from the argument types, positionally by field."""
        info_fields = []
        node = tdecl.node
        for member in f(node, "fields", ()) or ():
            if not _is_fn_field(member):
                info_fields.append((str(f(member, "name", "")), f(member, "ty")))
        found = {}
        argmap = {}
        pos = []
        for a in args:
            aname = f(a, "name") if kind(a) == "Arg" else None
            value = f(a, "value") if kind(a) == "Arg" else a
            if aname:
                argmap[str(aname)] = value
            else:
                pos.append(value)
        for i, (fname, fty) in enumerate(info_fields):
            value = argmap.get(fname)
            if value is None and i < len(pos):
                value = pos[i]
            if value is None or fty is None:
                continue
            _code, aty = self.peek(value)
            self.unify(fty, aty, found)
        return tuple(found.get(tp, UNKNOWN) for tp in tdecl.tparams)

    def peek(self, node):
        """The type of an expression, speculatively: nothing is emitted and
        nothing is reported.  A peek runs outside the scope the real lowering
        will run in -- a match arm's binder is not bound yet -- so a
        diagnostic from one would be an error about a program that is fine."""
        saved = (list(self.lines), self.tmp, self.indent, len(self.e.diags))
        # ...and the WORKLIST, which is the half this used to miss.  A peek
        # that reaches a call requests the function it thinks is being called,
        # and a peek runs outside the real scope -- so a wrong guess left a
        # request for a function nobody calls, and gen_c emitted it.  That is
        # how `Map.get` at `K = ?` got monomorphised from a receiver whose
        # type was not yet known.  Speculation must cost nothing: anything
        # genuinely needed is requested again by the lowering that is real.
        marks = (len(self.e.worklist), set(self.e.done))
        try:
            code, ty = self.expr(node)
        finally:
            self.lines, self.tmp, self.indent = saved[0], saved[1], saved[2]
            del self.e.diags[saved[3] :]
            del self.e.worklist[marks[0] :]
            self.e.done = marks[1]
        return (code, ty)

    def peek_block(self, node):
        """The type of a Block's tail, speculatively.

        `peek` is not enough: `self.expr` on a Block asks this, so calling it
        here would not terminate.  And peeking the tail NODE alone answers
        nothing, because the tail reads bindings the block's own statements
        declare.  So the block is lowered for real into a buffer that is then
        thrown away, exactly as `peek` does."""
        saved = (list(self.lines), self.tmp, self.indent, len(self.e.diags))
        marks = (len(self.e.worklist), set(self.e.done))   # see `peek`
        self.push()
        try:
            self.block_value(node, INFER)
            return self.blk_ty
        finally:
            self.pop()
            del self.e.worklist[marks[0] :]
            self.e.done = marks[1]
            self.lines, self.tmp, self.indent = saved[0], saved[1], saved[2]
            del self.e.diags[saved[3] :]

    def unify(self, tynode, actual, found, tparams=None):
        if tynode is None or actual is None:
            return
        if kind(tynode) == "Named":
            name = str(f(tynode, "name", ""))
            args = f(tynode, "args", ()) or ()
            if not args and name not in PRIMS and self.is_tparam(name, tparams):
                found.setdefault(name, actual)
                return
            if actual[0] == "named" and args:
                for sub, act in zip(args, actual[2]):
                    self.unify(sub, act, found, tparams)
            if name in ("Ptr", "RawPtr") and actual[0] == "ptr" and args:
                self.unify(args[0], actual[1], found, tparams)

    def is_tparam(self, name, tparams=None):
        # The DECLARATION being instantiated says which names are its type
        # parameters.  `signed = <unsigned>(typedef: unsigned) unsigned` is
        # generic in `unsigned`, and a shape heuristic cannot know that.
        if tparams is not None:
            return name in tparams
        return name in self.subst or name in getattr(self, "_tparams", ()) or (
            len(name) <= 2 and name[0].isupper()
        )

    def call_named(self, name, node, args, targs, want):
        cands = self.e.lookup(name, self.parts, "fn")
        if not cands:
            return None
        argnodes = self.arg_nodes(args)
        decl = self.pick_overload(cands, argnodes)
        return self.emit_call(decl, node, argnodes, targs, want)

    def call_assoc(self, tdecl, name, node, args, targs, want):
        """`Duration.seconds(2)` -- a member called with no receiver.

        Returns None when the type has no such member, so an explicit-receiver
        `Type.method(v, ..)` still resolves the way it always did.
        """
        ty = ("named", tdecl.parts, ())
        owned = [d for d in self.owned_decls(ty, name, "fn")
                 if self.e.fn_node(d.node) is not None]
        cands = [d for d in owned if _is_assoc_fn(self.e, d)]
        if not cands:
            # The member exists but asks for a receiver. Lowering `D.millis(b)`
            # as a method put the TYPE in the receiver slot and emitted an
            # undeclared `D`; there is no spelling that reaches a method
            # through its type, so say that instead of emitting the C.
            if owned and self.module_named(tdecl.name) is None:
                self.e.error(node, "`%s.%s` takes a receiver -- write "
                                   "`value.%s(..)`" % (tdecl.name, name, name))
                return ("0", UNKNOWN)
            return None
        argnodes = self.arg_nodes(args)
        decl = self.pick_overload(cands, argnodes)
        if decl.otparams and len(targs) < len(decl.otparams):
            # With no receiver, the owner's type arguments have nowhere to
            # come from. Saying so is the point: monomorphising at UNKNOWN
            # would compile, and would be a different function.
            self.e.error(node, "`%s.%s` needs `%s`'s type arguments written "
                               "here: it is called with no receiver"
                         % (tdecl.name, name, tdecl.name))
            return ("0", UNKNOWN)
        return self.emit_call(decl, node, argnodes, targs, want)

    def call_member(self, callee, node, args, targs, want):
        base = f(callee, "base")
        name = str(f(callee, "name", ""))
        if name == "match":
            return None  # Match is its own node
        if kind(base) == "Path" and self.find(str(f(base, "name", ""))) is None:
            bname = str(f(base, "name", ""))
            tdecl = self.e.type_decl(bname, self.parts)
            if tdecl is not None and kind(tdecl.node) == "Enum":
                return self.construct_variant(tdecl, name, node, args, targs, want)
            if tdecl is not None:
                got = self.call_assoc(tdecl, name, node, args, targs, want)
                if got is not None:
                    return got
            base_parts = self.module_named(bname)
            if base_parts is not None:
                cands = [
                    d for d in self.e.decls.get((base_parts, name), []) if d.dkind == "fn"
                ]
                if cands:
                    argnodes = self.arg_nodes(args)
                    decl = self.pick_overload(cands, argnodes)
                    return self.emit_call(decl, node, argnodes, targs, want)
                # `a.beta_Gamma(tag: 3)` -- a TYPE reached through a module
                # binding.  Two modules may declare one name, so the module is
                # part of the question and not decoration.
                for d in self.e.decls.get((base_parts, name), []):
                    if d.dkind != "type":
                        continue
                    if kind(d.node) == "Enum":
                        return self.construct_variant(d, name, node, args,
                                                      targs, want)
                    return self.construct_type(d, node, args, targs, want)
        if kind(base) == "Path":
            bound = self.find(str(f(base, "name", "")))
            if bound is not None and bound[1] is not None and bound[1][0] == "loop":
                return self.lower_handle(bound, name, self.arg_nodes(args), node)
        rcode, rty = self.expr(base)
        argnodes = self.arg_nodes(args)
        if is_handle(rty):
            return self.lower_handle((rcode, rty), name, argnodes, node)
        if self.e.is_scope_ty(rty):
            return self.lower_defer(rcode, name, argnodes, node)
        if rty is not None and rty[0] == "ptr":
            got = self.ptr_method(rcode, rty, name, argnodes, node, targs)
            if got is not None:
                return got
        if rty is not None and rty[0] == "named":
            if self.e.is_trait(rty) and self.e.has_impl(rty):
                got = self.dispatch(rcode, rty, name, argnodes, targs, want, node)
                if got is not None:
                    return got
            # The type's own members AND its impls' -- `Key.impl(Eq, {eq = ..})`
            # is not a second mechanism, it is where Key's `eq` is written.
            cands = [d for d in self.owned_decls(rty, name, "fn")
                     if self.e.fn_node(d.node) is not None]
            with_body = [d for d in cands if f(self.e.fn_node(d.node), "body") is not None]
            # CASE 1, the static one: the receiver's type is known, so a
            # method the type does not define itself is the bound's own,
            # compiled for THIS receiver -- `self.eq(..)` inside it resolves
            # to the impl, and no record and no indirection take part.
            #
            # Both sets are ONE overload set: `Display` supplies a sealed
            # `toString(self, a: Alloc)` beside the impl's
            # `toString(self, sb :: String)`, and resolution picks between
            # them on the declared parameter type like anywhere else.
            inherited = self.trait_methods(rty, name)
            # and the free functions that travel with the type: "a method is
            # a UFCS function whose first parameter happens to be named self"
            # (DESIGN.md, Ownership), so these are not a fallback for when the
            # members miss -- they are in the same overload set, and the arity
            # picks between them.
            ufcs = self.ufcs_decls(name, rty)
            pool = list(with_body)
            for d in inherited + ufcs:
                if d not in pool:
                    pool.append(d)
            if pool:
                decl = self.pick_overload(pool, argnodes, receiver=(rcode, rty))
                own = any(d is decl for d in inherited)
                return self.emit_call(decl, node, argnodes, targs, want,
                                      receiver=(rcode, rty),
                                      self_ty=rty if own else None)
            if cands:
                decl = self.pick_overload(cands, argnodes, receiver=(rcode, rty))
                return self.emit_call(decl, node, argnodes, targs, want,
                                      receiver=(rcode, rty))
        # `out.add(fmt, ..)` on a sink: the format door, which is expanded
        # here rather than dispatched, so it is reached by name
        if name == "add" and rty is not None and rty[0] == "named" \
                and self.e.is_trait(rty):
            door = self.sink_door()
            if door is not None:
                return self.emit_call(door, node, argnodes, targs, want,
                                      receiver=(rcode, rty))
        # a ufcs free function: the receiver is the first parameter
        cands = self.ufcs_decls(name, rty)
        if not cands and rty is not None and rty[0] == "named":
            # ... or a bound's bodyless declaration, whose body is the backend
            cands = self.trait_methods(rty, name, needs_body=False)
        if cands:
            decl = self.pick_overload(cands, argnodes, receiver=(rcode, rty))
            return self.emit_call(decl, node, argnodes, targs, want, receiver=(rcode, rty))
        self.e.error(node, "no method `%s` on `%s`" % (name, ty_label(rty)))
        return ("0", UNKNOWN)

    def ufcs_decls(self, name, rty):
        """The free functions this receiver reaches through a dot.

        The FIRST PARAMETER is the gate, and it is the only one. A member of
        an unrelated type that happens to share the name is not a candidate:
        resolving `found.get(0)` by name across the program found `Map.get`
        for a `Vec`, instantiated it at `K = ?, V = ?`, and reported three
        diagnostics inside std/collections about code nothing called.

        A receiver whose type is not yet known therefore reaches nothing --
        which is the point. `peek` lowers a block's tail before the block's
        own statements have bound anything, so an unknown receiver there is
        an ordinary event and must not select a monomorphisation.
        """
        if rty is None or rty == UNKNOWN:
            return []
        out = []
        for d in self.e.lookup(name, self.parts, "fn") + self.e.by_name.get(name, []):
            if d.dkind != "fn" or d.owner or d in out:
                continue        # a member; its owner decides, not its name
            if not self.takes_receiver(d, rty):
                continue
            out.append(d)
        return out

    def takes_receiver(self, decl, rty):
        """Is the receiver what this function's first parameter asks for?"""
        fnode = self.e.fn_node(decl.node)
        params = self.e.params_of(fnode) if fnode else ()
        node = f(params[0], "ty") if params else None
        if node is None:
            return False
        if kind(node) == "Named" and str(f(node, "name", "")) in (decl.tparams or ()):
            # `loop*<R: Range<T>, T> = (range: R, ..)`: the first parameter IS
            # a type parameter, so what narrows the receiver is its BOUND, and
            # the bound is sema's question. From here it is a wildcard.
            return True
        # speculative: an unresolved type parameter here is not an error to
        # report, exactly as it is not one in `intrinsic`
        mark = len(self.e.diags)
        subst = dict((tp, UNKNOWN) for tp in decl.tparams)
        want = self.e.resolve_type(node, subst, decl.scope_parts)
        del self.e.diags[mark:]
        if want is None or want == UNKNOWN:
            return False
        if want[0] == "named":
            return rty[0] == "named" and (
                want[1][-1] == rty[1][-1]
                or self.satisfies(rty, ("named", want[1], ())))
        if want[0] == "prim":
            return rty[0] == "prim" and want[1] == rty[1]
        return want[0] == rty[0]

    def eq_call(self, lhs, rhs, node):
        """`a == b` on a type that impls `Eq`, as the call it is.

        Statically resolved: the receiver's type is known, so this is a direct
        call to the function the impl supplies and no record takes part.
        """
        ty = lhs[1]
        cands = [d for d in self.owned_decls(ty, "eq", "fn")
                 if self.e.fn_node(d.node) is not None
                 and f(self.e.fn_node(d.node), "body") is not None]
        if not cands:
            return None
        code, _rty = self.emit_call(cands[0], node, [rhs], (), prim("bool"),
                                    receiver=lhs)
        return code

    def trait_methods(self, rty, name, needs_body=True):
        """Methods the receiver's type satisfies but does not declare.

        The impl supplies the required members; everything sealed or default
        on the bound comes along, compiled once per receiver type.  All of
        them, because a bound may declare two of one name.

        `needs_body` is what tells a bound's DEFINITION from its signature.
        `Alloc.create` is declared with no body anywhere -- the backend is its
        body, exactly as it is for `Ptr`'s members -- so it is not a method to
        compile for this receiver, but it is still the receiver's own answer
        to `create` and nothing else in the program is.
        """
        out = []
        for d in sorted(self.e.by_name.get(name, []), key=lambda d: d.parts):
            if d.dkind != "fn" or not d.owner or d.owner == rty[1][-1]:
                continue
            bound = ("named", d.parts[:-1], ())
            # the member's owner has to be the bound ITSELF -- an impl entry's
            # parts end `target/trait/name`, and that is the impl's answer, not
            # the bound's own declaration.
            if self.e.struct_decl(bound) is None or bound[1][-1] != d.owner:
                continue
            fnode = self.e.fn_node(d.node)
            if fnode is None or (needs_body and f(fnode, "body") is None):
                continue
            if not self.satisfies(rty, bound):
                continue
            out.append(d)
        return out

    def satisfies(self, ty, trait):
        """Does this type have an impl for that trait?  A concrete type that
        declares the member itself counts too -- there is one declaration
        form and an impl is not a second mechanism."""
        if ty is None or ty[0] != "named":
            return False
        target = ty[1][-1]
        traitname = trait[1][-1]
        for d in self.e.by_name.values():
            for x in d:
                if x.owner == target and len(x.parts) >= 3 and x.parts[-2] == traitname:
                    return True
        decl = self.e.struct_decl(trait)
        if decl is None:
            return False
        # a type that already declares everything the bound asks for
        # satisfies it: storage counts, so `String` does not accidentally
        # satisfy `Vec` by having none of `capacity`.
        for m in f(decl.node, "fields", ()) or ():
            name = str(f(m, "name", "") or "")
            if not name:
                continue
            if _is_fn_field(m) and f(self.e.fn_node(m), "body") is not None:
                continue        # sealed or default: it comes along free
            if not [x for x in self.e.by_name.get(name, []) if x.owner == target]:
                return False
        return True

    def dispatch(self, rcode, rty, name, argnodes, targs, want, node):
        """CASE 2, the dynamic one: the value IS the trait, so the call goes
        through the record it carries."""
        slots = self.e.trait_slots(rty)
        matching = [s for s in slots if s[1] == name]
        if not matching:
            return None
        member = None
        for cand in matching:
            fnode = self.e.fn_node(cand[2])
            if len(self.e.params_of(fnode)) == len(argnodes) + 1:
                member = cand
                break
        member = member or matching[0]
        slot, _name, mnode, params, ret = member
        fnode = self.e.fn_node(mnode)
        if f(fnode, "body") is not None:
            return None  # sealed or default: an ordinary call, specialised
        recv = self.new_tmp(rty)
        self.line("%s = %s;" % (recv, rcode))
        # the caller's own instantiation, so the erased result can be rebuilt
        tdecl = self.e.trait_decl(rty)
        mdecl = Decl(tdecl.parts + (name,), mnode, "fn", name,
                     _tparam_names(mnode), owner=rty[1][-1], module=tdecl.module)
        own = self.infer_fn_targs(mdecl, fnode, argnodes, (recv, rty))
        subst = dict(zip(mdecl.tparams, own))
        real_params = [self.e.resolve_type(f(p, "ty"), subst, tdecl.scope_parts, rty)
                       for p in self.e.params_of(fnode)[1:]]
        real_ret = self.e.resolve_type(self.e.ret_of(fnode), subst, tdecl.scope_parts, rty)
        codes = []
        for i, value in enumerate(argnodes):
            pty = real_params[i] if i < len(real_params) else None
            code, aty = (value if isinstance(value, tuple) else self.expr(value, pty))
            codes.append(self.e.convert(code, pty or aty, params[i] if i < len(params) else None))
        for tp in mdecl.tparams:
            # the element size the slot's erasure dropped
            elem = subst.get(tp)
            codes.append("sizeof(%s)" % self.e.ctype(elem).strip()
                         if elem not in (None, UNKNOWN) else "1")
        call = "%s.%s(%s.%sself%s)" % (recv, slot, recv, GEN,
                                       "".join(", " + c for c in codes))
        if ret in (None, UNIT):
            self.line("%s;" % call)
            return ("0", UNIT)
        tmp = self.new_tmp(ret)
        self.line("%s = %s;" % (tmp, call))
        return (self.e.convert(tmp, ret, real_ret), real_ret or ret)

    def ptr_method(self, rcode, rty, name, argnodes, node, targs=()):
        """`Ptr<T>`'s members ARE the backend.

        mem_ptr.zen writes every one of them as a signature and says why:
        "the bodies belong to the backend: gen_c lowers a Ptr<T> to a `T*`
        and these members to dereference, indexed store, pointer arithmetic
        and memcpy.  They are written as signatures because there is nothing
        underneath to write them in."  This is that lowering.
        """
        elem = rty[1]
        cell = self.e.ctype(elem)

        def arg(i, ty=None):
            value = argnodes[i]
            if isinstance(value, tuple):
                return value[0]
            return self.expr(value, ty)[0]

        if name == "read" and len(argnodes) == 1:
            return ("%s[%s]" % (paren(rcode), arg(0, prim("usize"))), elem)
        if name == "write" and len(argnodes) == 2:
            self.line("%s[%s] = %s;" % (paren(rcode), arg(0, prim("usize")), arg(1, elem)))
            return ("0", UNIT)
        if name == "offset" and len(argnodes) == 1:
            return ("(%s + %s)" % (paren(rcode), arg(0, prim("usize"))), rty)
        if name == "back" and len(argnodes) == 1:
            return ("(%s - %s)" % (paren(rcode), arg(0, prim("usize"))), rty)
        if name == "bytes" and len(argnodes) == 1:
            return ("(sizeof(%s) * (size_t)%s)" % (cell, arg(0, prim("usize"))),
                    prim("usize"))
        if name == "copy_from" and len(argnodes) == 2:
            self.line("memcpy(%s, %s, sizeof(%s) * (size_t)%s);"
                      % (rcode, arg(0, rty), cell, arg(1, prim("usize"))))
            return ("0", UNIT)
        if name == "is_null" and not argnodes:
            return ("(%s == NULL)" % paren(rcode), prim("bool"))
        if name == "to" and len(argnodes) == 0:
            # `to<U>` must change the ELEMENT type: read, write, bytes and
            # copy_from all scale by it, so returning the receiver's own type
            # leaves them scaling by T.  Arena.realloc reads its usize header
            # through `.to<usize>()`, so as a no-op that read is ONE BYTE, and
            # every Vec whose buffer reaches 256 bytes silently loses the rows
            # written before each grow -- 512 & 0xFF == 0, so `keep` is 0 and
            # copy_from copies nothing.  Both bump and realloc truncate the
            # same way, which is why nothing ever errored.
            if targs:
                u = self.e.resolve_type(targs[0], self.subst, self.parts, self.self_ty)
                if u not in (None, UNKNOWN):
                    return ("((%s *)%s)" % (self.e.ctype(u).strip(), paren(rcode)),
                            ("ptr", u))
            return (rcode, rty)
        return None

    def pick_overload(self, cands, argnodes, receiver=None):
        """Resolution on arity and on declared parameter types.

        "a closure's type is its full signature", so a closure argument's
        PARAMETER COUNT is part of the arity question -- it is what tells
        `loop(range, (h, value) {..})` from `loop(range, (h, index, value)
        {..})`, which are otherwise the same two-argument call.
        """
        cands = sorted(cands, key=lambda d: d.parts)
        if len(cands) == 1:
            return cands[0]
        want = len(argnodes) + (1 if receiver is not None else 0)
        exact = []
        variadic = []
        loose = []
        for d in cands:
            fnode = self.e.fn_node(d.node)
            params = self.e.params_of(fnode) if fnode else ()
            n = len(params) if fnode else -1
            # `args: ...` is zero-or-more, so a variadic declares a MINIMUM
            # arity -- and a fixed arity that fits is the more specific
            # candidate, exactly as a concrete parameter beats a generic one.
            if params and _is_variadic(params[-1]):
                if want >= n - 1:
                    variadic.append(d)
                continue
            if n == want:
                exact.append(d)
            elif n in (want + 1, want - 1):
                loose.append(d)
        pool = exact or variadic or loose or cands
        shaped = []
        for d in pool:
            params = self.e.params_of(self.e.fn_node(d.node))
            ok = True
            for i, value in enumerate(argnodes):
                idx = i + (1 if receiver is not None else 0)
                if idx >= len(params) or kind(value) != "Lambda":
                    continue
                pty = f(params[idx], "ty")
                if pty is None or kind(pty) != "FnType":
                    continue
                if len(f(pty, "params", ()) or ()) != len(f(value, "params", ()) or ()):
                    ok = False
            if ok:
                shaped.append(d)
        pool = shaped or pool
        return self.by_param_types(pool, argnodes, receiver) if len(pool) > 1 else pool[0]

    def by_param_types(self, pool, argnodes, receiver):
        """"Resolution is on declared parameter types and arity."

        Two candidates that differ only in a parameter's type -- `digit(d:
        u64)` beside `digit(d: i64)` -- are the whole reason this is not an
        arity question.  Resolving them by file order picks the wrong one
        half the time, and on `0 - (v % 10)` that is a spurious trap.
        """
        # the receiver is the first parameter and nothing else -- so it is the
        # first argument here too, and `Square(..).label()` picks square's
        # `label` rather than the first one declared
        atys = [receiver[1]] if receiver is not None else []
        for value in argnodes:
            if isinstance(value, tuple):
                atys.append(value[1])
            elif kind(value) == "Lambda" or (
                    kind(value) == "Literal"
                    and f(value, "kind") in ("int", "float")):
                # "an unannotated literal has no width yet", so a NUMERIC one
                # says nothing about which candidate was meant.  A string or a
                # char does: its type is not open.
                atys.append(None)
            else:
                atys.append(self.peek(value)[1])
        best, score = None, None
        for d in pool:
            params = self.e.params_of(self.e.fn_node(d.node))
            hits, bad = 0, 0
            for idx, aty in enumerate(atys):
                if idx >= len(params) or aty in (None, UNKNOWN):
                    continue
                pnode = f(params[idx], "ty")
                pname = f(pnode, "name", None) if pnode is not None else None
                if isinstance(pname, str) and pname in d.tparams:
                    continue     # a generic parameter fits anything
                mark = len(self.e.diags)
                pty = self.e.resolve_type(pnode, {}, d.scope_parts)
                del self.e.diags[mark:]
                if pty in (None, UNKNOWN):
                    continue
                if pty == aty:
                    hits += 1
                elif pty[0] == "named" and aty[0] == "named":
                    # a concrete type is acceptable where a bound it impls is
                    # wanted, and nowhere else
                    if self.satisfies(aty, pty):
                        hits += 1
                    else:
                        bad += 1
                elif pty[0] != aty[0] or pty[0] == "prim":
                    bad += 1     # a different machine type: not this one
            if score is None or (-bad, hits) > score:
                best, score = d, (-bad, hits)
        return best if best is not None else pool[0]

    def build_variant(self, decls, payload_node, want, node):
        """`Ok(v)` / `None` / `Err(e)` written without their enum.

        The instance comes from what is expected -- a return type, a
        parameter, a field -- and otherwise from the payload, which is the
        only other thing that can fix a type parameter.  Nothing here guesses
        an error type: a `None` never becomes an `Err`.
        """
        decl = decls[0]
        enum_parts = decl.scope_parts
        vname = decl.name
        for cand in decls:  # prefer the arity the expected type asks for
            if want is not None and want[0] == "named" and want[1] == cand.parts[:-1]:
                decl = cand
                enum_parts = cand.parts[:-1]
                break
        ty = None
        if want is not None and want[0] == "named" and want[1] == enum_parts:
            ty = want
        edecl = None
        for d in self.e.by_name.get(enum_parts[-1], []):
            if d.dkind == "type" and d.parts == enum_parts:
                if ty is not None and len(d.tparams) != len(ty[2]):
                    continue
                edecl = d
                break
        if edecl is None:
            self.e.error(node, "unresolved variant `%s`" % vname)
            return ("0", UNKNOWN)
        payload_ty = None
        if ty is not None:
            info = self.e.enum_info(ty)
            payload_ty = dict(info[2]).get(vname) if info else None
        code = None
        if payload_node is not None:
            code, aty = self.expr(payload_node, payload_ty)
            if ty is None:
                # infer the enum's arguments from the payload we were given
                found = {}
                for v in f(edecl.node, "variants", ()) or ():
                    if str(f(v, "name", "")) == vname:
                        self.unify(f(v, "payload"), aty, found)
                ty = ("named", enum_parts,
                      tuple(found.get(tp, UNKNOWN) for tp in edecl.tparams))
        if ty is None:
            ty = ("named", enum_parts, tuple(UNKNOWN for _ in edecl.tparams))
        if any(a == UNKNOWN for a in ty[2]):
            self.e.error(node, "cannot infer the type of `%s` here" % vname)
        return (self.make_variant(ty, vname, code), ty)

    def construct_variant(self, tdecl, vname, node, args, targs, want):
        targ_tys = tuple(self.e.resolve_type(t, self.subst, self.parts, self.self_ty) for t in targs)
        if not targ_tys and tdecl.tparams and want is not None and want[0] == "named":
            if want[1] == tdecl.parts:
                targ_tys = want[2]
        if not targ_tys and tdecl.tparams:
            argnodes = self.arg_nodes(args)
            if argnodes:
                _c, aty = self.peek(argnodes[0])
                targ_tys = tuple(aty for _ in tdecl.tparams)
        ty = ("named", tdecl.parts, targ_tys)
        argnodes = self.arg_nodes(args)
        payload = None
        if argnodes:
            info = self.e.enum_info(ty)
            pty = dict(info[2]).get(vname) if info else None
            payload = self.expr(argnodes[0], pty)[0]
        return (self.make_variant(ty, vname, payload), ty)

    def make_variant(self, ty, vname, payload):
        cname = self.e.ctype(ty)
        tag = sym_variant(self.e.variant_parts(ty, vname))
        info = self.e.enum_info(ty)
        if info is not None and dict(info[2]).get(vname) is None:
            payload = None  # a `()` payload is no storage: `Ok(())` is a tag
        if payload is None:
            return "((%s){ .%stag = %s })" % (cname, GEN, tag)
        return "((%s){ .%stag = %s, .%sdata = { .%s = %s } })" % (
            cname,
            GEN,
            tag,
            GEN,
            sym_member(vname),
            payload,
        )

    def emit_call(self, decl, node, argnodes, targs, want, receiver=None, self_ty=None):
        fnode = self.e.fn_node(decl.node)
        if fnode is None:
            self.e.error(node, "`%s` is not callable" % decl.name)
            return ("0", UNKNOWN)
        params = list(self.e.params_of(fnode))
        if f(fnode, "body") is None and is_loop_shape(self.e, fnode):
            return self.lower_loop(decl, fnode, node, argnodes, want, receiver)
        if f(fnode, "body") is None:
            got = self.lower_intrinsic(decl, fnode, node, argnodes, want, receiver,
                                       targs)
            if got is not None:
                return got
        if f(fnode, "body") is None and decl.owner:
            # "A trait value is a fat value: a receiver pointer plus one
            # function pointer per method."  Which function a bodyless member
            # runs is decided by the impl behind that receiver, and gen_c has
            # no dispatch through the record yet -- so it says so rather than
            # emitting a call to a function nobody defines.
            self.e.error(node, "`%s.%s` is supplied by an impl; gen_c has no "
                               "trait dispatch yet" % (decl.owner, decl.name))
            subst0 = dict(zip(decl.tparams, tuple(UNKNOWN for _ in decl.tparams)))
            ret0 = self.e.resolve_type(self.e.ret_of(fnode), subst0, decl.scope_parts,
                                       self.e.self_type(decl, subst0))
            ret0 = refine(ret0, want)
            if ret0 in (None, UNIT, UNKNOWN):
                return ("0", UNIT)
            tmp = self.new_tmp(ret0)
            self.line("memset(&%s, 0, sizeof %s);" % (tmp, tmp))
            return (tmp, ret0)
        if any(kind(v) == "Lambda" for v in argnodes) and f(fnode, "body") is not None:
            return self.inline_call(decl, fnode, node, argnodes, targs, want, receiver)
        targ_tys = tuple(self.e.resolve_type(t, self.subst, self.parts, self.self_ty)
                         for t in targs)
        owner_tys = ()
        if decl.otparams:
            if receiver is not None and receiver[1] is not None and receiver[1][0] == "named":
                owner_tys = tuple(receiver[1][2])
            else:
                owner_tys = tuple(UNKNOWN for _ in decl.otparams)
        values = list(argnodes)
        # the instantiation FIRST: the receiver's own parameter type is
        # written in the declaration's type parameters (`unbox = <T>(b:
        # Box<T>)`), so resolving it before they are known reports an
        # `unknown type T` about a declaration that is perfectly well formed.
        own = decl.tparams[len(decl.otparams):]
        if own and len(targ_tys) != len(own):
            targ_tys = self.infer_fn_targs(decl, fnode, values, receiver, owner_tys)
        targ_tys = owner_tys + tuple(targ_tys)
        subst = dict(zip(decl.tparams, targ_tys))
        codes = []
        if receiver is not None:
            rwant = None
            if params:
                rwant = self.e.resolve_type(f(params[0], "ty"), subst,
                                            decl.scope_parts,
                                            self_ty or receiver[1])
            if params and f(params[0], "mutable", False):
                codes.append(self.by_ref_as(receiver[0], receiver[1], rwant,
                                            fallback=receiver[1]))
            else:
                codes.append(self.coerce(receiver[0], receiver[1], rwant))
        for i, value in enumerate(values):
            idx = i + (1 if receiver is not None else 0)
            pty = (
                self.e.resolve_type(f(params[idx], "ty"), subst, decl.scope_parts,
                                    self_ty or self.e.self_type(decl, subst))
                if idx < len(params)
                else None
            )
            if idx < len(params) and f(params[idx], "mutable", False):
                code, aty = (value if isinstance(value, tuple) else self.expr(value, pty))
                codes.append(self.by_ref_as(code, aty, pty, fallback=pty or aty))
            else:
                codes.append(self.value(value, pty))
        cname = self.e.request_fn(decl, targ_tys, self_ty)
        ret = self.e.resolve_type(self.e.ret_of(fnode), subst, decl.scope_parts,
                                  self_ty or self.e.self_type(decl, subst))
        return ("%s(%s)" % (cname, ", ".join(codes)), ret)


    # ---- closures ------------------------------------------------------
    #
    # "a body is a non-escaping stack closure, inlined at the call site, so
    # there is no closure record to box" -- loop_iter.zen states the claim
    # and tests/bench/bench_loop.zen gates it at allocs_op: 0.  So a lambda
    # is never a value here: passing one inlines the callee, and calling the
    # parameter it was bound to inlines the lambda.  Nothing is allocated and
    # nothing is boxed, which is the same sentence as the budget.

    def label(self, stem):
        self.tmp += 1
        return "%s%s%d" % (GEN, stem, self.tmp)

    def bind_closure(self, name, lam, pty, home):
        """A closure's free names mean what they meant WHERE IT WAS WRITTEN.

        Inlining puts the body inside the callee's frame, and `find`'s own
        `range.loop((h, value) { .. })` would otherwise shadow a caller's `h`
        -- silently, with a different value rather than with an error.  So the
        marker carries the depth of the scope stack it was written at, and
        `inline_lambda` restores it.

        `home` is the CALLER's depth, taken before `inline_call` pushed the
        callee's frame -- and taking it after was this compiler's one capture
        bug.  A lambda literal is written at the call site, so nothing the
        callee binds is in scope for it: not the callee's parameters, not the
        receiver bound under the first parameter's name, and not the callee's
        own locals, which `block_value` puts in that same frame rather than a
        nested one.  Keeping that frame is what made `(b > 0).then(() {
        println("{}", b) })` print `true`: `bool.then`'s first parameter is
        also spelled `b`, so the closure's own `b` found the receiver.
        """
        self.scopes[-1][name] = (name, ("lambda", lam, pty, home,
                                        (self.subst, self.parts, self.self_ty)))

    def inline_call(self, decl, fnode, node, argnodes, targs, want, receiver=None):
        """Inline a function that was handed a closure."""
        if self.inlining > INLINE_DEPTH:
            self.e.error(node, "inlining `%s` did not terminate" % decl.name)
            return ("0", UNKNOWN)
        params = list(self.e.params_of(fnode))
        offset = 1 if receiver is not None else 0
        owner_tys = ()
        if decl.otparams and receiver is not None and receiver[1] is not None \
                and receiver[1][0] == "named":
            owner_tys = tuple(receiver[1][2])
        elif decl.otparams:
            owner_tys = tuple(UNKNOWN for _ in decl.otparams)
        own = decl.tparams[len(decl.otparams):]
        targ_tys = tuple(self.e.resolve_type(t, self.subst, self.parts, self.self_ty)
                         for t in targs)
        if own and len(targ_tys) != len(own):
            targ_tys = self.infer_fn_targs(decl, fnode, argnodes, receiver, owner_tys)
        subst = dict(zip(decl.tparams, owner_tys + tuple(targ_tys)))
        base = decl.scope_parts
        self_ty = self.e.self_type(decl, subst)

        # the callee's parameter types, resolved once
        ptys = [self.e.resolve_type(f(p, "ty"), subst, base, self_ty) for p in params]
        ret = refine(self.e.resolve_type(self.e.ret_of(fnode), subst, base, self_ty), want)

        result = self.new_tmp(ret) if ret not in (None, UNIT, UNKNOWN) else None
        home = len(self.scopes)   # the caller's depth: every lambda argument
                                  # below was written HERE, not in the frame
                                  # the next line opens
        self.push()
        if receiver is not None and params:
            self.scopes[-1][str(f(params[0], "name", "self"))] = receiver
        for i, value in enumerate(argnodes):
            idx = i + offset
            if idx >= len(params):
                break
            pname = str(f(params[idx], "name", "_"))
            pty = ptys[idx]
            if kind(value) == "Lambda":
                self.bind_closure(pname, value, pty, home)
                continue
            code, aty = self.expr(value, pty)
            ty = pty if pty != UNKNOWN else aty
            # the argument crosses a boundary here exactly as it does at a
            # real call, so an Arena reaching an `alloc: Alloc` builds the
            # record rather than being copied into a differently shaped slot
            self.line("%s = %s;" % (self.e.declarator(ty, self.declare(pname, ty)),
                                    self.coerce(code, aty, pty)))
        saved_subst, saved_parts, saved_self = self.subst, self.parts, self.self_ty
        self.subst, self.parts, self.self_ty = subst, base, self_ty
        self.inlining += 1
        self.open()
        value = self.block_value(f(fnode, "body"), ret)
        if result is not None and value is not None:
            self.line("%s = %s;" % (result, value))
        self.close()
        self.inlining -= 1
        self.subst, self.parts, self.self_ty = saved_subst, saved_parts, saved_self
        self.pop()
        return (result if result is not None else "0", ret or UNIT)

    def inline_lambda(self, bound, argnodes, want, node):
        """Call a parameter that a closure was bound to."""
        _name, marker = bound
        lam, pty = marker[1], marker[2]
        params = list(f(lam, "params", ()) or ())
        want_params = ()
        ret = None
        if pty is not None and pty != UNKNOWN and pty[0] == "fn":
            ret, want_params = pty[1], pty[2]
        if ret in (None, UNKNOWN):
            ret = want
        result = self.new_tmp(ret) if ret not in (None, UNIT, UNKNOWN) else None
        # the arguments are written where the CALL is, so they are lowered
        # before the frame moves
        lowered = []
        for i, p in enumerate(params):
            declared = self.e.resolve_type(f(p, "ty"), self.subst, self.parts, self.self_ty) \
                if f(p, "ty") is not None else None
            expect = declared if declared not in (None, UNKNOWN) else (
                want_params[i] if i < len(want_params) else None)
            if i >= len(argnodes):
                self.e.error(node, "closure parameter `%s` has no argument"
                             % str(f(p, "name", "_")))
                lowered.append(None)
                continue
            value = argnodes[i]
            if isinstance(value, tuple):     # an already-lowered value
                code, aty = value
            else:
                code, aty = self.expr(value, expect)
            lowered.append((code, aty, expect))
        # back to the frame the closure was written in, so its free names
        # cannot be captured by the callee it was inlined into
        home = None
        if len(marker) > 4:
            home = (self.scopes, self.subst, self.parts, self.self_ty)
            self.scopes = self.scopes[:marker[3]]
            self.subst, self.parts, self.self_ty = marker[4]
        self.push()
        for p, got in zip(params, lowered):
            if got is None:
                continue
            pname = str(f(p, "name", "_"))
            code, aty, expect = got
            ty = expect if expect not in (None, UNKNOWN) else aty
            if is_handle(ty) or (aty is not None and aty[0] == "loop"):
                self.scopes[-1][pname] = (code, aty)
                continue
            cn = self.declare(pname, ty)
            self.line("%s = %s;" % (self.e.declarator(ty, cn), code))
        self.inlining += 1
        self.open()
        value = self.block_value(f(lam, "body"), ret)
        if result is not None and value is not None:
            self.line("%s = %s;" % (result, value))
        self.close()
        self.inlining -= 1
        self.pop()
        if home is not None:
            self.scopes, self.subst, self.parts, self.self_ty = home
        return (result if result is not None else "0", ret or UNIT)

    # ---- the loop intrinsic --------------------------------------------

    def lower_loop(self, decl, fnode, node, argnodes, want, receiver=None):
        """One of `loop_iter.zen`'s six signatures, as a C loop.

        `h.break(v)` and `h.next()` are the general non-local exit, so they
        are `goto`s rather than C's `break`/`continue`: an inlined body can
        sit inside a `switch` that a match produced, where a C `break` would
        leave the switch and not the loop.
        """
        args = list(argnodes)
        if receiver is not None:
            args = [receiver] + args
        body = args[-1] if args else None
        if body is None or (not isinstance(body, tuple) and kind(body) != "Lambda"):
            self.e.error(node, "a loop body must be written at the call site")
            return ("0", UNKNOWN)
        params = list(self.e.params_of(fnode))
        inner = f(f(params[-1], "ty"), "params", ()) or ()
        names = [str(f(p, "name", "")) for p in inner]
        wants_index = "index" in names[1:]
        wants_value = "value" in names[1:]
        wants_acc = "acc" in names[1:]

        ret = want if want not in (None, UNKNOWN) else None
        brk, cnt = self.label("brk"), self.label("cnt")

        lead = args[:-1]
        cond_node = None
        range_val = None
        init_val = None
        if lead:
            first = lead[0]
            if kind(first) == "Lambda" and not (f(first, "params", ()) or ()):
                cond_node = first              # while cond
            else:
                range_val = self.expr(first, None) if not isinstance(first, tuple) else first
            if len(lead) > 1:
                init_val = self.expr(lead[1], None)

        if ret is None:
            # "the loop evaluates to the final acc", and `h.break(value)`
            # makes it an expression too -- so a loop whose value nothing
            # asked for still HAS one, and the `.match` on it needs its type.
            el = init_val[1] if (wants_acc and init_val) else \
                self.range_elem(range_val)
            if el not in (None, UNIT, UNKNOWN):
                rdecl = self.e.type_decl("Res", self.parts, 1)
                if rdecl is not None:
                    ret = ("named", rdecl.parts, (el,))
        result = self.new_tmp(ret) if ret not in (None, UNIT, UNKNOWN) else None

        acc = None
        if wants_acc and init_val is not None:
            acc = self.new_tmp(init_val[1])
            self.line("%s = %s;" % (acc, init_val[0]))
        if result is not None:
            self.line("%s = %s;" % (result, self.none_of(ret, node)))

        counter = None
        limit = None
        base = None
        if range_val is not None:
            start, end = self.range_bounds(range_val, node)
            counter = self.new_tmp(prim("usize"))
            limit = self.new_tmp(prim("usize"))
            # `index` counts ITERATIONS and `value` is what the range holds,
            # so on `Range(10, 13)` they are 0,1,2 and 10,11,12 -- one name
            # for both would make the two indistinguishable exactly when the
            # range does not start at zero.
            base = self.new_tmp(prim("usize"))
            self.line("%s = %s;" % (counter, start))
            self.line("%s = %s;" % (base, counter))
            self.line("%s = %s;" % (limit, end))
            self.open("while (%s < %s) {" % (counter, limit))
        elif wants_index:
            counter = self.new_tmp(prim("usize"))
            self.line("%s = 0;" % counter)
            self.open("for (;;) {")
        elif cond_node is not None:
            self.open("for (;;) {")
            code, _ty = self.inline_lambda(("cond", ("lambda", cond_node, None)),
                                           (), prim("bool"), node)
            self.open("if (!%s) {" % paren(code))
            self.line("goto %s;" % brk)
            self.close()
        else:
            self.open("for (;;) {")

        self.loops.append((brk, cnt, result, ret, acc, len(self.dscopes)))
        handle = ("loop", len(self.loops))
        values = [(handle[0] and "0", handle)]
        if wants_index:
            values.append((("(%s - %s)" % (counter, base)) if base is not None
                           else counter, prim("usize")))
        if wants_value:
            values.append(self.range_value(range_val, counter, node))
        if wants_acc and acc is not None:
            values.append((acc, init_val[1]))
        # "acc threads through iterations, the loop evaluates to the final
        # acc" -- so the body is lowered AT the accumulator's type, or its
        # value has nowhere to land
        got = self.inline_lambda(("body", ("lambda", body, None)), tuple(values),
                                 init_val[1] if (wants_acc and init_val) else None,
                                 node)
        if wants_acc and acc is not None and got[0] not in ("0", None):
            self.line("%s = %s;" % (acc, got[0]))
        self.line("%s: ;" % cnt)
        if counter is not None:
            self.line("%s = %s + 1;" % (counter, counter))
        self.close()
        self.loops.pop()
        # Normal completion only, and it MUST precede the label: `h.break(v)`
        # writes `result` and jumps to `brk` (see lower_break), so an
        # assignment after the label overwrites the value the break carried
        # and the fold silently returns its accumulator instead.
        if wants_acc and acc is not None and result is not None:
            self.line("%s = %s;" % (result, self.ok_of(ret, acc, node)))
        self.line("%s: ;" % brk)
        return (result if result is not None else "0", ret or UNIT)

    def lower_intrinsic(self, decl, fnode, node, argnodes, want, receiver, targs=()):
        if decl.name in ("println", "print") and decl.owner == "Console":
            # "stdout / stderr.  This is what `println` resolves to."  Nothing
            # impls Console: it is the capability itself, so its one method is
            # the backend's, like Ptr's members are.
            self.lower_print(node, [a for a in argnodes],
                             newline=(decl.name == "println"))
            ret = self.e.resolve_type(self.e.ret_of(fnode), {}, decl.scope_parts)
            if ret in (None, UNIT, UNKNOWN):
                return ("0", UNIT)
            return (self.ok_of(ret, None, node), ret)
        params = self.e.params_of(fnode)
        if params and _is_variadic(params[-1]):
            got = self.lower_format_call(decl, fnode, node, argnodes, receiver)
            if got is not None:
                return got
        if decl.owner == "Alloc" and decl.name == "create" and receiver is not None:
            got = self.lower_create(decl, fnode, node, targs, want, receiver)
            if got is not None:
                return got
        return self._lower_intrinsic(decl, fnode, node, argnodes, want, receiver)

    # ---- the format door -------------------------------------------------
    #
    # "`{}` routes through each argument's toString, which is TYPE-directed,
    # so the call is expanded where it is written: the compiler steps
    # text_fmt.fmt_next over `fmt` and emits an `add_bytes` for each literal
    # run and a `toString` for each hole.  No runtime format state, no
    # varargs walk, and one implementation of the format rules."  This is
    # that expansion; the rules it implements are text_fmt.zen's.

    @staticmethod
    def fmt_pieces(raw):
        """text_fmt.zen's format language, in full: `{}` is a hole, every
        other byte -- including a lone `{` and every `}` -- is literal."""
        out, run, i = [], bytearray(), 0
        while i < len(raw):
            if raw[i:i + 2] == b"{}":
                out.append((bytes(run), True))
                run = bytearray()
                i += 2
            else:
                run.append(raw[i])
                i += 1
        out.append((bytes(run), False))
        return out

    def free_fn(self, name, arity):
        """A writer text_fmt declares, by name: this expansion is the
        backend's, so it reaches the one implementation directly rather than
        through the caller's imports."""
        for d in sorted(self.e.by_name.get(name, []), key=lambda d: d.parts):
            if d.dkind != "fn" or d.owner:
                continue
            fnode = self.e.fn_node(d.node)
            if fnode is None or f(fnode, "body") is None:
                continue
            if len(self.e.params_of(fnode)) == arity:
                return d
        return None

    def sink_door(self):
        """text_fmt's `add(out :: Sink, fmt: str, args: ...)`.

        Reached by name for the same reason the other writers are -- the
        expansion is the backend's, so it must not depend on whether the
        caller happened to import text_fmt.  Bodyless, so `free_fn` (which
        wants a definition) is the wrong finder: this door has no body
        anywhere, because the compiler IS its body.
        """
        for d in sorted(self.e.by_name.get("add", []), key=lambda d: d.parts):
            if d.dkind != "fn" or d.owner:
                continue
            fnode = self.e.fn_node(d.node)
            if fnode is None or f(fnode, "body") is not None:
                continue
            params = self.e.params_of(fnode)
            if len(params) == 3 and _is_variadic(params[-1]):
                return d
        return None

    def full_of(self, ret, node):
        """The Err a piece that could not be written produces.

        Two error sets meet at `add` -- the buffer fails to GROW, the
        signature says `IoError` -- and DESIGN.md has no conversion between
        them.  `IoError.Full` is "no room: a fixed buffer, a full disk",
        which is what a buffer that cannot grow is, so the reason is named
        rather than invented (law 4).  `Res<String, AllocError>` has one
        variant and it is exact.
        """
        info = self.e.enum_info(ret)
        ety = dict(info[2]).get("Err") if info else None
        if ety is None:
            return self.none_of(ret, node)
        einfo = self.e.enum_info(ety)
        names = [v for v, p in (einfo[2] if einfo else ()) if p is None]
        if not names:
            return self.none_of(ret, node)
        pick = "Full" if "Full" in names else names[0]
        return self.make_variant(ret, "Err", self.make_variant(ety, pick, None))

    def write_piece(self, got, result, ret, done, node):
        """One write, and the short circuit that keeps a failure visible."""
        if got is None:
            return
        code, gty = got
        if gty is None or self.e.enum_info(gty) is None:
            self.line("(void)(%s);" % code)
            return
        tmp = self.new_tmp(gty)
        self.line("%s = %s;" % (tmp, code))
        ok = sym_variant(self.e.variant_parts(gty, "Ok"))
        self.open("if (%s.%stag != %s) {" % (tmp, GEN, ok))
        self.line("%s = %s;" % (result, self.full_of(ret, node)))
        self.line("goto %s;" % done)
        self.close()

    def write_hole(self, sb, value, node):
        """`{}` on one argument: type-directed, resolved here."""
        code, ty = (value if isinstance(value, tuple) else self.expr(value))
        if ty is not None and ty[0] == "prim" and ty[1] in INT_VALUES:
            name = "add_i64" if INT_VALUES[ty[1]][0] < 0 else "add_u64"
            wide = prim("i64" if name == "add_i64" else "u64")
            d = self.free_fn(name, 2)
            if d is not None:
                return self.emit_call(d, node, [("(%s)%s" % (
                    "int64_t" if name == "add_i64" else "uint64_t",
                    paren(code)), wide)], (), None, receiver=sb)
        if ty is not None and ty[0] == "prim" and ty[1] == "bool":
            d = self.free_fn("add_bool", 2)
            if d is not None:
                return self.emit_call(d, node, [(code, ty)], (), None, receiver=sb)
        if ty is not None and ty == self.str_type():
            return self.write_bytes(sb, (code, ty), node)
        if ty is not None and ty[0] == "named":
            # a Display: it writes into the buffer that is already open, so
            # nesting never allocates
            for d in self.owned_decls(ty, "toString", "fn"):
                fnode = self.e.fn_node(d.node)
                if fnode is None or f(fnode, "body") is None:
                    continue
                if len(self.e.params_of(fnode)) != 2:
                    continue
                return self.emit_call(d, node, [sb], (), None, receiver=(code, ty))
        self.e.error(node, "cannot format a value of this type")
        return None

    def write_bytes(self, sb, arg, node):
        """A literal run, or a `{}` that landed on a str: bytes, verbatim.

        A concrete String is written through its own `add_bytes` -- a direct
        call, no record -- and a Sink through the `write` it declares, which
        is the one the console also answers.  Same bytes, two floors, and
        which one applies is the receiver's type.
        """
        if sb[1] is not None and sb[1][0] == "named" and self.e.is_trait(sb[1]):
            got = self.dispatch(sb[0], sb[1], "write", [arg], (), None, node)
            if got is not None:
                return got
        for name in ("add_bytes", "write"):
            for cand in self.owned_decls(sb[1], name, "fn"):
                if self.e.fn_node(cand.node) is not None:
                    return self.emit_call(cand, node, [arg], (), None, receiver=sb)
        self.e.error(node, "this sink has no `write` to write through")
        return None

    def lower_format(self, sb, fmt_node, rest, result, ret, done, node):
        if not (kind(fmt_node) == "Literal" and f(fmt_node, "kind") == "str"):
            self.e.error(node, "a format string is read at compile time, so it "
                               "must be written at the call site")
            return
        pieces = self.fmt_pieces(decode_str(str(f(fmt_node, "text", ""))))
        holes = sum(1 for _r, h in pieces if h)
        if holes != len(rest):
            self.e.error(node, "the format string has %d hole(s) and the call "
                               "passes %d argument(s)" % (holes, len(rest)))
        n = 0
        for run, hole in pieces:
            if run:
                self.write_piece(self.write_bytes(sb, (self.str_literal(run),
                                                       self.str_type()), node),
                                 result, ret, done, node)
            if hole and n < len(rest):
                self.write_piece(self.write_hole(sb, rest[n], node),
                                 result, ret, done, node)
                n += 1

    def call_method(self, recv, name, args, node):
        """A method call gen_c writes for itself, resolved the way a written
        one is: the impl when the receiver is concrete, the record when the
        receiver IS the bound."""
        rcode, rty = recv
        if rty is None or rty[0] != "named":
            return None
        if self.e.is_trait(rty) and self.e.has_impl(rty):
            got = self.dispatch(rcode, rty, name, args, (), None, node)
            if got is not None:
                return got
        cands = [d for d in self.owned_decls(rty, name, "fn")
                 if self.e.fn_node(d.node) is not None
                 and f(self.e.fn_node(d.node), "body") is not None]
        inherited = self.trait_methods(rty, name)
        pool = cands + [d for d in inherited if d not in cands]
        if not pool:
            return None
        decl = self.pick_overload(pool, args, receiver=recv)
        own = any(d is decl for d in inherited)
        return self.emit_call(decl, node, args, (), None, receiver=recv,
                              self_ty=rty if own else None)

    def lower_create(self, decl, fnode, node, targs, want, receiver):
        """`alloc.create<T>()` -- "one typed convenience, a default built on
        raw" (DESIGN.md).  std declares it and writes no body, so the body is
        the backend's: `raw` hands back bytes and `Ptr.to` names them.
        """
        elem = None
        if targs:
            elem = self.e.resolve_type(targs[0], self.subst, self.parts, self.self_ty)
        if elem in (None, UNKNOWN) and want is not None and want[0] == "named":
            info = self.e.enum_info(want)
            ok = dict(info[2]).get("Ok") if info else None
            if ok is not None and ok[0] == "ptr":
                elem = ok[1]
        if elem in (None, UNKNOWN):
            self.e.error(node, "cannot infer what `create` is asked to make")
            return ("0", UNKNOWN)
        # ALIGN_MAX: mem_arena.zen aligns every run it re-requests to the
        # strictest alignment any Zen value needs, so asking for it here is
        # asking for what the arena would have given anyway.
        args = [("sizeof(%s)" % self.e.ctype(elem).strip(), prim("usize")),
                ("16", prim("usize"))]
        got = self.call_method(receiver, "raw", args, node)
        if got is None:
            return None
        subst = dict(zip(decl.tparams, (elem,)))
        ret = self.e.resolve_type(self.e.ret_of(fnode), subst, decl.scope_parts,
                                  self.e.self_type(decl, subst))
        return (self.e.convert(got[0], got[1], ret), ret)

    def lower_format_call(self, decl, fnode, node, argnodes, receiver):
        """The two bodyless variadic doors: `sb.add(fmt, ..)` and the
        allocating `alloc.String(fmt, ..)`."""
        args = list(argnodes)
        # `sb.add(fmt, ..)` on a String, and `out.add(fmt, ..)` on any Sink --
        # the same door, expanded the same way.  The second is a ufcs free
        # function so that a sink needs no slot for something the compiler
        # writes, and it is what a `toString` holding a console goes through
        if (decl.name == "add" and receiver is not None
                and decl.owner in ("String", None)):
            ret = self.e.resolve_type(self.e.ret_of(fnode), {}, decl.scope_parts,
                                      self.e.self_type(decl, {}))
            result = self.new_tmp(ret)
            done = self.label("fmt")
            self.line("%s = %s;" % (result, self.ok_of(ret, None, node)))
            if args:
                self.lower_format(receiver, args[0], args[1:], result, ret,
                                  done, node)
            self.line("%s: ;" % done)
            return (result, ret)
        if decl.owner is None and decl.name == "String" and receiver is not None:
            # `alloc.String("{}", x)`: the empty form, then the same
            # expansion `add` gets -- which is what keeps one set of rules
            empty = self.free_fn("String", 1)
            if empty is None:
                return None
            made = self.emit_call(empty, node, [], (), None, receiver=receiver)
            ret = made[1]
            result = self.new_tmp(ret)
            done = self.label("fmt")
            tmp = self.new_tmp(ret)
            self.line("%s = %s;" % (tmp, made[0]))
            self.line("%s = %s;" % (result, tmp))
            ok = sym_variant(self.e.variant_parts(ret, "Ok"))
            self.open("if (%s.%stag != %s) {" % (tmp, GEN, ok))
            self.line("goto %s;" % done)
            self.close()
            info = self.e.enum_info(ret)
            sty = dict(info[2]).get("Ok") if info else None
            sb = ("%s.%sdata.%s" % (tmp, GEN, sym_member("Ok")), sty)
            if args:
                self.lower_format(sb, args[0], args[1:], result, ret, done, node)
            self.line("%s = %s;" % (result, self.make_variant(ret, "Ok", sb[0])))
            self.line("%s: ;" % done)
            return (result, ret)
        return None

    def field_of(self, ty, name):
        info = self.e.struct_info(ty)
        for fname, fty in (info[2] if info else ()):
            if fname == name:
                return sym_member(fname), fty
        return None, None

    def lower_mem(self, decl, fnode, node, argnodes, receiver):
        """`Mem` is the page authority, and nothing impls it.

        "page authority: env.mem.alloc() makes an arena" -- these three are
        where memory enters the program, so they are the backend's, the same
        way `Ptr`'s members and `Console.println` are.  Everything above them
        is ordinary Zen.
        """
        name = decl.name
        base = decl.scope_parts
        ret = self.e.resolve_type(self.e.ret_of(fnode), {}, base)
        recv = receiver[0] if receiver is not None else "0"

        if name == "alloc":
            arena = ret
            state_m, state_t = self.field_of(arena, "state")
            if state_m is None or state_t is None or state_t[0] != "ptr":
                self.e.error(node, "Mem.alloc needs an Arena with a state pointer")
                return ("0", ret)
            st = state_t[1]
            cell = self.e.ctype(st)
            tmp = self.new_tmp(state_t)
            self.line("%s = (%s *)malloc(sizeof(%s));" % (tmp, cell, cell))
            for fname, value in (("mem", recv), ("head", "NULL"), ("next", "0")):
                m, _t = self.field_of(st, fname)
                if m:
                    self.line("%s->%s = %s;" % (tmp, m, value))
            return ("((%s){ .%s = %s })" % (self.e.ctype(arena), state_m, tmp), arena)

        if name == "page":
            info = self.e.enum_info(ret)
            if info is None:
                self.e.error(node, "Mem.page must return a Res")
                return ("0", ret)
            payload = dict(info[2])
            pty = payload.get("Ok")
            page = pty[1] if pty is not None and pty[0] == "ptr" else None
            if page is None:
                self.e.error(node, "Mem.page must return a Res<Ptr<Page>, E>")
                return ("0", ret)
            cell = self.e.ctype(page)
            size = self.value(argnodes[0], prim("usize")) if argnodes else "0"
            prev = self.value(argnodes[1], pty) if len(argnodes) > 1 else "NULL"
            raw = self.new_tmp(("ptr", prim("u8")))
            szt = self.new_tmp(prim("usize"))
            out = self.new_tmp(ret)
            self.line("%s = (size_t)%s;" % (szt, paren(size)))
            self.line("%s = (unsigned char *)malloc(sizeof(%s) + %s);" % (raw, cell, szt))
            self.open("if (%s == NULL) {" % raw)
            self.line("%s = %s;" % (out, self.err_value(ret, payload.get("Err"), node)))
            self.close("} else {")
            self.indent += 1
            for fname, value in (("prev", prev),
                                 ("base", "(%s + sizeof(%s))" % (raw, cell)),
                                 ("size", szt)):
                m, mt = self.field_of(page, fname)
                if m:
                    self.line("((%s *)%s)->%s = %s;" % (
                        cell, raw, m, self.e.convert(value, None, mt) if False else value))
            self.line("%s = %s;" % (out, self.make_variant(ret, "Ok", "(%s *)%s" % (cell, raw))))
            self.close()
            return (out, ret)

        if name == "release":
            page = self.value(argnodes[0], None) if argnodes else "NULL"
            self.line("free((void *)%s);" % paren(page))
            return ("0", UNIT)
        return None

    # ---- the filesystem capability ---------------------------------------

    #: FsError, by the ordinal PRELUDE_FS returns.  The names are env.zen's;
    #: the number never leaves the generated C, and this is the one table
    #: that maps between them.
    FS_ERRORS = ("NotFound", "Denied", "IsDir", "Failed")

    def str_parts(self, value, node):
        """A `str` argument as (bytes, length), spilled once.

        A `str` is a pointer and a count, and both are read -- so the value
        lands in a temporary first or a call in the argument gets made twice.
        """
        code, ty = value if isinstance(value, tuple) else self.expr(value, self.str_type())
        if ty is None or ty[0] != "named":
            self.e.error(node, "a path is a `str`")
            return None
        dm, _dt = self.field_of(ty, "data")
        lm, _lt = self.field_of(ty, "len")
        if dm is None or lm is None:
            self.e.error(node, "a path is a `str`")
            return None
        tmp = self.new_tmp(ty)
        self.line("%s = %s;" % (tmp, code))
        return ("(const unsigned char *)%s.%s" % (tmp, dm), "%s.%s" % (tmp, lm))

    def fs_err(self, ret, ety, rc, out, node):
        """`rc` -> `Err(<the variant it names>)`, written as the chain it is.

        Reading the variant out of the enum rather than out of a number is
        what lets env.zen reorder or rename its own error set without the
        backend agreeing to it in secret.
        """
        info = self.e.enum_info(ety) if ety is not None else None
        names = [v for v, p in (info[2] if info else ()) if p is None]
        chain = [n for n in self.FS_ERRORS if n in names]
        if not chain:
            self.line("%s = %s;" % (out, self.err_value(ret, ety, node)))
            return
        for name in chain[:-1]:
            self.open("if (%s == %d) {" % (rc, self.FS_ERRORS.index(name) + 1))
            self.line("%s = %s;" % (out, self.make_variant(
                ret, "Err", self.make_variant(ety, name, None))))
            self.close("} else {")
            self.indent += 1
        # the last one is the plain `else`: the helper returns exactly the
        # ordinals above, so a chain that tested all of them would end in a
        # branch nothing can reach -- and an unreachable arm naming a reason
        # is how a wrong reason gets reported later
        self.line("%s = %s;" % (out, self.make_variant(
            ret, "Err", self.make_variant(ety, chain[-1], None))))
        for _name in chain[:-1]:
            self.close()

    def lower_stdin(self, decl, fnode, node, argnodes, receiver):
        """`Stdin.read` -- the one way a byte stream enters a program.

        env.zen writes it as a signature and says why: it is the authority
        itself, reached only as `env.in`.  The floor is `fread` on stdin,
        which is plain C99, so it is a `needs` of its own and not the
        filesystem's -- a program reading a pipe must not be handed
        <sys/stat.h> for it.

        IT ALLOCATES NOTHING.  There is no Alloc in the signature, so by law 1
        there is no memory either: it fills the SPARE CAPACITY of a run the
        caller already owns, and `Vec.reserve` is what makes that room.  The
        buffer arrives BY ADDRESS because the parameter is written `::`, and
        the three fields it reads are the ones that say where the run is, how
        much of it is written, and how wide it is.
        """
        if len(argnodes) != 2:
            return None
        base = decl.scope_parts
        ret = self.e.resolve_type(self.e.ret_of(fnode), {}, base)
        params = self.e.params_of(fnode)
        vty = self.e.resolve_type(f(params[1], "ty"), {}, base) if len(params) > 1 else None
        dm, _dt = self.field_of(vty, "data")
        lm, _lt = self.field_of(vty, "len")
        cm, _ct = self.field_of(vty, "capacity")
        if dm is None or lm is None or cm is None:
            self.e.error(node, "Stdin.read must take a Vec<u8>")
            return ("0", ret)
        self.e.needs.add("stdin")

        info = self.e.enum_info(ret)
        ety = dict(info[2]).get("Err") if info else None
        buf = self.new_tmp(("ptr", vty))
        want = self.new_tmp(prim("usize"))
        got = self.new_tmp(prim("usize"))
        rc = self.new_tmp(prim("i32"))
        out = self.new_tmp(ret)
        self.line("%s = &(%s);" % (buf, self.value(argnodes[0], vty)))
        self.line("%s = %s;" % (want, self.value(argnodes[1], prim("usize"))))
        self.line("%s = zg_stdin_read((unsigned char *)%s->%s, %s->%s, %s->%s, %s, &%s);"
                  % (rc, buf, dm, buf, lm, buf, cm, want, got))
        # the two failures a byte-counted read has, and no more: the room was
        # too small, or the stream broke.  END OF INPUT IS NEITHER -- it is
        # Ok(0) -- so there is no third arm and nothing here reports it.
        self.open("if (%s == ZG_IO_FULL) {" % rc)
        self.line("%s = %s;" % (out, self.make_variant(
            ret, "Err", self.make_variant(ety, "Full", None))
            if ety is not None else self.make_variant(ret, "Err", None)))
        self.close("} else { if (%s != 0) {" % rc)
        self.indent += 1
        self.line("%s = %s;" % (out, self.make_variant(
            ret, "Err", self.make_variant(ety, "Closed", None))
            if ety is not None else self.make_variant(ret, "Err", None)))
        self.close("} else {")
        self.indent += 1
        self.line("%s->%s = %s->%s + %s;" % (buf, lm, buf, lm, got))
        self.line("%s = %s;" % (out, self.make_variant(ret, "Ok", got)))
        self.close()
        self.close()
        return (out, ret)

    def lower_fs(self, decl, fnode, node, argnodes, receiver):
        """`Fs`'s three members ARE the backend.

        env.zen writes them as signatures and says why: "reached only as
        `env.fs` -- law 2, no ambient authority".  Nothing impls Fs, because
        Fs is the authority itself, exactly as Console and Mem are.
        """
        name = decl.name
        base = decl.scope_parts
        ret = self.e.resolve_type(self.e.ret_of(fnode), {}, base)
        if not (name == "read" and len(argnodes) == 2) and not (
                name in ("exists", "is_dir") and len(argnodes) == 1) and not (
                name == "write" and len(argnodes) == 2):
            return None
        # only now: a program that never reaches one of these members must not
        # pay for <sys/stat.h>
        self.e.needs.add("fs")

        if name in ("exists", "is_dir"):
            path = self.str_parts(argnodes[0], node)
            if path is None:
                return ("0", prim("bool"))
            test = "== 1" if name == "is_dir" else ">= 0"
            return ("(zg_fs_kind(%s, %s) %s)" % (path[0], path[1], test), prim("bool"))

        if name == "write":
            info = self.e.enum_info(ret)
            ety = dict(info[2]).get("Err") if info else None
            path = self.str_parts(argnodes[0], node)
            data = self.str_parts(argnodes[1], node)
            if path is None or data is None:
                return ("0", ret)
            rc = self.new_tmp(prim("i32"))
            out = self.new_tmp(ret)
            self.line("%s = zg_fs_write(%s, %s, %s, %s);" % (
                rc, path[0], path[1], data[0], data[1]))
            self.open("if (%s != 0) {" % rc)
            self.fs_err(ret, ety, rc, out, node)
            self.close("} else {")
            self.indent += 1
            self.line("%s = %s;" % (out, self.make_variant(ret, "Ok", None)))
            self.close()
            return (out, ret)

        # Res<String, FsError>: the buffer the Alloc hands out, wrapped in the
        # owner that tells the same story every other buffer in std tells.
        info = self.e.enum_info(ret)
        payload = dict(info[2]) if info else {}
        sty = payload.get("Ok")
        ety = payload.get("Err")
        # AT the declared type: `a` arrives as an Arena and the signature says
        # Alloc, so lowering it at its own type would store the arena in the
        # Vec's `alloc` field instead of the two-word handle onto it. The
        # declaration is what says which -- law 7.
        params = self.e.params_of(fnode)
        aty = self.e.resolve_type(f(params[1], "ty"), {}, base) if len(params) > 1 else None
        alloc = (self.value(argnodes[0], aty), aty)
        path = self.str_parts(argnodes[1], node)
        if sty is None or path is None:
            self.e.error(node, "Fs.read must return a Res<String, FsError>")
            return ("0", ret)

        want = self.new_tmp(prim("usize"))
        got = self.new_tmp(prim("usize"))
        rc = self.new_tmp(prim("i32"))
        out = self.new_tmp(ret)
        self.line("%s = 0;" % want)
        self.line("%s = 0;" % got)
        self.line("%s = zg_fs_size(%s, %s, &%s);" % (rc, path[0], path[1], want))
        self.open("if (%s != 0) {" % rc)
        self.fs_err(ret, ety, rc, out, node)
        self.close("} else {")
        self.indent += 1
        # the run itself.  ALIGN_MAX, as `create` asks for: it is what the
        # arena would have given anyway, and it keeps the size header the
        # arena writes ahead of every run intact, so a String read off the
        # disk still grows through the ordinary realloc.
        run = self.call_method(alloc, "raw", [(want, prim("usize")),
                                              ("16", prim("usize"))], node)
        if run is None:
            self.e.error(node, "Fs.read needs an Alloc")
            return (out, ret)
        self.fs_run(ret, ety, sty, run, alloc, want, got, rc, out, path, node)
        self.close()
        return (out, ret)

    def fs_run(self, ret, ety, sty, run, alloc, want, got, rc, out, path, node):
        """The Ok half: bytes into the run, run into a String."""
        rinfo = self.e.enum_info(run[1])
        ok = dict(rinfo[2]).get("Ok") if rinfo else None
        buf = self.new_tmp(ok if ok is not None else ("ptr", prim("u8")))
        tag = "%s.%stag" % (run[0], GEN)
        self.open("if (%s != %s) {" % (
            tag, sym_variant(self.e.variant_parts(run[1], "Ok"))))
        # the one failure an allocation has, named in FsError's own set --
        # there is no From, so the seed's single enum has to carry it.
        self.line("%s = %s;" % (out, self.make_variant(
            ret, "Err", self.make_variant(ety, "OutOfMemory", None))
            if ety is not None else self.make_variant(ret, "Err", None)))
        self.close("} else {")
        self.indent += 1
        self.line("%s = %s.%sdata.%s;" % (buf, run[0], GEN, sym_member("Ok")))
        self.line("%s = zg_fs_read(%s, %s, (unsigned char *)%s, %s, &%s);"
                  % (rc, path[0], path[1], buf, want, got))
        self.open("if (%s != 0) {" % rc)
        self.fs_err(ret, ety, rc, out, node)
        self.close("} else {")
        self.indent += 1
        self.line("%s = %s;" % (out, self.make_variant(
            ret, "Ok", self.fs_string(sty, buf, got, want, alloc, node))))
        self.close()
        self.close()

    def fs_string(self, sty, buf, got, want, alloc, node):
        """A String over a run the Alloc already owns.

        `String` IS its `Vec<u8>` and the Vec's fields are collections'
        private business, so this is the one place the backend writes them --
        the same licence `lower_mem` takes with an ArenaState, and for the
        same reason: the memory enters the program here.
        """
        dm, vty = self.field_of(sty, "data")
        if dm is None or vty is None:
            self.e.error(node, "Fs.read must return a Res<String, FsError>")
            return "(%s){0}" % self.e.ctype(sty)
        inits = []
        # len is what ARRIVED and capacity is what was asked for: a short read
        # must not leave the String claiming bytes nobody ever wrote, and the
        # run really is `want` wide, which is what grow may reuse
        for fname, value in (("data", buf), ("len", got), ("capacity", want)):
            m, _mt = self.field_of(vty, fname)
            if m:
                inits.append(".%s = %s" % (m, value))
        m, mt = self.field_of(vty, "alloc")
        if m:
            inits.append(".%s = %s" % (m, self.e.convert(alloc[0], alloc[1], mt)))
        vec = "((%s){ %s })" % (self.e.ctype(vty), ", ".join(inits))
        return "((%s){ .%s = %s })" % (self.e.ctype(sty), dm, vec)

    def err_value(self, ret, ety, node):
        """`Err(OutOfMemory)` -- the one failure a page request has."""
        if ety is None:
            return self.make_variant(ret, "Err", None)
        info = self.e.enum_info(ety)
        names = [v for v, p in (info[2] if info else ()) if p is None]
        inner = self.make_variant(ety, names[0], None) if names else "(%s){0}" % self.e.ctype(ety)
        return self.make_variant(ret, "Err", inner)

    def _lower_intrinsic(self, decl, fnode, node, argnodes, want, receiver):
        if decl.owner == "Mem" and decl.name in ("alloc", "page", "release"):
            got = self.lower_mem(decl, fnode, node, argnodes, receiver)
            if got is not None:
                return got
        if decl.owner == "Fs" and decl.name in ("read", "write", "exists", "is_dir"):
            got = self.lower_fs(decl, fnode, node, argnodes, receiver)
            if got is not None:
                return got
        if decl.owner == "Stdin" and decl.name == "read":
            got = self.lower_stdin(decl, fnode, node, argnodes, receiver)
            if got is not None:
                return got
        """The bodyless declarations whose bodies ARE the backend.

        `to_u64* = (self: u8) u64` and `null_ptr* = <T>() Ptr<T>` are written
        as signatures for the same reason `Ptr`'s members are: there is
        nothing underneath to write them in.  Conversions are methods rather
        than a cast keyword, so this is where the cast lives.
        """
        name = decl.name
        # speculative: the caller may not be an intrinsic at all, so an
        # unresolved type parameter here is not an error to report
        mark = len(self.e.diags)
        subst = dict((tp, UNKNOWN) for tp in decl.tparams)
        ret = self.e.resolve_type(self.e.ret_of(fnode), subst, decl.scope_parts)
        del self.e.diags[mark:]
        if name.startswith("to_") and (receiver is not None or argnodes):
            target = name[3:]
            if target in PRIMS:
                value = receiver if receiver is not None else None
                if value is None:
                    v = argnodes[0]
                    value = v if isinstance(v, tuple) else self.expr(v)
                return ("(%s)%s" % (PRIMS[target], paren(value[0])), prim(target))
        if name == "null_ptr":
            ty = ret if ret is not None and ret[0] == "ptr" and ret[1] != UNKNOWN else (
                want if want is not None and want[0] == "ptr" else ("ptr", prim("u8")))
            return ("((%s)NULL)" % self.e.ctype(ty).strip(), ty)
        return None

    def range_bounds(self, range_val, node):
        """`start` and `end`, which every Range supplies -- stored on
        `Range(0, n)` and computed by an impl on a Vec."""
        code, ty = range_val
        if ty is not None and ty[0] == "named":
            tmp = self.new_tmp(ty)
            self.line("%s = %s;" % (tmp, code))
            start = self.member_of(tmp, ty, "start", node)
            end = self.member_of(tmp, ty, "end", node)
            self._range = (tmp, ty)
            return (start, end)
        if ty is not None and ty[0] == "array":
            # "a fixed array satisfies Range intrinsically, and it is the one
            # place the compiler supplies what no module could have written"
            # -- `[T, N]` is a type constructor, so there is no
            # `[T, N].impl(..)` to write and no module for it to live in.
            tmp = self.new_tmp(ty)
            self.line("%s = %s;" % (tmp, code))
            self._range = (tmp, ty)
            return ("0", str(ty[1]))
        self._range = None
        self.e.error(node, "a loop needs a Range")
        return ("0", "0")

    def member_of(self, code, ty, name, node):
        info = self.e.struct_info(ty)
        if info:
            for fname, _fty in info[2]:
                if fname == name:
                    return "%s.%s" % (paren(code), sym_member(name))
        computed = self.computed_of(ty, name)
        if computed is not None:
            return self.read_computed(ty, code, computed)[0]
        self.e.error(node, "a Range needs `%s`" % name)
        return "0"

    def range_elem(self, range_val):
        """What a Range walks over, without lowering the walk."""
        if range_val is None:
            return None
        _code, ty = range_val
        if ty is None:
            return None
        if ty[0] == "array":
            return ty[2]
        if ty[0] != "named":
            return None
        at = [d for d in self.owned_decls(ty, "at", "fn")
              if self.e.fn_node(d.node) is not None
              and f(self.e.fn_node(d.node), "body") is not None]
        if not at:
            return prim("usize")   # it walks its own index space
        fnode = self.e.fn_node(at[0].node)
        mark = len(self.e.diags)
        got = self.e.resolve_type(self.e.ret_of(fnode),
                                  dict(zip(at[0].tparams, ty[2])),
                                  at[0].scope_parts, ty)
        del self.e.diags[mark:]
        info = self.e.enum_info(got) if got is not None and got[0] == "named" else None
        return dict(info[2]).get("Ok") if info else None

    def range_value(self, range_val, counter, node):
        """The element at the counter: `at` when the Range supplies one, and
        the index itself when it does not -- `Range(0, 5)` walks its own
        index space, which is what makes a fold a bare C for-loop."""
        if range_val is None or counter is None:
            return ("0", UNKNOWN)
        code, ty = range_val
        if ty is not None and ty[0] == "array":
            # its `at` is the bounds-checked index that already traps, and
            # the walk never leaves the range, so the check is the C index
            base = self._range[0] if self._range is not None else code
            return ("%s.%selems[%s]" % (paren(base), GEN, counter), ty[2])
        at = self.owned_decls(ty, "at", "fn") if ty is not None and ty[0] == "named" else []
        at = [d for d in at if f(self.e.fn_node(d.node), "body") is not None]
        if not at:
            # "a Range that supplies no `at` walks its own index space" --
            # which is what makes `Range(0, 5)` a bare C for-loop.
            return (counter, prim("usize"))
        got = self.emit_call(at[0], node, [(counter, prim("usize"))], (), None,
                             receiver=(code, ty))
        # `at` returns Res<T>: a None ends the walk early
        info = self.e.enum_info(got[1]) if got[1] is not None and got[1][0] == "named" else None
        if info is None:
            return got
        names = [v for v, _ in info[2]]
        ok = "Ok" if "Ok" in names else names[0]
        tmp = self.new_tmp(got[1])
        self.line("%s = %s;" % (tmp, got[0]))
        self.open("if (%s.%stag != %s) {" % (tmp, GEN, sym_variant(self.e.variant_parts(got[1], ok))))
        self.line("goto %s;" % self.loops[-1][0] if self.loops else "break;")
        self.close()
        return ("%s.%sdata.%s" % (tmp, GEN, sym_member(ok)), dict(info[2]).get(ok))

    def none_of(self, ty, node):
        if ty is None or ty[0] != "named":
            return "0"
        info = self.e.enum_info(ty)
        names = [v for v, p in info[2] if p is None] if info else []
        if "None" in names:
            return self.make_variant(ty, "None", None)
        return "(%s){0}" % self.e.ctype(ty)

    def ok_of(self, ty, code, node):
        if ty is None or ty[0] != "named":
            return code if code is not None else "0"
        info = self.e.enum_info(ty)
        names = [v for v, _ in info[2]] if info else []
        if "Ok" not in names:
            return code if code is not None else "0"
        return self.make_variant(ty, "Ok", code)

    def lower_handle(self, bound, name, argnodes, node):
        """`h.break(v)` / `h.break()` / `h.next()` -- the same jump `.try()`
        is, one frame down."""
        depth = bound[1][1]
        if depth < 1 or depth > len(self.loops):
            self.e.error(node, "`%s` outside its loop" % name)
            return ("0", UNIT)
        brk, cnt, result, ret, _acc, ddepth = self.loops[depth - 1]
        if name == "next":
            # `h.next()` leaves this iteration's block, so this iteration's
            # bindings die here rather than at the `}` the goto jumps over.
            self.unwind_to(ddepth)
            self.line("goto %s;" % cnt)
            return ("0", UNIT)
        if name == "break":
            code = None
            if argnodes and result is not None:
                payload_ty = None
                info = self.e.enum_info(ret) if ret is not None and ret[0] == "named" else None
                if info:
                    payload_ty = dict(info[2]).get("Ok")
                code, aty = self.expr(argnodes[0], payload_ty)
                self.line("%s = %s;" % (result, self.ok_of(ret, code, node)))
            self.unwind_to(ddepth, code)
            self.line("goto %s;" % brk)
            return ("0", UNIT)
        self.e.error(node, "LoopHandle has no `%s`" % name)
        return ("0", UNKNOWN)

    def lower_defer(self, rcode, name, argnodes, node):
        """`s.defer(() { .. })` -- push a closure onto that block's stack.

        The closure runs long after this frame is gone, so its captures are
        COPIED into the block's record here, at registration.  That is what
        "a closure registered on a scope keeps its captures in that scope's
        own storage" buys: the values are read where they are still alive.
        """
        if name != "defer":
            self.e.error(node, "`Scope` has no `%s`" % name)
            return ("0", UNKNOWN)
        if len(argnodes) != 1 or kind(argnodes[0]) != "Lambda":
            self.e.error(node, "`defer` takes a closure written at the call site")
            return ("0", UNIT)
        caps = self.captures(argnodes[0])
        thunk, env = self.e.defer_thunk(self, argnodes[0], caps, node)
        addr, size = "0", "0"
        if env is not None:
            tmp = self.label("cap")
            self.line("%s %s;" % (env, tmp))
            for i, (_name, code, _ty) in enumerate(caps):
                self.line("%s.%sc%d = %s;" % (tmp, GEN, i, code))
            addr, size = "&" + tmp, "sizeof %s" % tmp
        file, line, col = self.e.pos.of(node)
        self.line("%sdefer(%s, %s, %s, %s, %s, %d, %d);"
                  % (GEN, rcode, thunk, addr, size,
                     c_string(file.encode("utf-8")), line, col))
        return ("0", UNIT)

    def captures(self, lam):
        """The frame values a deferred closure reads, in source order.

        A name bound INSIDE the closure is not a capture; everything else it
        names that resolves in this frame is, and is copied.  Over-capturing
        costs a word in the record, under-capturing is a dangling read, so
        the doubtful cases go in.
        """
        bound = set()
        for n in zast.walk(lam):
            if kind(n) == "Lambda":
                for p in f(n, "params", ()) or ():
                    bound.add(str(f(p, "name", "_")))
            elif kind(n) == "PatVariant":
                binder = f(n, "binder")
                if isinstance(binder, str):
                    bound.add(binder)
        seen, out = set(), []
        for n in zast.walk(f(lam, "body")):
            if kind(n) != "Path":
                continue
            name = str(f(n, "name", ""))
            if name in bound or name in seen:
                continue
            got = self.find(name)
            if got is None:
                continue
            ty = got[1]
            if ty is None or ty in (UNIT, UNKNOWN) or ty[0] in ("lambda", "loop", "fn"):
                # a handle or an inlined closure names a frame that is going
                # away; there is nothing to copy and nothing to run later
                continue
            seen.add(name)
            out.append((name, got[0], ty))
        return out

    def infer_fn_targs(self, decl, fnode, values, receiver, owner_tys=()):
        params = list(self.e.params_of(fnode))
        found = dict(zip(decl.otparams, owner_tys))
        offset = 1 if receiver is not None else 0
        if receiver is not None and params:
            self.unify(f(params[0], "ty"), receiver[1], found, decl.tparams)
        for i, value in enumerate(values):
            idx = i + offset
            if idx >= len(params):
                break
            pty = f(params[idx], "ty")
            if not isinstance(value, tuple) and kind(value) == "Lambda" and pty is not None and kind(pty) == "FnType":
                for lp, dp in zip(f(value, "params", ()) or (), f(pty, "params", ()) or ()):
                    if f(lp, "ty") is not None:
                        self.unify(f(dp, "ty"), self.e.resolve_type(
                            f(lp, "ty"), self.subst, self.parts, self.self_ty),
                            found, decl.tparams)
                # "a closure passed to a function whose signature is already
                # known infers its parameter types from that signature", so
                # the body is peeked with them BOUND -- `map`'s `U` is the
                # body's value and the body says `value * 2`.
                self.push()
                for lp, dp in zip(f(value, "params", ()) or (), f(pty, "params", ()) or ()):
                    mark = len(self.e.diags)
                    lty = self.e.resolve_type(f(dp, "ty"), found, decl.scope_parts)
                    del self.e.diags[mark:]
                    if lty not in (None, UNKNOWN):
                        self.scopes[-1][str(f(lp, "name", "_"))] = ("0", lty)
                try:
                    _c, rty = self.peek(_block_value(f(value, "body")))
                finally:
                    self.pop()
                self.unify(f(pty, "ret"), rty, found, decl.tparams)
                continue
            _c, aty = self.peek(value)
            self.unify(pty, aty, found, decl.tparams)
        self.infer_from_bounds(decl, found)
        return tuple(found.get(tp, UNKNOWN)
                     for tp in decl.tparams[len(decl.otparams):])

    def infer_from_bounds(self, decl, found):
        """`<R: Range<T>, T>`: a parameter named ONLY inside another's bound.

        range.zen mandates that form for the whole loop family -- a bound
        monomorphises, so `at` is a direct call and the body inlines -- so
        this is the inference half of that claim rather than an edge case.
        The impl is where the answer is: `Vec.impl(Range<T>, ..)` says which
        of the receiver's own arguments the bound's argument is.
        """
        for tp in f(decl.node, "tparams", ()) or ():
            got = found.get(str(f(tp, "name", "")))
            if got in (None, UNKNOWN) or got[0] != "named":
                continue
            for bname, bargs in _bound_apps(tp):
                if not bargs:
                    continue
                if got[1][-1] == bname:
                    # the argument IS the bound: `Range(0, 10)` reaching
                    # `<R: Range<T>>`, where nothing else can name T
                    for i, arg in enumerate(bargs):
                        if arg is None or i >= len(got[2]):
                            continue
                        if found.get(arg, UNKNOWN) not in (None, UNKNOWN):
                            continue
                        el = got[2][i]
                        if el in (None, UNKNOWN):
                            # "a Range that supplies no `at` walks its own
                            # index space" -- which is what `range_value`
                            # lowers, so the inference has to say the same
                            at = [d for d in self.owned_decls(got, "at", "fn")
                                  if self.e.fn_node(d.node) is not None
                                  and f(self.e.fn_node(d.node), "body") is not None]
                            el = prim("usize") if not at else el
                        if el not in (None, UNKNOWN):
                            found[arg] = el
                    continue
                for target, trait, applied, owner_tps in self.e.impls:
                    if target != got[1][-1] or trait != bname:
                        continue
                    for i, written in enumerate(applied):
                        if i >= len(bargs) or bargs[i] is None:
                            continue
                        if found.get(bargs[i], UNKNOWN) not in (None, UNKNOWN):
                            continue
                        if written in owner_tps:
                            j = owner_tps.index(written)
                            if j < len(got[2]):
                                found[bargs[i]] = got[2][j]

    # print ---------------------------------------------------------------

    def lower_print(self, node, args, newline=True):
        """`println("a {} b", x)` -> typed writes, one call per piece.

        std owns `println` once it exists (DESIGN.md routes it through the
        `Env` in scope); until then this is the builtin that makes the corpus
        runnable.  `{}` on an integer prints decimal with no separators and
        `println` appends exactly one newline, per TESTING.md.
        """
        self.e.needs.add("print")
        argnodes = self.arg_nodes(args)
        if not argnodes:
            self.line("%sprint_nl();" % GEN)
            return ("0", UNIT)
        fmt_node = argnodes[0]
        rest = argnodes[1:]
        if kind(fmt_node) == "Literal" and f(fmt_node, "kind") == "str":
            raw = decode_str(str(f(fmt_node, "text", "")))
            pieces = raw.split(b"{}")
            for i, piece in enumerate(pieces):
                if piece:
                    self.line(
                        "%sprint_bytes(%s, %d);" % (GEN, c_string(piece), len(piece))
                    )
                if i < len(pieces) - 1:
                    if i < len(rest):
                        self.print_value(rest[i])
                    else:
                        self.line("%sprint_bytes(\"{}\", 2);" % GEN)
            for extra in rest[len(pieces) - 1 :]:
                self.print_value(extra)
        else:
            self.print_value(fmt_node)
            for extra in rest:
                self.print_value(extra)
        if newline:
            self.line("%sprint_nl();" % GEN)
        return ("0", UNIT)

    def print_value(self, node):
        code, ty = self.expr(node)
        if ty is not None and ty[0] == "prim":
            name = ty[1]
            if name == "bool":
                self.line("%sprint_bool(%s);" % (GEN, code))
                return
            if name in ("f32", "f64"):
                self.line("%sprint_f64((double)%s);" % (GEN, paren(code)))
                return
            if name in INT_VALUES:
                signed = INT_VALUES[name][0] < 0
                if signed:
                    self.line("%sprint_i64((int64_t)%s);" % (GEN, paren(code)))
                else:
                    self.line("%sprint_u64((uint64_t)%s);" % (GEN, paren(code)))
                return
            if name == "str":
                tmp = self.new_tmp(ty)
                self.line("%s = %s;" % (tmp, code))
                self.line(
                    "%sprint_bytes((const char *)%s.data, %s.len);" % (GEN, tmp, tmp)
                )
                return
        if ty is not None and ty[0] == "named":
            info = self.e.struct_info(ty)
            names = [n for n, _ in info[2]] if info else []
            if info and "data" in names and "len" in names:
                tmp = self.new_tmp(ty)
                self.line("%s = %s;" % (tmp, code))
                self.line(
                    "%sprint_bytes((const char *)%s.%s, (size_t)%s.%s);"
                    % (GEN, tmp, sym_member("data"), tmp, sym_member("len"))
                )
                return
            # a Display: `{}` routes through its toString, and the sink it is
            # handed is the CONSOLE, so printing a value allocates nothing.
            # This is the whole reason toString takes a Sink rather than a
            # String -- println has no Alloc to give it one
            if self.print_display(code, ty, node):
                return
        self.e.error(node, "cannot print a value of this type")

    def print_display(self, code, ty, node):
        """`println("{}", shape)` as the call it is: shape.toString(console)."""
        sink = self.console_sink()
        if sink is None:
            return False
        for d in self.owned_decls(ty, "toString", "fn"):
            fnode = self.e.fn_node(d.node)
            if fnode is None or f(fnode, "body") is None:
                continue
            if len(self.e.params_of(fnode)) != 2:
                continue
            got = self.emit_call(d, node, [sink], (), None, receiver=(code, ty))
            if got is not None:
                self.line("(void)(%s);" % got[0])
                return True
        return False

    def console_sink(self):
        """The console, as a Sink: a fat value over the print runtime.

        `println` holds a console and nothing else -- no Alloc, no buffer --
        so the sink it hands to `toString` has no receiver at all.  `self` is
        NULL because stdout is not a value the program owns; the two slots go
        straight to the writes `println` itself lowers into.  Nothing is
        allocated on this path, which is the property DESIGN.md's law 1 asks
        for and the reason the whole Sink migration exists.
        """
        decl = None
        for d in sorted(self.e.by_name.get("Sink", []), key=lambda d: d.parts):
            if d.dkind == "type":
                decl = d
                break
        if decl is None:
            return None
        ty = ("named", decl.parts, ())
        if not self.e.is_trait(ty):
            return None
        self.e.needs.add("print")
        inits = [".%sself = NULL" % GEN]
        for slot, name, _member, params, ret in self.e.trait_slots(ty):
            fn = self.e.console_thunk(name, slot, params, ret)
            if fn is None:
                return None
            inits.append(".%s = %s" % (slot, fn))
        return ("((%s){ %s })" % (self.e.ctype(ty), ", ".join(inits)), ty)

    # control flow --------------------------------------------------------

    def ex_Block(self, node, want=None):
        if want in (None, UNKNOWN):
            # A block's type is its tail expression's type, and the only way
            # to learn it is to RUN the block -- the tail reads bindings the
            # block itself declares, so inspecting the tail node in isolation
            # resolves nothing.  So lower speculatively, then lower again
            # with the answer as `want`.
            #
            # Without this a block has no type to report, and a `.match`
            # whose arms are ALL blocks therefore types as `()`: no result
            # temporary is allocated and every arm's value is dropped, with
            # no diagnostic and a zero in its place.
            found = self.peek_block(node)
            if found not in (None, UNIT, UNKNOWN):
                want = found
        result = None
        if want not in (None, UNIT, UNKNOWN):
            result = self.new_tmp(want)
        self.push()
        self.open()
        value = self.block_value(node, want)
        if result is not None and value is not None:
            self.line("%s = %s;" % (result, value))
        self.close()
        self.pop()
        return (result if result is not None else "0", want or UNIT)

    def ex_Match(self, node, want=None):
        scrut = f(node, "scrutinee")
        arms = list(f(node, "arms", ()) or ())
        scode, sty = self.expr(scrut)
        ty = want
        if ty in (None, UNKNOWN):
            ty = self.arm_type(arms, sty)
        result = None
        if ty not in (None, UNIT, UNKNOWN):
            result = self.new_tmp(ty)
        tmp = self.new_tmp(sty) if sty not in (None, UNIT, UNKNOWN) else None
        if tmp:
            self.line("%s = %s;" % (tmp, scode))
            scode = tmp

        if sty is not None and sty[0] == "prim" and sty[1] == "bool":
            self.match_bool(node, scode, arms, result, ty)
        elif sty is not None and sty[0] == "named" and self.e.enum_info(sty):
            self.match_enum(node, scode, sty, arms, result, ty)
        else:
            self.match_scalar(node, scode, sty, arms, result, ty)
        return (result if result is not None else "0", ty or UNIT)

    def arm_type(self, arms, sty=None):
        """The match's type, taken from the arm that carries the most
        information: a bare integer literal defaults to i32 and would make
        `(cap == 0).match({true => 8, false => cap * 2})` an i32 beside a
        usize, so an arm that is not a literal decides.

        Every arm is consulted, not just the first informative one.  Two arms
        are two ways of producing ONE value, so first-arm-wins is not a rule
        that can hold: `true => Ok(())` beside `false => report(n)` types the
        match `Res<()>`, and the second arm's `Res<(), AllocError>` then has
        nowhere to go -- it either fails in the C compiler or, in trailing
        position, is discarded."""
        fallback = None
        best = None
        for arm in arms:
            body = f(arm, "body")
            self.push()
            try:
                self.bind_arm(arm, sty)
                # a Block reports its type by being lowered; `peek` would reach
                # `ex_Block`, which lowers it a second time to find the same
                # answer
                if kind(body) == "Block":
                    ty = self.peek_block(body)
                else:
                    _code, ty = self.peek(body)
            finally:
                self.pop()
            if ty in (None, UNIT, UNKNOWN):
                continue
            if kind(body) == "Literal":
                fallback = fallback or ty
                continue
            best = ty if best is None else self.wider_arm(best, ty)
        return best or fallback or UNIT

    def bind_arm(self, arm, sty):
        """This arm's binder, in scope, before its body is looked at.

        `peek` "runs outside the scope the real lowering will run in", and an
        arm body reads exactly what that scope holds -- `Ok(d) => d.render(..)`
        is the whole of one. Without the binder the receiver has no type, and
        an untyped receiver used to be answered by searching the program for
        the NAME, which is how a `Vec` reached `Map.get`.

        Nothing is emitted: the codes are placeholders, because the only
        question here is the arm's TYPE.
        """
        if sty is None or sty[0] != "named":
            return
        info = self.e.enum_info(sty)
        if not info:
            return
        pat = f(arm, "pattern")
        if kind(pat) != "PatVariant":
            return
        mark = len(self.lines)
        conds, binds = [], []
        self.pat_conds("0", sty, pat, conds, binds)
        del self.lines[mark:]
        for name, bty, _code in binds:
            self.scopes[-1][name] = ("0", bty)

    def wider_arm(self, a, b):
        """Of two arm types, the one the match as a whole has.

        Only one widening exists and it is the one DESIGN.md already names:
        "the error type of a `Res` is a union, and propagation merges sets".
        A `Res` carrying an error set is wider than the same `Res` without
        one, and two error sets meet as their union.  Nothing else merges --
        two genuinely different arm types are a type error, reported where
        the arm is lowered rather than guessed at here."""
        if a == b:
            return a
        if not (a[0] == "named" and b[0] == "named" and a[1] == b[1]):
            return a
        if not (a[2] and b[2] and a[2][0] == b[2][0]):
            return a
        if len(a[2]) == 1 and len(b[2]) == 2:
            return b
        if len(b[2]) == 1 and len(a[2]) == 2:
            return a
        if len(a[2]) == 2 and len(b[2]) == 2:
            return ("named", a[1], (a[2][0], union_of([a[2][1], b[2][1]])))
        return a

    def arm_body(self, arm, result, ty):
        body = f(arm, "body")
        self.push()
        if kind(body) == "Block":
            value = self.block_value(body, ty)   # `_block_body` coerces its own tail
        else:
            value, vty = self.expr(body, ty)
            if vty == UNIT and ty not in (None, UNIT, UNKNOWN):
                # this arm produces NOTHING, and nothing does not coerce into
                # the match's type: `_ => println(..)` beside `Call(c) =>
                # c.args.loop(..)` is a match written in statement position for
                # its effects.  Run it; leave the result slot alone.
                if value and value not in ("", "0"):
                    self.line("(void)(%s);" % value)
                self.pop()
                return
            if value is not None:
                # an arm produces the MATCH's value, not its own: a `Res` whose
                # error set is narrower than the match's has to be widened here
                value = self.coerce(value, vty, ty)
        if result is not None and value is not None:
            self.line("%s = %s;" % (result, value))
        elif result is None and value and value not in ("", "0"):
            # an arm whose body is a call returning `()` still has to RUN
            self.line("(void)(%s);" % value)
        self.pop()

    def match_bool(self, node, scode, arms, result, ty):
        true_arm = false_arm = default = None
        for arm in arms:
            pat = f(arm, "pattern")
            pk = kind(pat)
            if pk == "PatWild":
                default = arm
            elif pk == "PatLit":
                text = str(f(pat, "text", "")).strip()
                if text == "true":
                    true_arm = arm
                elif text == "false":
                    false_arm = arm
            elif pk == "PatVariant":
                name = str(f(pat, "name", ""))
                if name == "true":
                    true_arm = arm
                elif name == "false":
                    false_arm = arm
        true_arm = true_arm or default
        false_arm = false_arm or default
        self.open("if (%s) {" % paren(scode))
        if true_arm is not None:
            self.arm_body(true_arm, result, ty)
        self.close("} else {")
        self.indent += 1
        if false_arm is not None:
            self.arm_body(false_arm, result, ty)
        self.close()

    def pat_conds(self, code, ty, pat, conds, binds):
        """What a pattern tests and what it binds, at any depth.

        `Left(Full(n))` is two tag tests and one binding, and the depth is
        not a special form: the same three shapes -- a name, a variant, a
        literal -- read the same way one level down.
        """
        if pat is None:
            return
        if isinstance(pat, str):
            # cst hands a bare payload name over as text.  It names a VARIANT
            # when the payload's type declares one and a binding otherwise --
            # `Left(Blank)` against `Left(cell)`.
            if pat == "_":
                return
            info = self.e.enum_info(ty) if ty is not None and ty[0] == "named" else None
            if info is not None and pat in dict(info[2]):
                conds.append("%s.%stag == %s" % (
                    paren(code), GEN, sym_variant(self.e.variant_parts(ty, pat))))
            elif ty is not None:
                binds.append((pat, ty, code))
            return
        k = kind(pat)
        if k == "PatWild":
            return
        if k == "PatLit":
            got = self.str_pat_cond(code, ty, pat)
            if got is not None:
                conds.append(got)
                return
            conds.append("%s == %s" % (paren(code), str(f(pat, "text", "0"))))
            return
        if k != "PatVariant":
            return
        info = self.e.enum_info(ty) if ty is not None and ty[0] == "named" else None
        vname = str(f(pat, "name", ""))
        if info is None or vname not in dict(info[2]):
            return
        conds.append("%s.%stag == %s" % (
            paren(code), GEN, sym_variant(self.e.variant_parts(ty, vname))))
        pty = dict(info[2]).get(vname)
        if pty is not None:
            self.pat_conds("%s.%sdata.%s" % (paren(code), GEN, sym_member(vname)),
                           pty, f(pat, "binder"), conds, binds)

    def str_pat_cond(self, code, ty, pat):
        """`s.match({ "i8" => .. })` where `s` is a `str`.

        A `str` is a struct, so the ordinary `==` this falls through to emitted
        `zg_str == "i8"` -- a struct against a `char *`, which is invalid C and
        was emitted SILENTLY. The backend written in Zen hit this and worked
        around it with nested calls rather than the match it wanted.

        Compared here the way `str.impl(Eq)` compares: the LENGTH first, then
        the bytes. Length first is not an optimisation, it is the correctness:
        comparing over the shorter length is the classic bug, and a prefix is
        not the whole.
        """
        if f(pat, "kind") != "str":
            return None
        want = self.str_type()
        if ty is None or ty != want:
            return None
        raw = decode_str(str(f(pat, "text", '""')))
        data, length, user = self.str_names()
        dname = sym_member(data) if user else "data"
        lname = sym_member(length) if user else "len"
        base = paren(code)
        if not raw:
            return "%s.%s == 0" % (base, lname)
        return "(%s.%s == %d && memcmp(%s.%s, %s, %d) == 0)" % (
            base, lname, len(raw), base, dname, c_string(raw), len(raw))

    def emit_arm(self, arm, pty, payload, result, ty):
        conds, binds = [], []
        self.pat_conds(payload, pty, f(f(arm, "pattern"), "binder"), conds, binds)
        return conds, binds

    def open_arm(self, binds, arm, result, ty):
        self.push()
        for name, bty, code in binds:
            self.line("%s = %s;" % (self.e.declarator(bty, self.declare(name, bty)),
                                    code))
        self.arm_body(arm, result, ty)
        self.pop()

    def match_enum(self, node, scode, sty, arms, result, ty):
        info = self.e.enum_info(sty)
        payloads = dict(info[2])
        # Arms group by the OUTER variant: `Left(Full(n))` and `Left(Blank)`
        # are two arms of one case, and two C `case` labels for one tag is
        # not legal C.  Everything below the tag is an if/else inside it.
        order, groups, wild = [], {}, []
        for arm in arms:
            pat = f(arm, "pattern")
            vname = str(f(pat, "name", "")) if kind(pat) == "PatVariant" else None
            if vname in payloads:
                if vname not in groups:
                    order.append(vname)
                    groups[vname] = []
                groups[vname].append(arm)
            else:
                wild.append(arm)
        self.open("switch (%s.%stag) {" % (paren(scode), GEN))
        for vname in order:
            self.line("case %s: {" % sym_variant(self.e.variant_parts(sty, vname)))
            self.indent += 1
            pty = payloads.get(vname)
            payload = ("%s.%sdata.%s" % (paren(scode), GEN, sym_member(vname))
                       if pty is not None else None)
            shaped = [(arm,) + self.emit_arm(arm, pty, payload, result, ty)
                      for arm in groups[vname]]
            plain = [s for s in shaped if not s[1]]
            if len(shaped) == 1 and plain:
                self.open_arm(shaped[0][2], shaped[0][0], result, ty)
            else:
                first, closed = True, False
                for arm, conds, binds in shaped:
                    if not conds:
                        if first:
                            self.open("{")
                        else:
                            self.close("} else {")
                            self.indent += 1
                        self.open_arm(binds, arm, result, ty)
                        first, closed = False, True
                        break
                    head = " && ".join(conds)
                    if first:
                        self.open("if (%s) {" % head)
                    else:
                        self.close("} else if (%s) {" % head)
                        self.indent += 1
                    self.open_arm(binds, arm, result, ty)
                    first, closed = False, True
                if closed and not plain and wild:
                    self.close("} else {")
                    self.indent += 1
                    self.open_arm([], wild[0], result, ty)
                if closed:
                    self.close()
            self.line("break;")
            self.indent -= 1
            self.line("}")
        if wild:
            self.line("default: {")
            self.indent += 1
            self.open_arm([], wild[0], result, ty)
            self.line("break;")
            self.indent -= 1
            self.line("}")
        else:
            file, line, col = self.e.pos.of(node)
            self.line(
                "default: %sunreachable(%s, %d, %d);"
                % (GEN, c_string(file.encode("utf-8")), line, col)
            )
        self.close()

    def match_scalar(self, node, scode, sty, arms, result, ty):
        first = True
        for arm in arms:
            pat = f(arm, "pattern")
            pk = kind(pat)
            if pk == "PatWild":
                if first:
                    self.open("{")
                else:
                    self.close("} else {")
                    self.indent += 1
            else:
                cond = self.str_pat_cond(scode, sty, pat)
                if cond is None:
                    text = str(f(pat, "text", f(pat, "name", "0")))
                    cond = "%s == %s" % (paren(scode), text)
                if first:
                    self.open("if (%s) {" % cond)
                else:
                    self.close("} else if (%s) {" % cond)
                    self.indent += 1
            self.arm_body(arm, result, ty)
            first = False
        if not first:
            self.close()

    def ex_Try(self, node, want=None):
        """`.try()` -- unwrap Ok, or return the Err/None from this function."""
        operand = f(node, "operand")
        code, ty = self.expr(operand)
        info = self.e.enum_info(ty) if ty is not None and ty[0] == "named" else None
        if info is None:
            self.e.error(node, "`.try()` needs a Res value")
            return (code, ty)
        variants = info[2]
        names = [v for v, _ in variants]
        ok = "Ok" if "Ok" in names else names[0]
        payload = dict(variants).get(ok)
        tmp = self.new_tmp(ty)
        self.line("%s = %s;" % (tmp, code))
        self.open(
            "if (%s.%stag != %s) {"
            % (tmp, GEN, sym_variant(self.e.variant_parts(ty, ok)))
        )
        self.emit_propagate(node, tmp, ty, ok)
        self.close()
        if payload is None:
            return ("0", UNIT)
        return ("%s.%sdata.%s" % (tmp, GEN, sym_member(ok)), payload)

    def emit_propagate(self, node, tmp, ty, ok):
        """Rebuild this function's error variant from the operand's."""
        # "every early exit is a scope exit."  `.try()` is the common one, and
        # the error is carried in `tmp`, which is a temporary and never
        # dropped -- so the whole frame can unwind before the return is built.
        self.unwind_to(0)
        ret = self.ret
        rinfo = self.e.enum_info(ret) if ret is not None and ret[0] == "named" else None
        if rinfo is None:
            self.e.error(node, "`.try()` requires the enclosing function to return a Res")
            self.line("return;" if self.ret == UNIT else "return (%s){0};" % self.e.ctype(self.ret))
            return
        rnames = [v for v, _ in rinfo[2]]
        rpayloads = dict(rinfo[2])
        source = [v for v, _ in self.e.enum_info(ty)[2] if v != ok]
        target = next((v for v in ("Err", "None") if v in rnames and v in source), None)
        if target is None:
            target = next((v for v in rnames if v != ok), None)
        if target is None:
            self.line("return (%s){0};" % self.e.ctype(ret))
            return
        pty = rpayloads.get(target)
        if pty is None:
            self.line("return %s;" % self.make_variant(ret, target, None))
            return
        src = "%s.%sdata.%s" % (tmp, GEN, sym_member(target))
        sty = dict(self.e.enum_info(ty)[2]).get(target)
        got = self.widen_error(src, sty, pty)
        if got is None:
            # "There is no `From`, and no implicit error conversion."  The set
            # this function declares does not contain what the operand raises,
            # and inventing the conversion here would be the compiler deciding
            # an error's identity.  Widen the declared set instead.
            self.e.error(node, "no implicit error conversion: this error is not "
                               "part of the set this function returns -- widen the "
                               "declared set, there is no From")
            got = "(%s){0}" % self.e.ctype(pty)
        self.line("return %s;" % self.make_variant(ret, target, got))

    # -- error sets ---------------------------------------------------------
    #
    # "The error type of a `Res` is a union, and propagation merges sets."
    # Widening is the only move: every member of the operand's set has to be a
    # member of this function's, and it keeps its own name on the way in.
    # Nothing here converts, and nothing here invents a reason -- when a member
    # has no home in the wider set the answer is None and the caller reports.

    def widen_error(self, code, sty, pty, seen=()):
        if sty is None or pty is None or sty == pty \
                or UNKNOWN in (sty, pty):
            return code
        if pty[0] == "union":
            members = pty[1]
            if sty in members:
                return self.into_union(code, sty, pty)
            if sty[0] == "union" and all(m in members for m in sty[1]):
                return self.per_member(code, sty,
                                       lambda m, v: self.into_union(v, m, pty))
            if sty[0] == "named":
                return self.spread_set(code, sty, pty, seen)
            return None
        if pty[0] == "named":
            info = self.e.enum_info(pty)
            if info is None:
                return None
            variants = dict(info[2])
            if sty[0] == "named":
                # `WriteError = IoError | AllocError` is an enum whose variants
                # ARE the member types, so an AllocError selects the variant of
                # that name.  Only the wider set naming the narrower.
                name = sty[1][-1]
                if name in variants and variants[name] in (None, sty):
                    return self.make_variant(
                        pty, name, code if variants[name] is not None else None)
                return self.spread_set(code, sty, pty, seen)
            if sty[0] == "union" and all(
                    m[0] == "named" and variants.get(m[1][-1], m) == m
                    for m in sty[1]):
                return self.per_member(
                    code, sty,
                    lambda m, v: self.make_variant(
                        pty, m[1][-1],
                        v if variants[m[1][-1]] is not None else None))
        return None

    def spread_set(self, code, sty, pty, seen):
        """A NAMED set widened into `pty`, one arm per member, on its tag.

        `WriteError = IoError | AllocError` and `IoError | AllocError` are the
        same two variants under two spellings, and an `IoError` arriving
        through either is the same `IoError`: the merge renames nothing and
        carries every value across whole.  Each member is then widened in its
        own right, so a set of sets terminates at the members that are not
        sets.  This applies only to a "union of existing types", never to an
        ordinary enum that happens to share variant names, which is what
        `error_set_members` checks.

        The order is the declaration's, so this is a pure function of the two
        types.  `seen` is what stops `A = B | X` and `B = A | Y` from
        descending forever; a set that contains itself has no finite value
        anyway, and the answer here is the same None a stranger gets.
        """
        if self.e.error_set_members(sty) is None or sty[1] in seen:
            return None
        seen = seen + (sty[1],)
        out = None
        for vname, spay in reversed(self.e.enum_info(sty)[2]):
            if spay is None:
                return None    # a member the set did not keep
            got = self.widen_error(
                "%s.%sdata.%s" % (paren(code), GEN, sym_member(vname)),
                spay, pty, seen)
            if got is None:
                return None
            out = got if out is None else "(%s.%stag == %s ? %s : %s)" % (
                paren(code), GEN,
                sym_variant(self.e.variant_parts(sty, vname)), got, out)
        return out

    def into_union(self, code, member, uty):
        return "((%s){ .%stag = %stag%s, .%sdata = { .%s = %s } })" % (
            self.e.ctype(uty), GEN, GEN, tcode(member), GEN,
            GEN + "m" + tcode(member), code)

    def per_member(self, code, sty, build):
        """One arm per member of the source set, selected on its tag.  The
        member order is the union's own, which `union_of` sorted, so this is a
        pure function of the two types."""
        out = None
        for m in reversed(sty[1]):
            built = build(m, "%s.%sdata.%s" % (paren(code), GEN,
                                               GEN + "m" + tcode(m)))
            out = built if out is None else "(%s.%stag == %stag%s ? %s : %s)" % (
                paren(code), GEN, GEN, tcode(m), built, out)
        return out

    def ex_Lambda(self, node, want=None):
        """A closure in value position.

        A closure passed to a call is inlined at the call site and never
        reaches here; one that gets this far would have to outlive the frame
        it captured, which is an escaping closure -- and an escaping closure
        needs an `Alloc` and is stage 3's checker's business.
        """
        self.e.error(node, "a closure here would have to escape its frame; "
                           "an escaping closure needs an Alloc (DESIGN.md)")
        return ("0", UNKNOWN)

    def ex_FixedArray(self, node, want=None):
        ty = self.e.resolve_type(f(node, "ty"), self.subst, self.parts, self.self_ty)
        elems = list(f(node, "elems", ()) or ())
        codes = [self.expr(e, ty[2] if ty[0] == "array" else None)[0] for e in elems]
        cname = self.e.ctype(ty)
        return ("((%s){ { %s } })" % (cname, ", ".join(codes) or "0"), ty)

    def ex_ArrayLit(self, node, want=None):
        elems = list(f(node, "elems", ()) or ())
        elem_ty = want[2] if want is not None and want[0] == "array" else None
        codes = []
        for e in elems:
            code, ety = self.expr(e, elem_ty)
            elem_ty = elem_ty or ety
            codes.append(code)
        ty = ("array", len(elems), elem_ty or prim("i32"))
        cname = self.e.ctype(ty)
        return ("((%s){ { %s } })" % (cname, ", ".join(codes) or "0"), ty)

    def ex_Record(self, node, want=None):
        # `{ src: .., deps: .. }` is a build-file literal: its type comes from
        # the parameter it is passed to, which is std.build's business.
        self.e.error(node, "a record literal has no type here")
        return ("0", UNKNOWN)

    def ex_ScopeRef(self, node, want=None):
        rec = self.sscopes[-1] if self.sscopes else None
        if rec is None:  # pragma: no cover - scope_record scans for this node
            self.e.error(node, "`@scope` has no enclosing block here")
            return ("0", UNKNOWN)
        return ("&" + rec, self.e.scope_type())

    def ex_MetaCall(self, node, want=None):
        self.e.error(node, "`@meta` is not in the seed subset (PLAN.md 0.5)")
        return ("0", UNKNOWN)



def is_loop_shape(emitter, fnode):
    """A bodyless function whose last parameter is a body taking a LoopHandle.

    `loop_iter.zen` declares six signatures and no definitions on purpose --
    "a loop is the one thing that cannot be written in a language whose only
    control flow is .match, .loop and recursion" -- so the compiler lowers
    them.  This recognises them by SHAPE rather than by module and name, so
    the six overloads and anything else built the same way are one case.
    """
    params = emitter.params_of(fnode)
    if not params:
        return False
    ty = f(params[-1], "ty")
    if ty is None or kind(ty) != "FnType":
        return False
    inner = f(ty, "params", ()) or ()
    if not inner:
        return False
    first = f(inner[0], "ty")
    return first is not None and kind(first) == "Named" and f(first, "name") == "LoopHandle"


def erase(ty):
    """A generic member gets ONE slot, with its type parameters erased.

    `realloc*<T> = (self: @Self, p: Ptr<T>, count: usize) Res<Ptr<T>, E>` is
    three of Alloc's four members' shape, and a record cannot carry a slot per
    instantiation without its layout becoming a function of the program.  So a
    pointer erases to `Ptr<u8>` and a Res carrying one erases with it -- the
    same trade Zig's `std.mem.Allocator` makes.  The value is REBUILT on the
    way in and out, never reinterpreted, so nothing here depends on two
    pointer types sharing a representation.
    """
    if ty is None:
        return ty
    if ty[0] == "ptr":
        return ("ptr", prim("u8"))
    if ty[0] == "named" and ty[2]:
        return ("named", ty[1], tuple(erase(a) for a in ty[2]))
    return ty


def refine(ty, want):
    """Fill a type's unresolved arguments in from what the call site expected.

    `then<T>` gets its T from the closure it was handed; when the closure's
    body says nothing, the expected type does.  Only holes are filled -- a
    known type is never overwritten by an expectation.
    """
    if want in (None, UNKNOWN):
        return ty
    if ty in (None, UNKNOWN):
        return want
    if ty[0] == "named" and want[0] == "named" and ty[1] == want[1] \
            and len(ty[2]) == len(want[2]):
        return ("named", ty[1],
                tuple(w if a == UNKNOWN else a for a, w in zip(ty[2], want[2])))
    return ty


def is_handle(ty):
    return ty is not None and ty[0] == "loop"


def _writes_scope(node):
    """Does `@scope` in this subtree mean THIS block?

    A nested block and a lambda body are blocks of their own, so the search
    stops at each -- which is the whole of "it nests, and each block gets its
    own", and the reason the inner example's defers run at the inner brace.
    """
    for child in zast.children(node):
        if kind(child) == "ScopeRef":
            return True
        if kind(child) in ("Block", "Lambda"):
            continue
        if _writes_scope(child):
            return True
    return False

