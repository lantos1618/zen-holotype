def paren(code):
    if code.isidentifier() or (code.startswith("(") and code.endswith(")")):
        return code
    return "(" + code + ")"


def parse_int(text):
    text = str(text).strip().replace("_", "")
    if not text:
        return 0
    try:
        if text[:2].lower() == "0x":
            return int(text, 16)
        if text[:2].lower() == "0b":
            return int(text, 2)
        if text[:2].lower() == "0o":
            return int(text, 8)
        return int(text, 10)
    except ValueError:
        return 0


def int_literal(value, ty):
    """A C constant that means exactly `value` at exactly `ty`'s width.

    There is no negative literal in C: `-2147483648` is unary minus applied to
    a constant that does not fit an `int`, so the negation happens in a wider
    type.  <stdint.h> spells INT32_MIN `(-2147483647 - 1)`, and so does this.
    Unsigned constants always carry `ULL` -- suffixing by magnitude is exactly
    the bug, because `1` is an `int` and promotes as one.
    """
    name = ty[1] if ty and ty[0] == "prim" else "i32"
    ctype = PRIMS.get(name, "int32_t")
    if name not in INT_VALUES:
        return str(value)
    lo, hi, _bits = INT_VALUES[name]
    signed = lo < 0
    if not signed:
        return "((%s)%dULL)" % (ctype, value & hi)
    if value == lo:
        return "((%s)(-%dLL - 1LL))" % (ctype, -(lo + 1))
    return "((%s)%dLL)" % (ctype, value)


def float_literal(text):
    text = str(text).strip()
    if not text:
        return "0.0"
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text


_ESCAPES = {
    "n": b"\n",
    "t": b"\t",
    "r": b"\r",
    "0": b"\0",
    "\\": b"\\",
    "'": b"'",
    '"': b'"',
}


def decode_str(text):
    """Source text of a string literal -> its bytes."""
    s = str(text)
    if len(s) >= 2 and s[0] == '"' and s[-1] == '"':
        s = s[1:-1]
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            nxt = s[i + 1]
            if nxt in _ESCAPES:
                out += _ESCAPES[nxt]
                i += 2
                continue
            if nxt == "x" and i + 3 < len(s):
                try:
                    out.append(int(s[i + 2 : i + 4], 16))
                    i += 4
                    continue
                except ValueError:
                    pass
            out += nxt.encode("utf-8")
            i += 2
            continue
        out += c.encode("utf-8")
        i += 1
    return bytes(out)


def decode_char(text):
    s = str(text)
    if len(s) >= 2 and s[0] == "'" and s[-1] == "'":
        s = s[1:-1]
    raw = decode_str('"%s"' % s)
    return raw[0] if raw else 0


def c_string(raw: bytes) -> str:
    """A C string literal.  Octal escapes, so an escape never runs on into the
    next character the way `\\xNN` does, and no hex is emitted at all -- which
    also keeps the determinism scanner's pointer-shaped-hex check quiet."""
    out = ['"']
    for b in raw:
        ch = chr(b)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= b < 127:
            out.append(ch)
        else:
            out.append("\\%03o" % b)
    out.append('"')
    return "".join(out)


